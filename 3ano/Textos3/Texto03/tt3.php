            <h2> Por que as pessoas migram?</h2>

            <div class="w3-margin"><img id="imagem3" src="tt03f06.png" alt="tt03f06" class="w3-mobile">

                <span class="w3-small w3-margin-left" id="citacao3"> Fonte:

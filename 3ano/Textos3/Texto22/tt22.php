        <p>A América Central é uma região situada entre a América do Norte e a América do Sul, composta por sete países:
            Belize, Guatemala, Honduras, El Salvador, Nicarágua, Costa Rica e Panamá. Geograficamente, a região é
            caracterizada por cadeias montanhosas que se estendem ao longo de sua extensão, além de vulcões ativos e uma
            rica biodiversidade.</p>

        <p>A América do Sul, por sua vez, é dividida em várias sub-regiões, incluindo os Países Andinos e o Cone Sul,
            onde se destaca o Mercosul, um importante bloco econômico. Ambas as regiões têm uma grande importância
            geopolítica devido à riqueza em recursos naturais, como petróleo, minérios e biodiversidade.</p>

        <p>Além disso, a América Central possui uma relevância estratégica por sua proximidade ao <span class="termo" data-palavra="Canal do Panamá" data-definicao="Canal artificial que conecta os oceanos Atlântico e Pacífico através do istmo do Panamá, uma das rotas comerciais marítimas mais importantes do mundo. Construído pelos Estados Unidos e devolvido ao controle panamenho em 1999.">Canal do Panamá</span>, uma
            das rotas comerciais mais importantes do mundo. Concluída em 1914, a obra interligou os oceanos Atlântico e
            Pacífico através do istmo centro-americano e, ao encurtar drasticamente o trajeto entre as duas costas dos
            Estados Unidos, tornou-se depois a principal via de circulação entre a Europa e os países do Pacífico. Essa
            importância voltou ao centro do debate internacional
            a partir de 2025, quando o presidente estadunidense Donald Trump passou a ameaçar "retomar" o controle do
            canal, alegando que a China exercia influência indevida sobre a via por meio da operação de dois portos
            do canal por uma empresa de Hong Kong. Em meio à pressão, Panamá e Estados Unidos assinaram acordos de
            segurança que permitem tropas estadunidenses realizarem exercícios militares em território panamenho por
            três anos, e a Suprema Corte do Panamá declarou inconstitucionais os contratos que davam à empresa chinesa
            o controle dos portos do canal, episódio que mostra como a geografia estratégica da América Central segue
            atraindo a disputa entre grandes potências.</p>


        <h2>5. Questão Cubana</h2>

        <div class="w3-margin"><img id="imagem5" src="tt22f05.png" alt="Blindado avançando por rua de cidade cubana durante a Revolução Cubana, com população nas calçadas - Duvid Geografia" class="w3-mobile" >

			<span class="w3-small w3-margin-left" id="citacao5" > </span>
		   </div>

        <p>Cuba ocupa um lugar único na história e na geopolítica da América Latina. A <span class="termo" data-palavra="Revolução Cubana" data-definicao="Movimento revolucionário liderado por Fidel Castro que derrubou o governo de Fulgencio Batista em 1º de janeiro de 1959, instaurando um governo socialista em Cuba e rompendo com a influência histórica dos Estados Unidos sobre a ilha.">Revolução Cubana</span> de 1959, liderada por Fidel Castro, transformou radicalmente o país, estabelecendo um governo socialista que desafiou a hegemonia dos Estados Unidos na região. Antes da revolução, Cuba era amplamente influenciada pelos interesses econômicos e políticos dos EUA, com uma economia baseada no turismo, no açúcar e em outras exportações. A revolução, no entanto, trouxe profundas mudanças sociais e econômicas, incluindo a nacionalização de indústrias, a reforma agrária e o estabelecimento de um sistema de saúde e educação gratuitos.</p>

        <p>Um dos eventos mais marcantes da história recente de Cuba foi o <span class="termo" data-palavra="Embargo dos EUA a Cuba" data-definicao="Conjunto de sanções econômicas, comerciais e financeiras impostas por Washington a Cuba a partir de 1962, em resposta à aliança do país com a União Soviética e à nacionalização de propriedades estadunidenses. Segue em vigor e foi endurecido em 2025-2026.">embargo econômico</span> imposto pelos Estados Unidos em 1962, que continua em vigor até hoje. O embargo foi uma resposta direta à aliança de Cuba com a União Soviética durante a Guerra Fria e à expropriação de propriedades americanas na ilha. Esse bloqueio econômico teve um impacto devastador na economia cubana, limitando o acesso a produtos básicos, tecnologia e mercados internacionais.</p>

        <p>Desde o início de seu segundo mandato, em janeiro de 2025, o presidente Donald Trump voltou a colocar Cuba entre as prioridades da política externa dos EUA para a América Latina, combinando novas sanções econômicas e financeiras, restrições a viagens e pressão sobre o setor energético cubano. Em janeiro de 2026, uma ordem executiva classificou Cuba como uma "ameaça incomum e extraordinária" à segurança estadunidense e passou a permitir tarifas adicionais contra qualquer país que forneça petróleo à ilha, agravando uma crise de combustíveis que já afetava o abastecimento de alimentos, água e hospitais no país. Em outubro de 2025, pela trigésima terceira vez consecutiva, a Assembleia Geral da ONU votou, por larga maioria, pelo fim do embargo, uma posição que os Estados Unidos seguem rejeitando. Apesar dessas dificuldades, o governo cubano conseguiu manter seu sistema socialista e implementar políticas sociais que continuam a ser um marco distintivo do país.</p>
    
        <p>Cuba se destaca como uma exceção na América Latina por sua adesão ao socialismo em uma região predominantemente composta por economias de mercado. Enquanto a maioria dos países latino-americanos adotou políticas neoliberais nas últimas décadas, Cuba permaneceu firme em seu modelo econômico e político, com um controle centralizado e uma economia planificada. Isso resultou em um desenvolvimento econômico diferente, com avanços notáveis em áreas como a saúde e a educação, mas também com limitações significativas em termos de crescimento econômico e inovação tecnológica.</p>

        <p>Entre as fontes de divisas mais importantes para a economia cubana estão o turismo internacional e as
            remessas enviadas por cubanos que vivem no exterior, sobretudo nos Estados Unidos, que ajudam milhões de
            famílias na ilha a driblar a escassez de produtos básicos agravada pelo embargo. Em 2021, o governo cubano
            promoveu uma reforma monetária que unificou o peso cubano com o antigo peso conversível, numa tentativa de
            simplificar um sistema de dupla moeda que distorcia preços e salários havia décadas. A reforma, no
            entanto, veio acompanhada de forte inflação, o que aprofundou as dificuldades econômicas da população
            cubana justamente no momento em que o endurecimento do embargo, a partir de 2025, voltou a restringir o
            acesso do país a combustíveis e insumos básicos.</p>
    
        <p>A posição única de Cuba também gerou impactos regionais significativos. As relações de Cuba com os Estados Unidos têm sido historicamente tensas, culminando na Crise dos Mísseis de 1962, que quase levou a um conflito nuclear. No entanto, Cuba também recebeu apoio de outros países latino-americanos, especialmente em fóruns internacionais como a ONU, onde a maioria das nações da região condena o embargo americano e apoia o direito de Cuba à autodeterminação. Apesar das dificuldades econômicas, Cuba continua a exercer uma influência cultural e política desproporcional ao seu tamanho, sendo um símbolo de resistência e soberania na América Latina. Na próxima aula, vamos aprofundar a situação política atual de Cuba, além dos casos da Venezuela e da Bolívia.</p>
    

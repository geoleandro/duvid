        <h2>2. Características Físicas</h2>

        <div class="w3-margin"><img id="imagem2" src="tt22f02.png" alt="Mapa físico da América do Sul e da América Central - Duvid Geografia" class="w3-mobile">
            <span class="w3-small w3-margin-left" id="citacao2">  </span>
        </div>
	   

        <p>A América Central e do Sul são regiões com uma diversidade física impressionante, que vai desde altas
            montanhas até florestas densas. O relevo é uma das características mais marcantes, com a presença dominante
            das cadeias montanhosas, especialmente os <span class="termo" data-palavra="Cordilheira dos Andes" data-definicao="Cadeia de montanhas que se estende por cerca de 7.000 km ao longo de toda a costa oeste da América do Sul, atravessando sete países. É a cadeia montanhosa mais extensa do mundo emersa acima do nível do mar.">Andes</span>. Esta cordilheira, que se estende por aproximadamente 7.000
            km ao longo da costa oeste da América do Sul, é a mais extensa do mundo e atinge alturas superiores a 6.900
            metros, no Monte Aconcágua, na Argentina.</p>

        <p>Além dos Andes, a região abriga vastas áreas de florestas tropicais, como a Amazônia, a maior floresta
            tropical do mundo, que cobre partes de nove países sul-americanos. Essas florestas são não apenas cruciais
            para a biodiversidade global, mas também desempenham um papel vital na regulação do clima da Terra.</p>

        <p><strong>Fato Interessante:</strong> A Bacia Amazônica é cortada pelo Rio Amazonas, o maior rio do mundo em
            volume de água, responsável por cerca de 20% de toda a água doce despejada nos oceanos do planeta. A
            floresta amazônica também armazena bilhões de toneladas de carbono, o que faz de sua preservação um tema
            central nas discussões internacionais sobre mudanças climáticas.</p>

        <p>Em termos de clima, a América Central e do Sul oferecem uma grande variedade. O clima equatorial predomina na
            Amazônia, onde as chuvas são abundantes durante todo o ano, sustentando a densa vegetação tropical. Em
            contraste, o <span class="termo" data-palavra="Deserto do Atacama" data-definicao="Deserto localizado no norte do Chile, considerado um dos lugares mais secos do planeta, com áreas onde não há registro de chuva há décadas ou mesmo séculos.">Deserto do Atacama</span>, no Chile, é um dos lugares mais secos do planeta, com algumas áreas que não
            recebem chuvas há séculos.</p>

        <p>As savanas, como o <span class="termo" data-palavra="Cerrado" data-definicao="Bioma de savana tropical característico do Brasil central, com vegetação de árvores baixas e retorcidas, estações de seca e chuva bem definidas, e uma das maiores biodiversidades entre as savanas do mundo.">Cerrado</span> no Brasil, também fazem parte do mosaico climático da região, caracterizadas por
            estações de chuva e seca bem definidas. Este bioma é uma das savanas mais ricas em biodiversidade do mundo,
            abrigando milhares de espécies de plantas e animais.</p>

        <p>Essa combinação de relevo variado e climas diversos torna a América Central e do Sul uma região de grande
            importância ecológica e geográfica, além de ser um verdadeiro tesouro natural que continua a fascinar
            cientistas e viajantes de todo o mundo.</p>



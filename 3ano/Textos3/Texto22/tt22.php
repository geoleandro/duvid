        <h2>3. Colonização</h2>

        <div class="w3-margin"><img id="imagem3" src="tt22f03.png" alt="Mapa político da América Central e das Ilhas do Caribe - Duvid Geografia" class="w3-mobile" >

            <span class="w3-small w3-margin-left" id="citacao3" >  </span>
            
            </div>
    
        <p>A história da América Central e do Sul é marcada por um longo período de colonização europeia, que moldou profundamente a cultura, a religião e as línguas dessas regiões. Os colonizadores, principalmente espanhóis e portugueses, chegaram ao Novo Mundo no final do século XV, atraídos pela promessa de riquezas e novas terras. A influência europeia é evidente até hoje, com o espanhol e o português sendo as línguas predominantes, e o cristianismo, especialmente o catolicismo, profundamente enraizado na vida social e cultural.</p>

        <p>Antes da chegada dos europeus, porém, o continente já era densamente povoado: estima-se que, no século XV,
            viviam ali cerca de 50 milhões de pessoas de diferentes culturas e etnias. Alguns povos pré-colombianos
            formaram verdadeiros impérios urbanos, com organização econômica voltada à agricultura e ao comércio. Os
            maias e os astecas ocuparam a chamada Mesoamérica (região que hoje corresponde a Costa Rica, Nicarágua,
            Honduras, El Salvador, Belize, Guatemala e o centro-sul do México), enquanto os incas construíram seu
            império ao longo da Cordilheira dos Andes, na área hoje ocupada por Peru, Equador, Bolívia e Chile. Esse
            legado indígena não desapareceu: estima-se que, hoje, cerca de 30 milhões de indígenas distribuídos em
            mais de 670 grupos étnico-culturais vivam na América Latina, com destaque para países como México, Peru,
            Guatemala e Bolívia, onde o percentual da população de origem indígena é particularmente elevado.</p>

        <p>A colonização não foi um processo pacífico. Pelo contrário, foi marcada pela exploração intensa dos recursos naturais e pela subjugação das populações indígenas. Ouro, prata e outros recursos foram extraídos em grandes quantidades e enviados para a Europa, enriquecendo as metrópoles coloniais à custa das economias locais e das vidas de milhões de pessoas.</p>

        <p>Espanha e Portugal adotaram modelos de colonização distintos. A Coroa espanhola organizou seu império americano em vice-reinos administrados de perto por Madri, com cidades planejadas ao redor de minas de prata e ouro, como Potosí, no atual território boliviano, uma das maiores minas de prata da história. Para explorar a mão de obra indígena, os espanhóis criaram o sistema de <span class="termo" data-palavra="Encomienda" data-definicao="Sistema de trabalho forçado imposto pela colonização espanhola na América, no qual um colono recebia o direito de explorar o trabalho de um grupo de indígenas em troca da suposta obrigação de catequizá-los e protegê-los.">encomienda</span>, no qual um colono recebia o direito de explorar o trabalho de grupos indígenas em troca da promessa de catequizá-los e protegê-los, uma promessa raramente cumprida na prática. Já Portugal, com menos recursos para administrar diretamente sua colônia, adotou inicialmente o sistema de capitanias hereditárias, concedendo grandes faixas de terra a particulares que assumiam os custos e os riscos da colonização em troca de amplos poderes administrativos.</p>

        <p>Um aspecto sombrio dessa era foi o uso massivo de mão de obra escrava africana. Os primeiros africanos escravizados chegaram ao continente americano em 1502, na Ilha de São Domingos, que corresponde ao atual território do Haiti e da República Dominicana, no Mar do Caribe. Dali, o tráfico se espalhou por toda a região: os escravizados foram forçados a trabalhar nas plantações de cana-de-açúcar do Brasil e das Antilhas, nas lavouras de cacau e café da Venezuela e nas plantações de café, algodão e tabaco da Colômbia. Milhões de africanos atravessaram o Atlântico em condições desumanas, e os grupos afro-latinos resultantes desse processo compartilham uma história de escravização, de inserção desigual no modelo colonial e de luta por liberdade, como na formação de quilombos, contribuindo para a formação de sociedades profundamente desiguais.</p>
    
        <p>Mesmo após a independência dos países da América Central e do Sul, muitas das estruturas de poder e desigualdades sociais estabelecidas durante a colonização persistiram. As elites coloniais mantiveram seu poder e influência, enquanto a maioria da população continuou a enfrentar desafios relacionados à pobreza e à falta de acesso a oportunidades. Este legado colonial ainda é evidente hoje, influenciando a dinâmica social, econômica e política da região.</p>
    

        <h2>6. Economia da Região</h2>

        <div class="w3-margin"><img id="imagem6" src="tt22f06.png" alt="Gráfico do PIB per capita dos países da América Latina - Duvid Geografia" class="w3-mobile" >

            <span class="w3-small w3-margin-left" id="citacao6" >Fonte: Austin Rating, dados de 2021. </span>

            </div>

        <p>A economia da América Latina é marcada por uma forte dependência da exportação de commodities, o que desempenha um papel crucial na estabilidade e no crescimento econômico de muitos países da região. Produtos como petróleo, café, minérios e soja são os principais motores das exportações, gerando receitas vitais para os governos locais. No entanto, essa dependência também torna as economias vulneráveis às flutuações nos preços globais dessas commodities, o que pode resultar em crises econômicas quando os preços caem drasticamente. Por exemplo, a Venezuela, altamente dependente do petróleo, enfrentou sérias dificuldades econômicas quando o preço do barril despencou no mercado internacional, uma crise que também teve desdobramentos políticos profundos, como veremos na próxima aula.</p>

        <p><strong>O Mercosul</strong><br>
        Dentro desse contexto econômico, o <span class="termo" data-palavra="Mercosul" data-definicao="Mercado Comum do Sul, bloco econômico criado em 1991 pelo Tratado de Assunção, reunindo Brasil, Argentina, Paraguai e Uruguai como membros fundadores, com o objetivo de promover o livre comércio e a integração econômica entre seus membros.">Mercosul</span> (Mercado Comum do Sul) emerge como a principal iniciativa de integração regional da América do Sul. Fundado em 1991 pelo Tratado de Assunção, o bloco inicialmente estabeleceu apenas uma zona de livre-comércio entre seus membros fundadores, Brasil, Argentina, Paraguai e Uruguai. Em 1995, entrou em vigor a <span class="termo" data-palavra="União Aduaneira" data-definicao="Estágio de integração econômica mais avançado que uma simples área de livre-comércio, no qual os países-membros de um bloco passam a adotar uma tarifa externa comum para produtos vindos de fora do bloco, além de eliminar tarifas entre si.">união aduaneira</span>, com uma tarifa externa comum para produtos vindos de fora do bloco.</p>

        <p>A composição do bloco mudou ao longo do tempo: a Venezuela ingressou como membro pleno em 2012, mas foi suspensa já em 2016 por descumprir cláusulas democráticas e comerciais do acordo, suspensão que segue formalmente em vigor, embora mudanças recentes no cenário político venezuelano tenham reaberto, em 2026, o debate sobre seu eventual retorno ao bloco. Já a Bolívia, país andino que vinha negociando sua adesão desde 2012, tornou-se o sexto membro pleno do Mercosul em julho de 2024, unindo-se a Brasil, Argentina, Paraguai, Uruguai e ao próprio bloco fundador. Chile, Peru, Colômbia, Equador, Guiana e Suriname participam como membros associados, com acesso a vantagens comerciais sem os mesmos compromissos dos membros plenos.</p>

        <p><strong>Fato Interessante:</strong> Com a entrada da Bolívia, o Mercosul passou a reunir uma população superior a 299 milhões de habitantes, sendo o Brasil e a Argentina os países de maior peso econômico do bloco.</p>

        <p><strong>O Acordo com a União Europeia</strong><br>
        Desde 2004, o Mercosul negociava um acordo de livre-comércio com a União Europeia, concluído politicamente em junho de 2019, mas que dependia da aprovação dos parlamentos de todos os países envolvidos para entrar em vigor. Esse processo se arrastou por anos, em meio a preocupações europeias com o desmatamento e os direitos de povos indígenas no Brasil, e a preocupações sul-americanas com a concorrência da indústria europeia. O acordo foi finalmente assinado em janeiro de 2026 e entrou em vigor provisório em 1º de maio de 2026, criando uma das maiores zonas de livre-comércio do mundo, com mais de 780 milhões de habitantes e cerca de um quarto do PIB mundial.</p>

        <p><strong>Os Países Andinos</strong><br>
        Os <span class="termo" data-palavra="Países Andinos" data-definicao="Grupo de países sul-americanos atravessados pela Cordilheira dos Andes, tradicionalmente composto por Bolívia, Colômbia, Equador, Peru e Venezuela, com economias marcadas pela extração mineral e pela agricultura de subsistência em áreas rurais.">países andinos</span>, que incluem nações como Peru, Bolívia, Colômbia e Equador, apresentam uma economia caracterizada por uma forte dependência da mineração e da agricultura de subsistência. O Peru e a Bolívia, por exemplo, possuem vastos recursos minerais, incluindo cobre, prata, zinco e lítio, que são exportados para todo o mundo. Esses recursos são fundamentais para a economia desses países, mas a riqueza gerada nem sempre se traduz em melhorias significativas nas condições de vida da população local. A agricultura de subsistência também desempenha um papel importante, especialmente nas áreas rurais, onde muitas famílias dependem do cultivo de pequenos lotes de terra para sua sobrevivência.</p>

        <p>A situação boliviana ilustra bem essa dependência de commodities somada a um obstáculo geográfico
            específico: o país é hoje encravado, sem acesso ao mar, depois de perder a região costeira do Deserto do
            Atacama para o Chile na Guerra do Pacífico (1879-1904). No mesmo período, a Bolívia também cedeu
            território ao Brasil (origem do atual Acre), ao Peru e à Argentina, chegando a ocupar, no século XIX, a
            segunda maior extensão territorial da América Latina e caindo hoje para a quinta posição. A falta de
            litoral próprio encarece a exportação de commodities como o lítio e os minérios andinos, que precisam
            transitar por portos de países vizinhos antes de chegar ao mercado internacional.</p>

        <p>Essa combinação de fatores econômicos cria uma paisagem complexa na América Latina, onde a riqueza natural convive com desafios estruturais, como a desigualdade social e a falta de diversificação econômica. A dependência de commodities, enquanto fornece uma base econômica importante, também limita o desenvolvimento a longo prazo e a resiliência dessas economias a choques externos. Por isso, muitos países da região têm buscado alternativas para diversificar suas economias e reduzir a vulnerabilidade associada à dependência de commodities.</p>

        <p><strong>Fato Interessante:</strong> A fronteira entre Bolívia, Argentina e Chile concentra o chamado
            "triângulo do lítio", região que reúne mais da metade das reservas mundiais desse minério, hoje essencial
            para a fabricação de baterias de celulares, notebooks e carros elétricos. A Bolívia sozinha detém as
            maiores reservas estimadas do planeta, concentradas no salar de Uyuni, mas enfrenta dificuldades técnicas
            e políticas para explorar esse potencial em larga escala, enquanto Chile e Argentina já figuram entre os
            maiores produtores mundiais do minério. A disputa por esse recurso ilustra um padrão histórico da região:
            países ricos em matérias-primas estratégicas, mas que nem sempre conseguem agregar valor a elas antes de
            exportá-las, repetindo, no século XXI, uma lógica de dependência semelhante à observada com o petróleo,
            a prata e o cobre em séculos anteriores.</p>


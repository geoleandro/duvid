            <h2 id="titulo-pr"></h2>

            <p class="w3-border w3-round-large w3-padding">
                <strong>Por que as fronteiras africanas criadas pela Conferência de Berlim causam problemas até hoje?</strong>
            </p>
            <p>As fronteiras foram traçadas sem considerar as populações que viviam nessas terras: povos com a mesma língua e cultura foram separados em países diferentes, e grupos rivais foram forçados a conviver no mesmo Estado. Após a independência, essas fronteiras foram mantidas (pela OUA e depois pela UA), pois mudá-las abriria um precedente perigoso de guerras por território. O resultado é que conflitos étnicos e regionais são frequentemente heranças diretas desse mapa colonial.</p>

            <p class="w3-border w3-round-large w3-padding">
                <strong>O que diferencia colonialismo de neocolonialismo?</strong>
            </p>
            <p>O colonialismo foi a dominação direta: o país europeu mandava administradores, leis e exércitos. O neocolonialismo é a dominação indireta: o país é formalmente independente, tem governo próprio e bandeira, mas continua dependente economicamente de potências externas por meio de dívidas, acordos comerciais desfavoráveis e empresas multinacionais que controlam os recursos. A diferença está na forma, não no resultado: em ambos os casos, a riqueza gerada vai para fora.</p>

            <p class="w3-border w3-round-large w3-padding">
                <strong>O que é a AfCFTA e por que ela é importante?</strong>
            </p>
            <p>A Área de Livre Comércio Continental Africana (AfCFTA), lançada em 2021, reúne 54 países africanos em uma zona de livre comércio que pode se tornar a maior do mundo em número de países. O objetivo é aumentar o comércio intracontinental, atualmente muito baixo, pois a estrutura colonial ligava cada país diretamente à sua metrópole, não aos vizinhos africanos. Se bem implementada, a AfCFTA pode reduzir a dependência da África em relação aos mercados europeus e asiáticos.</p>


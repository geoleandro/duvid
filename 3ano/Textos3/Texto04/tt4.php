                    Economicamente Ativa, ou PEA</span>, é um termo essencial quando se trata de entender como uma
                sociedade
                funciona em termos de trabalho e economia. Ela engloba todas as pessoas em idade ativa, geralmente entre
                15
                e 64 anos, que estão aptas a trabalhar. Dentro desse grupo, podemos identificar duas categorias
                principais:
                as<strong> pessoas ocupadas</strong>, que estão atualmente empregadas e desempenham uma atividade
                remunerada, e as <strong>pessoas desocupadas</strong>, que fazem parte da PEA, mas estão em busca de
                oportunidades de emprego. </p>


            <p>Pessoas Ocupadas - Este grupo refere-se às pessoas que estão atualmente empregadas e exercem uma
                atividade
                remunerada. São indivíduos que contribuem ativamente para a produção de bens e serviços, desempenhando
                um
                papel crucial na economia de um país. </p>


            <p>Pessoas Desocupadas - Incluem-se aqui as pessoas que fazem parte da PEA, mas não têm emprego no momento.
                Essas pessoas estão em busca de oportunidades de emprego e podem enfrentar desafios relacionados ao
                desemprego. A taxa de desemprego é um indicador-chave usado para medir o nível de desocupação na PEA.
            </p>

            <p>O Brasil ilustra bem essas oscilações: em 2025, a taxa de desemprego caiu para 5,6% na média anual, a

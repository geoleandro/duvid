<p> O setor bancário brasileiro é um bom exemplo dessa concentração fora da indústria propriamente dita. Segundo
            o Banco Central, no fim de 2024, apenas quatro instituições, Caixa, Banco do Brasil, Itaú e Bradesco,
            concentravam 57,9% de todas as operações de crédito do país e 54,7% do total de ativos do sistema
            financeiro nacional. Esse tipo de concentração em poucos grandes bancos costuma significar menos
            concorrência em tarifas e taxas de juros, e afeta diretamente o custo do crédito para empresas e famílias
            em todo o país.</p>

<p>Essa concentração também traz problemas. Ela pode aumentar a desigualdade, já que essas empresas gigantes
            muitas vezes não dão oportunidades para as menores. Além disso, o poder fica muito concentrado em algumas
            mãos, o que pode influenciar até nas decisões políticas do país.
        </p>
<p> Alguns termos ajudam a entender melhor esse cenário de concentração industrial:</p>

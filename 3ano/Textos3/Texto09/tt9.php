<p>Fragilização dos serviços públicos: Redução na qualidade e acessibilidade de serviços como saúde e
                educação, que passam a ser privatizados ou terceirizados. </p>
</div>
<p> O Neoliberalismo, com seus princípios de livre mercado e redução do Estado, tem gerado debates intensos
            sobre seu impacto na sociedade e na economia dos países ao redor do mundo.</p>

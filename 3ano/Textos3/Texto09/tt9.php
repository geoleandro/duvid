<div class="w3-panel w3-leftbar w3-sand w3-margin w3-padding">
<h4><strong>Características:</strong></h4>
<p>Privatização: Setores como transporte, energia e saúde passam para as mãos de empresas privadas.</p>
<p>Desregulamentação: Redução das regras que as empresas precisam seguir, como normas ambientais e
                trabalhistas.</p>
<p>Ênfase no individualismo: Valorização da competição individual e redução do papel do Estado como provedor
                de serviços sociais.</p>
<h4><strong>Exemplos:</strong></h4>
<p>Chile: Após o golpe militar de 1973, que derrubou o governo socialista de Salvador Allende, a ditadura de
                Augusto Pinochet aplicou reformas neoliberais radicais planejadas por um grupo de economistas
                chilenos formados nos Estados Unidos, conhecidos como "Chicago Boys". O país privatizou setores como
                previdência e educação, levando a uma maior desigualdade social que ainda hoje é tema de debate
                político no Chile.</p>
<p>Reino Unido: Sob o governo de Margaret Thatcher nos anos 80, o Reino Unido implementou políticas de
                austeridade, cortando gastos sociais e favorecendo o setor privado.</p>
<p>Estados Unidos: O próprio berço de boa parte das ideias neoliberais aplicou reformas semelhantes às do Reino
                Unido. Sob o governo de Ronald Reagan, também nos anos 80, os Estados Unidos cortaram impostos para
                empresas e para os mais ricos, reduziram a regulamentação de setores como o financeiro e o de
                telecomunicações e enfraqueceram os sindicatos, na aposta de que a riqueza gerada no topo acabaria
                "escorrendo" para o restante da população, ideia conhecida como trickle-down economics. Décadas
                depois, essa mesma desregulamentação financeira, aprofundada nos anos 90 e 2000, deixou os bancos sem
                fiscalização suficiente sobre empréstimos imobiliários de altíssimo risco, o que provocou o colapso
                de grandes instituições, como o Lehman Brothers, em 2008, e desencadeou uma recessão que se espalhou
                por praticamente todo o mundo, considerada a pior crise econômica desde a Grande Depressão de
                1929.</p>
<p>Brasil: Nos anos 1990, os governos de Fernando Collor e, principalmente, Fernando Henrique Cardoso
                aplicaram um amplo programa de privatizações, vendendo para a iniciativa privada empresas estatais
                como a Vale do Rio Doce, a Telebrás e diversas companhias de energia elétrica, num processo que
                mudou profundamente a estrutura de setores estratégicos da economia brasileira, seguindo diretamente
                as recomendações do Consenso de Washington.</p>
<h4><strong>Impactos:</strong></h4>
<p> Desigualdade: Aumento da disparidade de renda e oportunidades entre ricos e pobres. Nos Estados Unidos, por
                exemplo, o corte de impostos promovido por Reagan reduziu a alíquota máxima do imposto de renda de
                cerca de 70%, no início dos anos 1980, para 28% ao final de seu governo, uma das maiores quedas de
                tributação sobre os mais ricos da história recente do país.</p>
<div class="w3-margin"><img alt="8" class="w3-mobile" id="imagem8" src="tt09f08.png"/>
</div>
<p> Concentração de riqueza: Poucos indivíduos e corporações acumulam a maior parte da riqueza da nação.</p>

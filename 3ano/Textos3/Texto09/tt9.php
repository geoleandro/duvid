<h2> Acumulação flexível </h2>
<p> A partir dos anos 1970, o capitalismo passou por uma transformação profunda na forma de produzir: a <span class="termo" data-palavra="Acumulação Flexível"
                data-definicao="Termo criado pelo geógrafo David Harvey para descrever o modelo de produção flexível
                que substituiu a rigidez do regime fordista-keynesiano a partir da década de 1970, apoiado em
                tecnologia, terceirização e adaptação rápida à demanda.">Acumulação Flexível</span>, um conceito que
            ajuda a entender por que as empresas hoje produzem de um jeito bem diferente do que faziam no século passado.</p>
<p> O conceito foi criado pelo geógrafo britânico David Harvey, no livro "Condição Pós-Moderna", de 1989, para
            descrever a passagem de um regime de produção fordista-keynesiano, rígido e concentrado em uma única
            fábrica, para um modelo muito mais flexível. Essa transição está diretamente ligada ao Toyotismo, que você
            já estudou na aula passada: as fábricas passaram a se adaptar rapidamente às mudanças do mercado,
            produzindo só o que é necessário, no momento certo, sem manter estoques gigantes, no espírito do sistema
            just in time.</p>
<div class="w3-margin"><img alt="tt09f02" class="w3-mobile" id="imagem2" src="tt09f02.png"/>
<span class="w3-small w3-margin-left" id="citacao12"> Fonte: https://www.significados.com.br/ </span>
</div>
<p> Quando falamos das características desse modelo, vemos que a produção acontece em várias partes, de forma
            espalhada, não mais concentrada em um lugar só. Muitas empresas também terceirizam parte do trabalho, ou
            seja, contratam outras empresas para fazer algumas etapas do processo. O lado ruim é que isso às vezes acaba
            gerando trabalhos precários, com menos direitos para os trabalhadores.</p>
<p> Você pode ver exemplos disso em vários lugares. Na indústria automobilística, por exemplo, as fábricas
            conseguem mudar rapidamente de um modelo de carro para outro, seguindo as tendências do mercado. Na
            tecnologia, com empresas lançando novos produtos o tempo todo, sempre buscando inovações. E na moda rápida,
            aquela que traz as últimas tendências das passarelas para as lojas em um piscar de olhos.</p>
<p> A chamada "moda rápida", ou fast fashion, é um dos exemplos mais visíveis da acumulação flexível no dia a
            dia. Redes como Zara, Shein e H&amp;M conseguem projetar, produzir e colocar novas peças à venda em
            questão de semanas, terceirizando a costura para fábricas em países onde a mão de obra é mais barata. A
            Shein, hoje líder global do setor, chega a lançar milhares de novos modelos de roupa por dia, um ritmo de
            produção muito mais acelerado que o de concorrentes tradicionais como Zara e H&amp;M somadas. Esse ritmo
            acelerado de produção e descarte de roupas também levanta preocupações ambientais, já que gera milhões de
            toneladas de resíduos têxteis todos os anos, entre roupas encalhadas, embalagens e sobras de tecido.</p>
<div class="w3-margin"><img alt="tt09f09" class="w3-mobile" id="imagem9" src="tt09f09.png"/>
<span class="w3-small w3-margin-left" id="citacao9"> Fonte: pixabay.com. </span>
</div>
<p> Esses ganhos de flexibilidade, porém, têm um lado problemático. A Acumulação Flexível pode aumentar a
            desigualdade, já que muitas vezes os trabalhadores não têm condições justas. Também pode trazer
            instabilidade, já que as mudanças rápidas às vezes deixam alguns setores ou empresas para trás, e tende a
            concentrar a riqueza em poucas mãos, deixando muita gente de fora dos benefícios.</p>
<p> Um desdobramento recente e bem conhecido da acumulação flexível é a chamada "uberização" do trabalho: em vez
            de contratar funcionários fixos, empresas de aplicativos conectam prestadores de serviço a clientes sob
            demanda, sem vínculo empregatício formal. Isso leva a extrema flexibilidade da lógica da acumulação
            flexível ao limite, e é um dos temas mais debatidos hoje quando se discute os direitos trabalhistas nesse
            novo modelo de economia. No Brasil, segundo o IBGE, o número de trabalhadores por aplicativos chegou a
            1,7 milhão de pessoas no terceiro trimestre de 2024, um crescimento de 25% em apenas dois anos. Entre
            esses trabalhadores, a informalidade atinge 71%, contra 44% entre os demais ocupados do país, e a renda
            média dos entregadores fica bem abaixo da média geral dos trabalhadores brasileiros, o que alimenta o
            debate sobre a falta de direitos trabalhistas nesse tipo de ocupação.</p>

<h3><span class="termo" data-palavra="Agricultura de Subsistência" data-definicao="Modelo agrícola em que a produção se destina principalmente ao consumo da própria família ou comunidade, com pouco ou nenhum excedente voltado ao mercado.">Agricultura de Subsistência</span></h3>
<p>A agricultura de subsistência é aquela em que os agricultores produzem alimentos principalmente para o
            consumo próprio e de suas famílias, com uma produção limitada para o mercado.</p>
<p><strong>Nepal:</strong> Um exemplo notável é o Nepal, onde a agricultura de subsistência é uma prática comum
            em muitas áreas rurais. Os agricultores no Nepal cultivam arroz, legumes e outras culturas para atender às
            necessidades alimentares de suas comunidades locais, com uma parte menor destinada à venda em mercados
            locais.</p>
<h3>Agricultura Comercial</h3>
<p>A agricultura comercial é caracterizada pela produção em larga escala de culturas destinadas principalmente à
            venda e ao mercado consumidor.</p>
<p><strong>Brasil:</strong> O Brasil é um exemplo destacado de agricultura comercial, sendo um dos líderes
            mundiais na exportação de produtos agrícolas, como soja, milho, café e carne bovina. Grandes áreas de terras
            são dedicadas ao cultivo em larga escala para atender à demanda nacional e internacional.</p>
<div class="w3-margin"><img alt="tt13f012" class="w3-mobile" id="imagem12" src="tt13f012.png"/>
<span class="w3-small w3-margin-left" id="citacao12"> </span>

<p><strong>Sustentabilidade Ambiental:</strong> A forma como cultivamos nossos alimentos afeta diretamente a
            saúde do planeta. Práticas agrícolas sustentáveis, como o cuidado com o solo e a conservação da água, são
            essenciais para proteger o meio ambiente a longo prazo.</p>

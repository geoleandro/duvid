<h2>Histórico da Agricultura no Mundo</h2>
<h3>Agricultura Arcaica</h3>
<div class="w3-margin"><img alt="tt13f03" class="w3-mobile" id="imagem3" src="tt13f03.png"/>
<span class="w3-small w3-margin-left" id="citacao3"></span>
</div>
<p>A agricultura arcaica marca o início das práticas agrícolas na história da humanidade. Foi nesse período
                que as comunidades humanas começaram a abandonar o nomadismo em busca de alimentos e passaram a cultivar
                plantas e criar animais. Algumas das civilizações antigas que se destacaram nesse período foram:</p>
<ul>
<li><strong>Mesopotâmia:</strong> Conhecida como o "berço da civilização", a Mesopotâmia, localizada
                    entre os rios Tigre e Eufrates, desenvolveu técnicas de irrigação que permitiram o cultivo de grãos
                    como cevada e trigo. Cidades como Ur e Babilônia prosperaram graças à agricultura.</li>
</ul>
<div class="w3-margin"><img alt="tt13f04" class="w3-mobile" id="imagem4" src="tt13f04.png"/>
<span class="w3-small w3-margin-left" id="citacao4"> </span>
</div>
<ul>
<li><strong>Egito Antigo:</strong> Às margens do rio Nilo, o Egito Antigo floresceu com uma agricultura
                    altamente produtiva. A inundação anual do rio depositava nutrientes ricos nas terras, permitindo o
                    cultivo de uma variedade de culturas, incluindo trigo, cevada, linho e vegetais.</li>
</ul>
<div class="w3-margin"><img alt="tt13f05" class="w3-mobile" id="imagem5" src="tt13f05.png"/>
<span class="w3-small w3-margin-left" id="citacao5"> </span>
</div>
<h3>Agricultura Moderna</h3>
<p>A transição para a agricultura moderna foi marcada pelas Revoluções Agrícolas, momentos de grandes
                avanços tecnológicos e práticas inovadoras que aumentaram significativamente a produção de alimentos. Um
                exemplo notável desse período é a <span class="termo" data-palavra="Revolução Verde" data-definicao="Conjunto de inovações agrícolas difundido a partir da década de 1960, baseado em sementes de alto rendimento, fertilizantes químicos, irrigação e mecanização, que aumentou a produtividade em larga escala, mas concentrou terras e gerou dependência de insumos industriais.">Revolução Verde</span>.</p>
<ul>
<li><strong>Índia:</strong> A Índia é um dos países que se beneficiaram enormemente da Revolução Verde.
                    No final do século XX, o país estava enfrentando uma crise alimentar devido ao rápido crescimento
                    populacional. No entanto, com a introdução de variedades de alto rendimento de trigo e arroz, além
                    do uso intensivo de fertilizantes e irrigação, a Índia conseguiu se tornar autossuficiente em
                    produção de alimentos. Isso teve um impacto significativo na redução da fome e da pobreza no país.
                </li>
</ul>
<div class="w3-margin"><img alt="tt13f06" class="w3-mobile" id="imagem6" src="tt13f06.png"/>
<span class="w3-small w3-margin-left" id="citacao6"> Uso de fertilizantes na agricultura indiana.</span>
</div>
<h3>Agricultura Contemporânea</h3>
<p>Na agricultura contemporânea, o uso de tecnologia, biotecnologia e práticas sustentáveis está moldando o
                futuro da produção de alimentos. Países líderes nesse campo estão desenvolvendo métodos inovadores para
                enfrentar os desafios da produção agrícola no século XXI.</p>
<ul>
<li><strong>Israel:</strong> Apesar de seu tamanho pequeno e de seu clima desafiador, Israel se tornou
                    um líder em tecnologias agrícolas. O país é conhecido por suas práticas avançadas de irrigação, como
                    o gotejamento, que permite uma utilização eficiente da água. Além disso, Israel investe em pesquisa
                    e desenvolvimento de variedades de plantas resistentes a condições extremas, como a seca,
                    tornando-se um exemplo de como a inovação pode transformar a agricultura.</li>
</ul>
<div class="w3-margin"><img alt="tt13f07" class="w3-mobile" id="imagem7" src="tt13f07.png"/>
<span class="w3-small w3-margin-left" id="citacao7"> Agricultura irrigada em Israel. </span>
</div>
<p><strong><span class="termo" data-palavra="Transgênicos" data-definicao="Organismos que receberam genes de outra espécie por engenharia genética, adquirindo características como resistência a pragas ou a herbicidas. Na agricultura, aumentam a produtividade, mas concentram o mercado de sementes em poucas empresas multinacionais.">Transgênicos</span> e Edição Genética:</strong> Outra fronteira da agricultura contemporânea é a biotecnologia
                aplicada ao melhoramento genético das plantas. Os organismos geneticamente modificados, ou
                transgênicos, recebem genes de outras espécies para adquirir características como resistência a
                pragas ou tolerância a herbicidas, reproduzindo de forma artificial mecanismos de defesa que algumas
                plantas já desenvolvem naturalmente contra insetos e doenças. Mais recentemente, técnicas como o
                CRISPR permitem editar diretamente o DNA da planta sem introduzir genes de outras espécies, tornando
                o processo mais preciso e rápido. Apesar dos ganhos de produtividade, o alto custo das sementes
                patenteadas e a dependência de poucas empresas multinacionais que dominam essa tecnologia dificultam
                o acesso de pequenos agricultores, que muitas vezes não conseguem competir com quem já adota essas
                inovações em larga escala.</p>
<p>Esses exemplos ilustram a evolução da agricultura ao longo dos séculos, desde as práticas rudimentares
                das civilizações antigas até a tecnologia de ponta e as abordagens sustentáveis da agricultura
                contemporânea. A história da agricultura é uma narrativa de adaptação e inovação, essenciais para
                alimentar uma população em constante crescimento em todo o mundo.</p>

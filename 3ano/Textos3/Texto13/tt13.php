<h2>Importância da Agricultura no Mundo</h2>
<p>A agricultura é um dos pilares fundamentais da humanidade, sendo responsável por produzir alimentos, fibras e
            matérias-primas essenciais para a nossa sobrevivência e o desenvolvimento das sociedades. Seu impacto vai
            desde as comunidades rurais mais remotas até as economias globais.</p>
<div class="w3-margin"><img alt="tt13f01" class="w3-mobile" id="imagem1" src="tt13f01.png"/>

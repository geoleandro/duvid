<h2>Relação entre Campo e Cidade no Mundo Atual</h2>
<h3>Diferenças na População Rural e Urbana</h3>
<p>No mundo contemporâneo, a distribuição da população entre áreas rurais e urbanas desempenha um papel crucial
            na dinâmica socioeconômica dos países. Essa relação varia consideravelmente ao redor do globo, com impactos
            significativos na agricultura e no desenvolvimento urbano.</p>
<div class="w3-margin"><img alt="8" class="w3-mobile" id="imagem8" src="tt13f08.png"/>
<span class="w3-small w3-margin-left" id="citacao8"> </span>
</div>
<p><strong>Índia:</strong> Um exemplo marcante dessa relação é a Índia, um país com uma vasta população rural e
            uma crescente urbanização. Enquanto cerca de 60% da população indiana ainda vive em áreas rurais, as cidades
            como Mumbai, Nova Delhi e Bangalore têm testemunhado um rápido crescimento populacional e econômico. Esse
            contraste entre o campo e a cidade na Índia reflete desafios e oportunidades únicas, como a necessidade de
            modernização agrícola e o surgimento de centros urbanos como polos de desenvolvimento econômico.</p>
<h3>Impacto da Urbanização na Agricultura</h3>
<p>A urbanização, processo pelo qual a população migra das áreas rurais para as áreas urbanas, tem um impacto
            direto na agricultura, principalmente em países em desenvolvimento.</p>
<p><strong>China:</strong> Um exemplo notável é a China, que experimentou uma das maiores migrações urbanas da
            história. Milhões de pessoas deixaram o campo em busca de oportunidades nas cidades. Esse êxodo rural teve
            um impacto significativo na agricultura chinesa, com áreas rurais enfrentando uma diminuição da mão de obra
            agrícola e mudanças nos padrões de produção. Além disso, a urbanização também tem levado à conversão de
            terras agrícolas em áreas urbanas, o que pode afetar a produção de alimentos e a segurança alimentar.</p>
<p>Esses exemplos destacam a complexa relação entre campo e cidade no mundo atual. Enquanto a urbanização
            oferece oportunidades econômicas e sociais para muitos, também apresenta desafios para a agricultura,
            exigindo inovação, modernização e planejamento cuidadoso para garantir a segurança alimentar e o
            desenvolvimento sustentável.</p>

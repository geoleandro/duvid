            <p><strong>Economia:</strong> A principal distinção entre as duas superpotências residia em seus sistemas
                econômicos. Os Estados Unidos promoviam um modelo capitalista de livre mercado, enquanto a União
                Soviética
                adotava um sistema de economia planificada baseado em princípios comunistas.</p>
            <div class="w3-margin"><img alt="tt10f02" class="w3-mobile" id="imagem2" src="tt10f02.png" />

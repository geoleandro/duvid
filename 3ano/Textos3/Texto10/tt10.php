                e o
                Pacto de Varsóvia, cada superpotência buscava expandir sua influência, estabelecendo esferas de
                influência
                geopolíticas.</p>
            <div class="w3-margin"><img alt="tt10f03" class="w3-mobile" id="imagem3" src="tt10f03.png" />

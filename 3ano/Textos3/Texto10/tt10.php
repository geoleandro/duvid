        <div class="topico">
            <h2>Guerra Fria: Economia Planificada vs. Capitalista: </h2>
            <div class="w3-margin"><img alt="tt10f05" class="w3-mobile" id="imagem5" src="tt10f05.png" />
                <span class="w3-small w3-margin-left" id="citacao5"> </span>
            </div>
            <p>Durante grande parte do século XX, o mundo esteve dividido entre dois sistemas econômicos e políticos
                diametralmente opostos: a economia planificada, representada pelo bloco soviético liderado pela União
                Soviética, e a economia capitalista, representada pelo bloco ocidental liderado pelos Estados Unidos.
                Esses
                sistemas não apenas moldaram as políticas internas de seus respectivos blocos, mas também influenciaram
                profundamente as relações globais e a geopolítica da época.</p>
            <h3>Economia Planificada do Bloco Soviético</h3>
            <p>A União Soviética adotou o modelo de economia planificada, no qual o Estado detinha o controle dos meios
                de
                produção, determinando o que seria produzido, em que quantidade e a que preço seria vendido. Esse
                sistema
                buscava eliminar as disparidades sociais e econômicas, prometendo igualdade e justiça social para todos
                os
                cidadãos soviéticos.</p>
            <h4>Centralização do Planejamento:</h4>
            <p>Um dos pilares da economia planificada era o planejamento centralizado. O Estado soviético elaborava
                planos
                quinquenais que estabeleciam metas de produção para todos os setores da economia, desde a agricultura
                até a
                indústria pesada.</p>
            <div class="w3-margin"><img alt="tt10f06" class="w3-mobile" id="imagem6" src="tt10f06.png" />
                <span class="w3-small w3-margin-left" id="citacao6">Fonte: Folha – UOL. </span>
            </div>
            <h4>Propriedade Estatal dos Meios de Produção:</h4>
            <p>Sob o sistema soviético, fábricas, terras agrícolas e empresas eram propriedade do Estado. Isso
                significava
                que não havia proprietários privados, e a produção estava voltada para o interesse coletivo.</p>
            <div class="area justificadoEsquerda">
                <div class="w3-panel w3-leftbar w3-sand w3-margin w3-padding">
                    <p><strong>Questão Reflexiva:</strong> Até que ponto o controle estatal sobre os meios de
                        produção garantiu ou restringiu a liberdade individual dos cidadãos soviéticos?</p>
                </div>
            </div>
            <h4>Exemplo da Economia Soviética: Indústria Pesada</h4>
            <p>Um exemplo notável da economia planificada soviética foi o foco na indústria pesada. Durante os primeiros
                planos quinquenais, a URSS direcionou enormes recursos para construir uma base industrial robusta. Isso
                resultou na rápida expansão da produção de aço, maquinaria e produtos químicos. No entanto, isso muitas
                vezes significava a falta de bens de consumo básicos para os cidadãos comuns, levando a longas filas e
                escassez de itens essenciais.</p>
            <h3>Economia Capitalista do Bloco Ocidental</h3>
            <p>Por outro lado, o bloco ocidental liderado pelos Estados Unidos adotou o sistema de economia capitalista,
                baseado na propriedade privada dos meios de produção e na busca do lucro como motor da atividade
                econômica.
            </p>
            <h4>Economia de Mercado Livre:</h4>
            <p>Sob o sistema capitalista, o mercado desempenha um papel fundamental na alocação de recursos. Os preços
                são
                determinados pela oferta e demanda, e as empresas competem umas com as outras para atrair consumidores.
            </p>
            <h4>Propriedade Privada e Iniciativa Individual:</h4>
            <p>Ao contrário da URSS, no sistema capitalista, as empresas são de propriedade privada, e os indivíduos têm
                o
                direito de iniciar seus próprios negócios e buscar lucro.</p>
            <div class="w3-margin"><img alt="tt10f07" class="w3-mobile" id="imagem7" src="tt10f07.png" />
                <span class="w3-small w3-margin-left" id="citacao7"> </span>
            </div>
            <div class="area">

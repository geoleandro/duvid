            <h2>Um mundo dividido: A Dinâmica de Poder entre Estados Unidos e União Soviética</h2>
            <p>Durante os séculos XVIII e XIX, um sistema de equilíbrio econômico, militar e político vigorou entre as
                principais potências europeias. Os conflitos mundiais do século XX mudaram esse panorama: em 1917, a
                Rússia passou por uma revolução socialista, e em 1922 formou-se a União das Repúblicas Socialistas
                Soviéticas (URSS). Um frágil equilíbrio de poder se manteve até o fim da Segunda Guerra Mundial, em
                1945,
                quando emergiu um <span class="termo" data-palavra="Ordem Bipolar" data-definicao="Organização do poder mundial baseada no antagonismo entre duas superpotências,
                Estados Unidos e União Soviética, entre o fim da Segunda Guerra Mundial (1945) e o colapso da URSS
                (1991).">sistema bipolar</span>, baseado no antagonismo entre duas superpotências: os Estados Unidos
                e a União Soviética.</p>
            <p>A rivalidade entre essas superpotências ultrapassou os âmbitos estratégico e diplomático para se
                expressar
                também como contraposição de modelos de organização social e econômica. No plano estratégico, o sistema
                bipolar se fundava na capacidade militar, materializada nas armas nucleares: a posse de arsenais capazes
                de reduzir o mundo a escombros tornou-se marca das duas superpotências, e uma guerra direta entre elas
                significaria a aniquilação mútua. Por isso, a tensão entre elas ficou conhecida como <span class="termo"
                    data-palavra="Guerra Fria" data-definicao="Período de tensão entre Estados Unidos e União Soviética, de 1945 a 1991, marcado por
                um 'equilíbrio do terror' nuclear sem confronto militar direto entre as duas superpotências.">Guerra
                    Fria</span>: houve um "equilíbrio do terror", sem enfrentamento direto, embora as duas potências
                tenham participado indiretamente de diversos conflitos em outros países, como a Guerra da Coreia
                (1950-1953).</p>
            <p>Ainda em 1945, as conferências de Yalta e Potsdam reuniram os líderes dos Estados Unidos, da União
                Soviética
                e do Reino Unido e resultaram no esboço da divisão do território europeu em áreas de influência. A
                Guerra
                Fria foi formalmente deflagrada em 1947, com a Doutrina Truman, que fixava como prioridade da política
                externa estadunidense a contenção do expansionismo soviético na Europa. O Plano Marshall, que vigorou
                entre 1948 e 1952, envolveu a transferência de bilhões de dólares para reerguer a economia dos países
                europeus arrasados pela guerra, funcionando como instrumento de aproximação desses países aos Estados
                Unidos. Uma fronteira estratégica, apelidada de <span class="termo" data-palavra="Cortina de Ferro"
                    data-definicao="Fronteira estratégica que, durante a Guerra Fria, separava o bloco capitalista
                (Ocidente) do bloco socialista (Leste) na Europa, símbolo da divisão ideológica entre as duas
                superpotências.">Cortina de Ferro</span>, passou a separar dois espaços antagônicos na Europa: o
                Ocidente, organizado com base na economia de mercado e liderado pelos Estados Unidos, e o Leste,
                reestruturado pela planificação central da economia e subordinado à União Soviética.</p>
            <div class="w3-margin"><img alt="tt10f01" class="w3-mobile" id="imagem1" src="tt10f01.png" />

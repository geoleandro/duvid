            <h2>Imperialismo: as raízes da disputa territorial</h2>
            <p>Antes de chegarmos à Guerra Fria, é preciso entender um processo anterior, que ajuda a explicar por que o
                mundo já chegava ao século XX profundamente desigual: o <span class="termo" data-palavra="Imperialismo"
                    data-definicao="Política de conquista de novos territórios praticada pelas potências industrializadas
                europeias, sobretudo na África e na Ásia, a partir da segunda metade do século XIX, motivada pela
                disputa por mercados consumidores e matérias-primas.">Imperialismo</span>.</p>
            <p>A partir da segunda metade do século XIX, a disputa por mercados consumidores e matérias-primas levou as
                potências europeias industrializadas, como Grã-Bretanha, França e Alemanha, a uma política de conquista
                de novos territórios. Um marco simbólico desse processo foi a Conferência de Berlim, realizada entre
                1884 e
                1885, na qual as potências europeias se reuniram para negociar entre si a partilha do continente
                africano, traçando fronteiras que muitas vezes ignoravam completamente a distribuição dos povos e das
                etnias locais, e cujas consequências, como conflitos territoriais e étnicos, ainda são sentidas em
                várias
                partes da África nos dias de hoje. Essas nações procuravam expandir o capital excedente de suas
                empresas, e os
                principais alvos foram áreas dos continentes africano e asiático, que sofreram com ações expansionistas
                estrangeiras. Esse processo de dominação ficou conhecido como Imperialismo.</p>
            <p>A disputa acirrada por mercados consumidores também levou as grandes empresas europeias a buscar
                constantes
                inovações técnicas. As empresas industriais que não tinham recursos para arcar com essas despesas foram
                à
                falência, enquanto muitas outras se uniram, passando a dominar o mercado mundial. Foi nesse período que
                se consolidaram os conceitos de monopólio e oligopólio, que você já estudou na aula sobre capitalismo
                monopolista: quando uma única empresa domina o mercado de um produto, ou quando um pequeno grupo de
                empresas domina esse mercado.</p>
            <p>O Imperialismo redesenhou o mapa mundial, dividindo praticamente toda a África e boa parte da Ásia entre
                as
                potências europeias, e deixou heranças que atravessaram o século XX: fronteiras artificiais que ainda
                hoje geram conflitos, economias voltadas à exportação de matéria-prima e uma desigualdade estrutural
                entre os antigos impérios e suas ex-colônias, que abriria caminho, décadas depois, para o processo de
                descolonização que veremos mais adiante nesta aula.</p>

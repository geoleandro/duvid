            <h2>Reprimarização e o papel das multinacionais</h2>

            <p>O debate sobre a <span class="termo" data-palavra="Reprimarização" data-definicao="Processo pelo qual a pauta de exportações de um país que havia avançado para produtos industrializados volta a ser dominada por commodities (matérias-primas agrícolas e minerais). No Brasil, esse processo se intensificou nos anos 2000 com o boom das commodities e a alta demanda chinesa por soja, minério de ferro e petróleo. Enquanto o Brasil passou a exportar mais soja e minério, países asiáticos como China e Coreia do Sul avançaram para produtos de maior tecnologia.">reprimarização</span> é central para entender o Brasil no século XXI. Nos anos 1970-1980, o Brasil tinha uma pauta exportadora mais diversificada, com participação significativa de produtos industrializados (calçados, têxteis, automóveis, aviões). A partir dos anos 2000, com o boom das commodities e a explosão da demanda chinesa por soja e minério, o agronegócio e a mineração tomaram conta das exportações.</p>

            <p>Isso não é totalmente negativo: o boom das commodities gerou divisas, emprego e crescimento econômico. Mas tem riscos: as commodities têm preços voláteis (o que a China paga pela soja hoje pode cair amanhã) e dependem de condições climáticas. Além disso, a desindustrialização que acompanhou a reprimarização eliminou empregos de qualidade na indústria e reduziu a capacidade tecnológica do país.</p>

            <h3>As empresas multinacionais no Brasil</h3>

            <p>As <span class="termo" data-palavra="Empresa Multinacional" data-definicao="Empresa com sede em um país e operações produtivas, comerciais ou financeiras em dois ou mais países. As multinacionais controlam parcela significativa do comércio mundial e das cadeias produtivas globais. Sua presença em países em desenvolvimento traz investimento, emprego e tecnologia, mas também transferência de lucros para a matriz, dependência tecnológica e pressão para reduzir salários e regulações trabalhistas e ambientais.">multinacionais</span> têm papel ambíguo na economia brasileira. Trazem investimento, tecnologia e empregos. Mas também transferem lucros para suas matrizes no exterior (o que drena divisas do país), pressionam por desregulamentação trabalhista e ambiental ("corrida para o fundo") e frequentemente impedem o desenvolvimento de empresas nacionais concorrentes.</p>

            <p>O Brasil tem também suas próprias multinacionais: a Embraer (aviação), a WEG (motores elétricos), a Marfrig e a JBS (carnes), a Vale (mineração), a Petrobras (petróleo). Essas empresas mostram que o Brasil tem capacidade de competir globalmente em setores selecionados. Mas sua abrangência ainda é limitada, e a maioria dos setores tecnológicos mais avançados é dominada por empresas de Estados Unidos, Coreia do Sul, Japão, Alemanha e China.</p>


            <p><span class="primeiraLetra">R:</span> As duas coisas. A China é o maior parceiro comercial do Brasil: compra a maior parte da nossa soja, minério e petróleo, gerando divisas que financiam parte da economia. Mas a China também concorre com a indústria brasileira: produtos chineses mais baratos substituíram produtos manufaturados nacionais em setores como eletroeletrônicos, têxteis e calçados, contribuindo para a desindustrialização. E a relação é assimétrica: o Brasil é dependente da demanda chinesa para suas commodities, o que significa que uma recessão na China ou uma mudança na política agrícola chinesa pode ter impacto profundo na economia brasileira. A gestão dessa relação é um dos principais desafios da política externa e econômica brasileira.</p>

            <p class="w3-border w3-round-large w3-padding">

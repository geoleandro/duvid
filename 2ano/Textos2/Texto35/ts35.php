            <h2>A divisão internacional do trabalho e a globalização</h2>

            <p>A <span class="termo" data-palavra="Divisão Internacional do Trabalho" data-definicao="Distribuição das atividades produtivas entre os países do mundo, determinada historicamente pelas relações de poder entre nações. Na divisão colonial clássica, os países periféricos forneciam matérias-primas e os países centrais fabricavam produtos industrializados. Na globalização contemporânea, essa divisão se fragmentou: partes de um produto podem ser fabricadas em diferentes países, mas ainda há uma hierarquia entre quem cria, quem fabrica e quem extrai.">Divisão Internacional do Trabalho</span> é a distribuição das atividades produtivas entre os países. Historicamente, o padrão colonial era simples: colônias forneciam matérias-primas (ouro, açúcar, algodão, borracha), metrópoles fabricavam produtos industrializados e os revendiam por preços muito maiores. Esse padrão criou uma hierarquia que persiste até hoje, mesmo que as formas tenham mudado.</p>

            <p>A <span class="termo" data-palavra="Globalização" data-definicao="Processo de intensificação das interações econômicas, culturais, políticas e tecnológicas entre países, impulsionado pela liberalização do comércio internacional, a revolução nas telecomunicações e transportes, e a expansão das empresas multinacionais. A globalização econômica reduziu barreiras ao fluxo de mercadorias, capitais e informações, mas não ao fluxo de pessoas. Seu resultado é controverso: gerou crescimento econômico em alguns países, mas também aprofundou desigualdades dentro dos países e entre eles.">globalização</span> intensificou as trocas entre países e fragmentou os processos produtivos em <span class="termo" data-palavra="Cadeias Produtivas Globais" data-definicao="Redes de produção dispersas geograficamente em que cada etapa de fabricação de um produto ocorre no país com maior vantagem comparativa para aquela etapa. O iPhone, por exemplo, é projetado nos EUA (Apple), tem chips feitos em Taiwan (TSMC), telas fabricadas na Coreia do Sul (Samsung), terras raras extraídas no Congo e na China, e é montado na China (Foxconn). A Apple captura a maior parte do valor; a China que monta captura muito menos.">cadeias produtivas globais</span>: a fabricação de um produto pode ser dividida entre dezenas de países, com cada um fazendo a parte para a qual tem custos mais baixos ou tecnologia mais avançada.</p>

            <h3>O Brasil na cadeia global: onde estamos?</h3>

            <p>O Brasil ocupa principalmente a base das cadeias produtivas globais: fornece commodities (soja, minério, petróleo) e produtos com baixo processamento. Isso significa capturar menos valor por tonelada exportada. Uma tonelada de soja vale cerca de 400 dólares. Uma tonelada de óleo de soja (processado) vale quase o dobro. Um quilo de carne de frango processada como nuggets vale muito mais do que um quilo de frango congelado inteiro. Quanto mais o produto for transformado, mais valor ele carrega.</p>

            <p>Por que o Brasil não processa mais antes de exportar? As causas são históricas, econômicas e políticas: o modelo de negócios das grandes tradings (Cargill, ADM, Bunge) prefere importar o processamento; países compradores como a China cobram tarifas progressivas sobre produtos mais processados (cobram menos imposto de soja bruta do que de farelo ou óleo de soja); e a política industrial brasileira das últimas décadas não priorizou o desenvolvimento de capacidade de transformação industrial das commodities.</p>

            <p>O tamanho dessa desvantagem aparece nos números do comércio mundial: em 2021, o Brasil ocupava apenas
                a 25ª posição no ranking do comércio internacional, participando dos fluxos globais de mercadorias
                com só 1,3% do total, uma fatia pequena para a décima maior economia do planeta. Produtos de alta
                intensidade tecnológica, como aviões e automóveis, respondiam por apenas cerca de 1,8% das
                exportações brasileiras. Em 2022, os dez maiores parceiros comerciais do Brasil foram, pela ordem,
                China, Estados Unidos, Argentina, Alemanha, Índia, Países Baixos, Chile, Espanha, México e Japão.
                Os maiores déficits comerciais do país ficaram justamente com os Estados Unidos e a Alemanha (que
                vendem ao Brasil mais produtos industrializados do que compram), enquanto o maior superávit veio da
                China, puxado pelas commodities.</p>


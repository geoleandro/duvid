        <p><em>Exemplo Prático:</em> As margens do Rio São Francisco são áreas de preservação permanente que ajudam a proteger as nascentes e a qualidade da água. As APPs garantem a conservação de matas ciliares, fundamentais para a proteção do solo e da água.</p>

        <p>Para que essas regras sejam cumpridas e fiscalizadas, todo imóvel rural no Brasil precisa estar inscrito
            no Cadastro Ambiental Rural (CAR), um registro eletrônico que reúne informações georreferenciadas sobre
            as APPs, a reserva legal e as áreas de uso restrito de cada propriedade. O CAR é hoje a principal
            ferramenta de monitoramento do desmatamento ilegal em terras privadas, permitindo cruzar dados de
            satélite com os limites declarados de cada propriedade.</p>
    
        <p><strong>Reservas Naturais</strong></p>
        <p>Reservas naturais no Brasil incluem Parques Nacionais, Florestas Nacionais e Reservas Extrativistas, que variam em termos de uso permitido e níveis de proteção.</p>
        <p><em>Exemplo Prático:</em> O Parque Nacional do Iguaçu, no Paraná, é um exemplo de área protegida que permite apenas atividades científicas e turísticas controladas. Já a Reserva Extrativista Chico Mendes, no Acre, permite o uso sustentável dos recursos naturais por populações tradicionais, combinando conservação com desenvolvimento socioeconômico.</p>

        <p>Essas categorias fazem parte do Sistema Nacional de Unidades de Conservação da Natureza (SNUC), que
            organiza as áreas protegidas brasileiras em dois grandes grupos: as unidades de proteção integral, que
            têm como objetivo principal preservar a natureza, com uso indireto dos recursos naturais (como os
            parques nacionais), e as unidades de uso sustentável, que buscam conciliar a conservação com o uso direto
            dos recursos por comunidades locais (como as reservas extrativistas e as florestas nacionais).</p>

        <p>Criado em 2000, o SNUC completou 25 anos em 2025 e hoje protege cerca de 20% do território terrestre
            brasileiro e 26% da área marinha do país, num total de mais de 2,6 milhões de km² distribuídos por mais
            de 3.185 unidades de conservação, um salto em relação aos cerca de 754 mil km² protegidos no ano 2000.
            Esse crescimento mostra que a expansão da fronteira agrícola, discutida ao longo desta aula, não é o
            único movimento em curso no território brasileiro: paralelamente a ela, o país também ampliou de forma
            significativa a área formalmente protegida por lei.</p>
    
        <p><strong>Técnica de Controle Biológico</strong></p>
        <p>O <span class="termo" data-palavra="controle biológico" data-definicao="Técnica que utiliza organismos vivos (predadores, parasitoides ou patógenos naturais) para controlar pragas agrícolas, reduzindo a dependência de agrotóxicos.">controle biológico</span> é uma técnica que utiliza organismos vivos para controlar pragas agrícolas. Em vez de usar agrotóxicos, os agricultores introduzem predadores naturais das pragas nas lavouras.</p>
        <p><em>Exemplo Prático:</em> O uso de joaninhas para controlar pulgões em plantações de hortaliças é uma prática comum no Brasil, reduzindo a necessidade de pesticidas químicos e promovendo um ecossistema agrícola mais equilibrado.</p>

        <p>Em escala industrial, o Brasil também é referência mundial nesse tipo de técnica: a vespa Trichogramma
            galloi é liberada em cerca de 5 milhões de hectares de cana-de-açúcar para combater a broca-da-cana,
            fazendo desse o maior programa de controle biológico com macrorganismos em regiões tropicais do mundo.
            Casos como esse mostram que o controle biológico não é apenas uma alternativa de pequena escala, mas uma
            tecnologia competitiva mesmo diante das grandes lavouras do agronegócio brasileiro.</p>
    
        <p><strong>Uso de Fertilizantes</strong></p>
        <p>Os fertilizantes são essenciais para repor nutrientes no solo e aumentar a produtividade agrícola. No entanto, o uso excessivo pode levar à contaminação dos cursos d'água e à degradação do solo.</p>
        <p><em>Dados do Brasil:</em> O Brasil é um dos maiores consumidores de fertilizantes do mundo, mas também um dos mais dependentes de importações: cerca de 85% a 90% de todo o fertilizante usado na agricultura brasileira vem de fora do país, sobretudo o potássio, do qual quase a totalidade do consumo nacional é importada. A agricultura brasileira depende fortemente de fertilizantes sintéticos, especialmente em culturas como soja, milho e cana-de-açúcar, o que torna o setor vulnerável a crises internacionais, como ficou evidente durante a guerra entre Rússia e Ucrânia.</p>



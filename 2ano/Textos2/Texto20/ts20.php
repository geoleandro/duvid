        <p>A <span class="termo" data-palavra="agroecologia" data-definicao="Abordagem que propõe práticas agrícolas alinhadas aos processos ecológicos e à biodiversidade, integrando conhecimentos tradicionais com técnicas modernas para construir sistemas de produção sustentáveis e socialmente justos.">agroecologia</span> propõe práticas agrícolas que respeitam os processos ecológicos, a biodiversidade e a sustentabilidade social. Ela integra conhecimentos tradicionais com técnicas modernas para promover sistemas agrícolas sustentáveis e resilientes.</p>
        <p><em>Exemplo Prático:</em> A técnica agroflorestal, que combina cultivos agrícolas com árvores, é usada em várias regiões do Brasil. Um exemplo é o projeto Agroflorestal no assentamento Sepé Tiaraju, no Paraná, onde a integração de árvores frutíferas e madeira com cultivos anuais tem aumentado a produtividade e a sustentabilidade ambiental.</p>

        <p>No Brasil, a agroecologia conta inclusive com uma política pública dedicada a ela: a Política Nacional de
            Agroecologia e Produção Orgânica (PNAPO), criada para articular e integrar políticas, programas e ações
            que incentivem a transição dos sistemas de produção agrícola para modelos de base agroecológica ou
            orgânica, priorizando a segurança alimentar e o uso sustentável dos recursos naturais.</p>
    
        <p><strong>Áreas de Preservação</strong></p>
        <p>As <span class="termo" data-palavra="área de preservação permanente" data-definicao="Área protegida por lei (Código Florestal), coberta ou não por vegetação nativa, com a função de preservar recursos hídricos, a paisagem, a estabilidade geológica e a biodiversidade.">áreas de preservação permanente (APPs)</span> e as reservas legais são mecanismos importantes no Brasil para proteger recursos hídricos, a biodiversidade e prevenir desastres naturais. As APPs costumam corresponder a faixas ao longo de rios, nascentes, encostas íngremes e topos de morro, enquanto a reserva legal é um percentual mínimo de vegetação nativa que todo imóvel rural precisa manter, variando de 20% em áreas de Mata Atlântica e Cerrado fora da Amazônia Legal a até 80% em propriedades localizadas na porção florestal da Amazônia Legal.</p>



        <div class="w3-margin"><img id="imagem7" src="ts20f07.png" alt="ts20f07" class="w3-mobile" >
		  
            <span class="w3-small w3-margin-left" id="citacao7" >  </span>

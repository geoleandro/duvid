        <p><strong>Desmatamento</strong></p>
        <p>A modernização agrícola, especialmente a expansão da fronteira agrícola, tem contribuído significativamente para o desmatamento no Brasil. A Amazônia e o Cerrado são biomas particularmente afetados pela conversão de florestas em áreas agrícolas e pastagens.</p>
        <p><em>Dados do Brasil:</em> Após picos históricos no início da década (13.038 km² em 2021), o desmatamento na Amazônia brasileira entrou em trajetória de queda: segundo o PRODES/INPE, em 2025 foram desmatados cerca de 5.796 km², uma redução de 11% em relação a 2024 e o quarto ano consecutivo de queda: o menor índice em 11 anos. Ainda assim, a expansão agrícola e pecuária segue sendo a principal causa da destruição da floresta.</p>

        <p>Um dado que costuma surpreender é que, atualmente, o Cerrado perde mais floresta em números absolutos do
            que a Amazônia, mesmo sendo um bioma bem menor: no mesmo período de 2025, foram desmatados cerca de 7.235
            km² de Cerrado, também uma queda de cerca de 11% frente ao ano anterior, mas ainda assim um volume maior
            do que o registrado na Amazônia. Isso acontece porque o Cerrado tem proteção legal mais fraca do que a
            Amazônia: o Código Florestal exige a preservação de uma fração bem menor da vegetação nativa em
            propriedades rurais do Cerrado, o que faz da savana brasileira a nova fronteira preferencial de expansão
            do agronegócio.</p>



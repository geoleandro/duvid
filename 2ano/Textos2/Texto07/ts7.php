<h2>As classificações do relevo brasileiro </h2>
<h3>Classificação geomorfológica</h3>
<p> A extensão territorial do Brasil levou diversos cientistas a adotarem distintas classificações para a grande
            variedade geológica e de paisagens existentes no Brasil.</p>
<p>Dentre os precursores geógrafos e geomorfólogos, destaca-se o professor Aroldo de Azevedo, na década de 1940.
        </p>
<p>Formado originalmente em Direito, Aroldo de Azevedo optou por seguir a carreira de geógrafo e se licenciou em
            Geografia e História pela Universidade de São Paulo em 1939, tornando-se um dos primeiros professores de
            Geografia do Brasil daquela universidade, onde chegou a dirigir o Instituto de Geografia entre 1963 e
            1967. Foi também o autor didático mais influente da área no país durante décadas, com mais de trinta
            livros publicados, o que fez de sua classificação do relevo a referência adotada pela maioria dos livros
            escolares do período.</p>
<p>O professor Aroldo de Azevedo privilegiou uma abordagem geomorfológica e, por isso, adotou o critério de
            altitudes para lidar com o relevo brasileiro. Ele identificou oito unidades geomorfológicas, conforme o mapa
            abaixo: </p>
<div class="w3-margin"><img alt="ts07f01" class="w3-mobile" id="imagem1" src="ts07f01.png"/>
</div>
<p> Essa classificação adotou um caráter mais abrangente à época, mais generalizado. Dividiu o país em oito
            grandes unidades: quatro planaltos (das Guianas, Central, Atlântico e Meridional) e quatro planícies
            (Amazônica, Costeira, do Pantanal e dos Pampas).</p>
<p>Esse modelo de representação do relevo brasileiro foi muito utilizado na maioria dos livros didáticos até a
            década de 1950. </p>
<h3>O relevo e a dinâmica geomorfoclimática</h3>
<p>Nos anos de 1960 e 1970, o geógrafo Aziz Ab’Saber propôs uma nova classificação do relevo brasileiro. Ele
            aperfeiçoou o modelo anterior, contando com o auxílio da <span class="w3-yellow" onclick="document.getElementById('aerofotogrametria').style.display='block'">aerofotogrametria</span> para elaborar uma nova proposta do relevo brasileiro a partir da erosão e
            da sedimentação. </p>
<div class="w3-modal w3-margin-top" id="aerofotogrametria">
<div class="w3-modal-content">
<div class="w3-container w3-padding">
<span class="w3-button w3-red w3-display-topright" onclick="document.getElementById('aerofotogrametria').style.display='none'">×</span>
<p>
                        O levantamento aerofotogramétrico é um dos métodos utilizados para o mapeamento da
                        superfície terrestre. O voo fotogramétrico é realizado por uma aeronave, na qual é acoplada
                        uma câmera fotogramétrica que cobre toda a área a ser mapeada.

                    </p>
</div>
</div>
</div>
<p>Ab’Saber percebeu que, além da altitude, era importante avaliar os processos geomorfológicos ligados à
            dinâmica climática. Essa abordagem considerava se o relevo sofria processos de erosão (desgaste) ou de
            sedimentação (acúmulo de sedimentos), ou seja, se determinada área perdia ou recebia sedimentos. </p>
<p>Nessa reformulação, os planaltos foram considerados como áreas desgastadas pela ação da erosão, enquanto que
            as planícies eram áreas que recebiam esses detritos em permanente processo de construção. </p>
<div class="w3-margin"><img alt="ts07f02" class="w3-mobile" id="imagem2" src="ts07f02.png"/>
</div>
<p>O autor manteve o planalto das Guianas, mas o subdividiu o planalto Brasileiro nas seguintes unidades, são
            elas: Planalto das Guianas; Central, Meridional, Serras e Planaltos do Leste e Sudeste, Maranhão-Piauí,
            Nordestino e Uruguaio-Sul-Rio-Grandense. As planícies estão relacionadas à: planície Costeira, Amazônica, do
            Pantanal e do Pampa. </p>
<p>Esses estudos buscavam provar que a Amazônia não era uma planície, pelo menos não totalmente, pois essa área
            era composta por planícies e terras baixas. Isso quer dizer que o terreno em construção (que recebia
            sedimentos) estava apenas localizado nas margens do rio Amazonas, enquanto que o restante era constituído
            por terrenos bastante desgastados. </p>
<p>Para o autor, 75% das terras brasileiras eram de planaltos; as planícies comporiam 25% restantes. Mesmo com
            observações feitas em viagens por terra e por aviões, o maior avanço viria com a incorporação dos radares no
            detalhamento do relevo. </p>
<h3>Classificação morfoestrutural</h3>
<p>Publicado em 1989 pelo geógrafo Jurandyr Ross, essa classificação utilizou de fotografias áreas do projeto
            <span class="w3-yellow" onclick="document.getElementById('RADAM').style.display='block'">RADAM</span>
            Brasil. Leva em conta a estrutura geológica na formação do relevo e o fator escultural das formas de relevo.
            Além dos planaltos e das planícies, surgem as unidades das depressões. São no total, 28 unidades do relevo,
            sendo 11 planaltos, 11 depressões e 6 planícies. É um mapeamento mais detalhado para nortear a ocupação do
            território, a construção de estradas, o planejamento, a ocupação do solo e a proteção ambiental.
        </p>

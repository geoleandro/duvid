<h3>O litoral tropical ou oriental</h3>
<p> Esse trecho do litoral já é marcado por ser quente e úmido com falésias e praias mais estreitas. Vai desde o
            Cabo de São Roque (RN) até o Cabo de São Tomé (RJ).</p>
<div class="w3-margin"><img alt="ts07f016" class="w3-mobile" id="imagem16" src="ts07f016.png"/>

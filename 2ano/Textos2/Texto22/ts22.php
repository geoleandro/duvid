        <h2>Mudanças na Matriz Energética Global</h2>

        <p>Nas últimas décadas, o mundo vem passando por transformações importantes na forma de produzir energia.
        Dados da Agência Internacional de Energia mostram que, entre 1971 e 2019, a oferta mundial de energia mais
        que dobrou, e sua composição também mudou: o petróleo, que já foi disparado a fonte mais usada, perdeu
        participação relativa para o gás natural, que se tornou uma alternativa ao petróleo na geração de
        eletricidade, trazendo vantagens econômicas e ambientais. Ao mesmo tempo, porém, o uso do carvão mineral
        também cresceu de forma expressiva em várias partes do mundo — um movimento na contramão do esforço global
        de transição para fontes menos poluentes.</p>

        <p>No setor de transportes, a principal novidade tem sido a tecnologia da <span class="termo" data-palavra="célula de combustível" data-definicao="Dispositivo que produz eletricidade diretamente a partir da reação química entre hidrogênio e oxigênio, emitindo apenas vapor-d'água como resíduo.">célula de combustível</span>: uma bateria
        que produz eletricidade a partir da reação entre hidrogênio e oxigênio. Carros elétricos com essa tecnologia
        são mais eficientes que os movidos por motores de combustão interna e emitem apenas vapor-d'água. O
        problema é que essas baterias dependem de grande quantidade de lítio, e a exploração desse mineral causa
        altos impactos ambientais, sobretudo nas regiões desérticas da Austrália, do Chile, da Argentina e da China,
        que detêm as maiores reservas mundiais.</p>

        <p>O uso de <span class="termo" data-palavra="biocombustíveis" data-definicao="Combustíveis produzidos a partir de biomassa — material orgânico como cana-de-açúcar, milho ou resíduos vegetais — em vez de fontes fósseis como petróleo e carvão.">biocombustíveis</span>
        também tem se ampliado em todo o mundo. A biomassa é um material orgânico — como lenha, carvão vegetal e
        resíduos em decomposição — que libera combustíveis. O Brasil é um dos maiores produtores e exportadores de
        etanol do mundo, obtido a partir da cana-de-açúcar. Se por um lado os biocombustíveis ajudam a reduzir as
        emissões de gases que geram o efeito estufa, por outro contribuem para o desmatamento e para a ocupação de
        terras agrícolas que poderiam ser usadas na produção de alimentos.</p>

        <p>A energia eólica e a energia solar também têm crescido, mas ainda representam uma fatia pequena da
        matriz energética mundial: somadas, essas fontes não passam de 2% do consumo energético total do planeta.
        As centrais fotovoltaicas, equipadas com células solares — componentes eletrônicos que transformam a luz do
        Sol em corrente elétrica — são uma das formas mais promissoras de obtenção de energia solar. O Brasil já
        tem experiências nesse campo, como a fazenda de energia solar do município de Oliveira dos Brejinhos, na
        Bahia.</p>


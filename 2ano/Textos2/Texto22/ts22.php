        <h2>Termoelétricas</h2>

        <div class="w3-margin"><img id="imagem3" src="ts22f03.png" alt="ts22f03" class="w3-mobile" >

            <span class="w3-small w3-margin-left" id="citacao3" >  </span>

            </div>

        <p>As <span class="termo" data-palavra="usina termelétrica" data-definicao="Usina que produz eletricidade a partir do calor liberado pela queima de combustíveis (carvão, gás natural, óleo diesel) ou pela fissão nuclear, usado para gerar vapor que movimenta turbinas.">usinas termoelétricas</span> produzem energia pela queima de combustíveis fósseis, como carvão, gás natural e óleo diesel.</p>

        <p>Essas usinas são mais poluentes, liberando grandes quantidades de gases de efeito estufa e podendo causar chuva ácida — um fenômeno em que poluentes lançados na atmosfera se combinam com a umidade do ar e retornam ao solo em forma de chuva ácida, prejudicando solos, rios e construções.</p>

        <p>No Brasil, as termoelétricas convencionais respondem por uma fração pequena da energia elétrica produzida no país, sendo utilizadas principalmente em períodos de seca, quando os níveis dos reservatórios hidrelétricos estão baixos — funcionam como uma espécie de "seguro" do sistema elétrico brasileiro. Elas usam combustíveis variados, como gás natural, carvão mineral, óleo diesel e até bagaço de cana-de-açúcar (um resíduo da produção de etanol e açúcar, reaproveitado como combustível pelas usinas sucroalcooleiras), e costumam ficar próximas a centros urbanos ou industriais, justamente para reduzir perdas no transporte da energia gerada.</p>

        <p><strong>Pontos importantes:</strong></p>
        <p><strong>Vantagens:</strong> Podem ser instaladas em locais próximos aos centros consumidores e não dependem de condições climáticas.</p>
        <p><strong>Desvantagens:</strong> Poluição ambiental e custos elevados devido à dependência de combustíveis fósseis.</p>


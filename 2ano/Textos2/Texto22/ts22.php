        <h2>Usinas Hidrelétricas</h2>

        <p>As usinas hidrelétricas utilizam a força da água para gerar energia. Em 2022, elas responderam por 61,9%
        de toda a oferta de energia elétrica do Brasil — de longe a principal fonte da matriz elétrica brasileira.</p>

        <p>Essa fonte de energia é renovável e considerada menos agressiva ao meio ambiente, apesar de seus impactos socioambientais, como o alagamento de áreas extensas e o deslocamento de comunidades ribeirinhas.</p>

        <p><strong>Exemplos de usinas hidrelétricas importantes:</strong></p>

        <p><strong>Usina de Belo Monte:</strong> Localizada no rio Xingu, na bacia amazônica, próxima a Altamira (PA). É a maior usina inteiramente brasileira e uma das maiores do mundo em capacidade instalada, inaugurada em 2016. O projeto é controverso, devido ao seu impacto ambiental significativo, incluindo a perda de cobertura vegetal e fauna, e o deslocamento de comunidades indígenas e ribeirinhas. Capacidade instalada: 11.233 MW — mas, na prática, a geração média fica em torno de 4.500 MW, podendo cair para menos de 200 MW nos meses mais secos, porque o Rio Xingu tem vazão muito irregular ao longo do ano.</p>

        <div class="w3-margin"><img id="imagem1" src="ts22f01.png" alt="ts22f01" class="w3-mobile" >
		   
            <span class="w3-small w3-margin-left" id="citacao1" >Usina de Belo Monte </span>
           
           </div>
    
        <p><strong>Usina de Itaipu:</strong> Situada no rio Paraná, na fronteira entre Brasil e Paraguai. É uma das
        maiores usinas hidrelétricas do mundo em capacidade instalada, com 14.000 MW distribuídos entre 20 unidades
        geradoras. Representa um exemplo de cooperação internacional, sendo um projeto binacional entre Brasil e
        Paraguai desde sua construção, nos anos 1970 e 1980. Hoje, Itaipu responde por cerca de 6,7% de toda a
        energia consumida no Brasil e por quase 78% da energia consumida no Paraguai — uma proporção que já foi
        ainda maior no passado, quando o país vizinho dependia de Itaipu para praticamente toda a sua eletricidade.
        Desde o início de suas operações, a usina já ultrapassou a marca histórica de 3,1 bilhões de MWh produzidos.</p>

        <div class="w3-margin"><img id="imagem2" src="ts22f02.png" alt="ts22f02" class="w3-mobile">
            <span class="w3-small w3-margin-left" id="citacao2"> Usina de Itaipu </span>
        </div>
    
        <p><strong>Usina de Tucuruí:</strong> Localizada no rio Tocantins, no Estado do Pará, a cerca de 300 km de Belém. A usina foi construída principalmente para fornecer energia elétrica barata para o projeto de mineração de Grande Carajás, incluindo a indústria de alumínio. Capacidade instalada: 8.370 MW.</p>

        <p><strong>Por que nem todo o potencial hidrelétrico do Brasil é usado:</strong> O clima equatorial e
        tropical do país garante médias pluviométricas elevadas, e os desníveis dos extensos planaltos brasileiros
        fornecem a força necessária para girar as turbinas — por isso o Brasil tem um dos maiores potenciais
        hidrelétricos do mundo. Mas esse potencial não é aproveitado da mesma forma em todas as regiões: a Região
        Hidrográfica Amazônica concentra o maior potencial do país (como você viu na aula sobre hidrografia
        brasileira), mas apenas uma pequena parte dele é explorada, por causa da distância dos centros consumidores
        e dos impactos socioambientais de projetos como o de Belo Monte. Já a Região Hidrográfica do Paraná, onde
        fica Itaipu, tem boa parte do seu potencial em uso, assim como o Rio Tocantins, onde está Tucuruí.
        Considerando as usinas já em operação, os rios com maior capacidade de geração de energia do país são o
        Tocantins, o São Francisco, o Grande, o Paraná, o Iguaçu e o Paranaíba.</p>


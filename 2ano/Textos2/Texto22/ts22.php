        <h2> Introdução </h2>


        <p> <span class="primeiraLetra">A</span> <span class="termo" data-palavra="matriz energética" data-definicao="Conjunto de todas as fontes de energia disponíveis para suprir as necessidades de um país, incluindo eletricidade, calor e combustíveis usados em transportes e indústria.">matriz energética</span> de um país refere-se ao conjunto de todas as fontes de energia disponíveis para suprir suas necessidades, incluindo energia elétrica, calor e combustível.
        </p>


        <p>No Brasil, a matriz energética é diversificada, com predominância de fontes renováveis, como a hidroeletricidade. A <span class="termo" data-palavra="matriz elétrica" data-definicao="Recorte da matriz energética que considera apenas as fontes usadas para gerar eletricidade — no Brasil, predominantemente hidrelétrica.">matriz elétrica</span>, por outro lado, é especificamente voltada para as fontes de energia que geram eletricidade.</p>

        <p>Ao longo desta aula, você vai entender a diferença entre matriz energética e matriz elétrica, conhecer as
        principais usinas hidrelétricas, termelétricas e nucleares do Brasil, e descobrir como o mundo — e o Brasil —
        vêm mudando a forma de produzir energia: do avanço do gás natural e dos biocombustíveis ao crescimento, ainda
        tímido, da energia eólica e solar. Você também vai entender por que o Brasil ainda depende de energia
        importada mesmo sendo rico em fontes renováveis, e como o desmatamento de uma floresta pode, indiretamente,
        afetar a conta de luz de milhões de brasileiros.</p>


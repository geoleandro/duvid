        <h2>O Setor Energético Brasileiro</h2>

        <p>Em 2021, cerca de 18% da energia consumida no Brasil foi importada — um percentual relativamente baixo,
        que mostra que o país tem baixa dependência externa de energia (bem diferente, por exemplo, do Japão, que
        importa a maior parte da energia que consome). As importações brasileiras vêm principalmente de gás
        natural, carvão mineral e óleo diesel. A importação de óleo diesel acontece porque as refinarias
        brasileiras não conseguem atender a toda a demanda desse combustível usando apenas petróleo nacional.</p>

        <p>O Brasil apresenta um equilíbrio relativo entre fontes renováveis e não renováveis quando se considera
        toda a matriz energética (e não só a elétrica). Em 2022, pouco mais da metade da oferta de energia — 52,6%
        — veio de fontes não renováveis, principalmente hidrocarbonetos como petróleo e gás natural. As fontes
        renováveis, como o etanol de cana-de-açúcar, a energia hidráulica e a lenha, responderam pelos outros
        47,4%. O setor de transportes e o setor de indústrias são os maiores consumidores de energia do país: em
        2022, consumiram, respectivamente, 33% e 32% do total.</p>

        <p>Olhando com mais detalhe para essa divisão de 2022: dentro da fatia não renovável (52,6%), o petróleo e
        seus derivados representam a maior parcela (35,7%), seguidos por gás natural, carvão mineral, energia
        nuclear e outras fontes não renováveis. Já dentro da fatia renovável (47,4%), a biomassa de cana-de-açúcar
        lidera (15,4%), seguida pela energia hidráulica, pela lenha e carvão vegetal, por outras fontes renováveis e,
        por fim, pela energia eólica e solar — que, apesar de crescerem rápido nos últimos anos, ainda representam
        uma fatia pequena da matriz energética total do país (diferente do que ocorre especificamente na matriz
        elétrica, onde a eólica já é a segunda maior fonte, atrás apenas da hidráulica).</p>

        <p>Essa configuração é resultado de transformações que vêm ocorrendo há décadas. O crescimento populacional
        e industrial, somado à expansão das áreas urbanas e agrícolas, aumentou a demanda por energia no Brasil,
        tornando necessária a ampliação constante do parque gerador. Ao longo do século XX, fontes modernas de
        energia — carvão mineral, petróleo e força hidráulica — substituíram gradualmente as fontes tradicionais
        que dominavam o consumo brasileiro no passado, como a lenha e o carvão vegetal.</p>

        <p><strong>Como se mede a energia:</strong> Comparar fontes de energia tão diferentes exige unidades de
        medida padronizadas. O joule (J) é a unidade básica de energia do Sistema Internacional de Unidades; como
        as quantidades de energia de um país inteiro são gigantescas, os relatórios costumam usar o exajoule
        (1 exajoule equivale a 10¹⁸ joules — um quintilhão). Já para comparar fontes de petróleo, gás e outros
        combustíveis entre si, é comum usar o tep ("tonelada equivalente de petróleo"), que representa a energia
        liberada pela queima de uma tonelada de petróleo bruto, ou o Mtep (milhão de tep), usado em gráficos de
        produção de energia de países inteiros. Para a eletricidade especificamente, a unidade mais comum é o watt
        e seus múltiplos, como o megawatt (MW, usado para medir a capacidade das usinas citadas nesta aula) e o
        gigawatt (GW): 1 gigawatt é energia suficiente para abastecer cerca de 500 mil residências, o equivalente ao
        consumo de aproximadamente 2 milhões de pessoas no Brasil.</p>


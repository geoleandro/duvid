        <h2>Usinas Nucleares</h2>

        <div class="w3-margin"><img id="imagem4" src="ts22f04.png" alt="ts22f04" class="w3-mobile" >

            <span class="w3-small w3-margin-left" id="citacao4" >  </span>

            </div>

        <p>As usinas nucleares utilizam o calor gerado pela <span class="termo" data-palavra="fissão nuclear" data-definicao="Reação em que o núcleo de um átomo pesado, como o urânio, se divide em núcleos menores, liberando uma enorme quantidade de energia na forma de calor.">fissão nuclear</span> de átomos de urânio para produzir eletricidade. No Brasil, as usinas nucleares estão localizadas em Angra dos Reis, no Estado do Rio de Janeiro, com as plantas Angra 1 e Angra 2 operando, e Angra 3 em construção.</p>

        <p><strong>Características das usinas nucleares:</strong></p>
        <p><strong>Capacidade instalada:</strong> Angra 1 (640 MW), Angra 2 (1.350 MW), e Angra 3 (1.405 MW) após a conclusão.</p>
        <p><strong>Vantagens:</strong> Baixa emissão de poluentes, alta eficiência energética e abundância de urânio no mundo.</p>
        <p><strong>Desvantagens:</strong> Risco de acidentes nucleares, como Chernobyl (1986) e Fukushima (2011), e o problema do lixo radioativo, que permanece perigoso por milhares de anos.</p>

        <p><strong>Os acidentes de Chernobyl e Fukushima:</strong> Em 1986, na usina de Chernobyl, na então União
        Soviética (atual Ucrânia), um teste de segurança mal conduzido — em que sistemas de proteção foram
        desligados propositalmente — provocou uma reação em cadeia descontrolada, seguida de explosão e incêndio no
        reator. O acidente liberou uma quantidade de radiação equivalente a centenas de bombas atômicas de
        Hiroshima, contaminando uma extensa área da Ucrânia, da Bielorrússia e da Rússia. Já em 2011, no Japão, um
        terremoto seguido de tsunami provocou a perda total de energia da usina de Fukushima, o que impediu o
        resfriamento dos reatores e levou à fusão do núcleo em três deles. Os dois acidentes são classificados como
        nível 7 — o mais grave — na escala internacional de eventos nucleares, e ajudam a explicar por que a energia
        nuclear, apesar de eficiente e pouco poluente no dia a dia, ainda gera tanta desconfiança pública.</p>

        <p><strong>De onde vem o urânio brasileiro:</strong> O Brasil tem uma única mina de urânio em operação,
        localizada em Caetité, no interior da Bahia — a única mina de urânio de toda a América Latina. Administrada
        pela estatal Indústrias Nucleares do Brasil (INB), que detém o monopólio constitucional da mineração e do
        ciclo do combustível nuclear no país, a mina produz o concentrado de urânio usado como matéria-prima nas
        usinas de Angra dos Reis, reduzindo a dependência brasileira de importação desse mineral estratégico.</p>


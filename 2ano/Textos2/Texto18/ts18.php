        <h2>Áreas de cultivo no Brasil</h2>

        <p>A economia brasileira é fortemente impulsionada pela agropecuária, com recordes na produção de cereais,
            oleaginosas e leguminosas. Principais estados produtores incluem Rio Grande do Sul, Paraná, São Paulo, Minas
            Gerais, Goiás, Mato Grosso e Mato Grosso do Sul. Veja o mapa a seguir:</p>


        <div class="w3-margin"><img id="imagem3" src="ts18f03.png" alt="ts18f03" class="w3-mobile">

            <span class="w3-small w3-margin-left" id="citacao3"> </span>


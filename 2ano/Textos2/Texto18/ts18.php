        <p><strong>Principais Produtos e Áreas Produtoras</strong></p>

        <p><strong>Café:</strong> Cultivado principalmente em Minas Gerais e Espírito Santo, o Brasil é o maior produtor
            e exportador mundial. Plantado inicialmente no Vale do Paraíba, no Rio de Janeiro, expandiu-se para São
            Paulo e norte do Paraná no século XX.</p>

        <p><strong>Cana-de-açúcar:</strong> Introduzida no século XVI, é agora cultivada principalmente no interior de
            São Paulo, além de Minas Gerais e Alagoas. A produção de álcool combustível impulsionou a expansão desde os
            anos 1970.</p>

        <p><strong>Algodão:</strong> Cultivado no Nordeste (algodão arbóreo) e Centro-Sul (algodão herbáceo). Permitido
            desde 2005, o cultivo de algodão transgênico é regulamentado no Brasil.</p>

        <p><strong>Soja:</strong> Inicialmente plantada no Rio Grande do Sul e Paraná, expandiu-se para Minas Gerais,
            Goiás, Mato Grosso do Sul, Mato Grosso e oeste da Bahia. Desde 2023, o Brasil é o maior produtor mundial
            de soja, com uma safra recorde de cerca de 153 milhões de toneladas — mais de 40% de toda a soja produzida
            no planeta, superando os Estados Unidos.</p>

        <p><strong>Laranja:</strong> Principalmente produzida no oeste de São Paulo, com 75% da produção nacional, além
            de Minas Gerais, Espírito Santo e a Baixada Fluminense.</p>

        <p><strong>Cacau:</strong> Principalmente cultivado na Bahia, que responde por 80% da produção nacional.</p>

        <p><strong>Pimenta-do-reino:</strong> Originária da Ásia, é cultivada no Pará e no Vale do Ribeira, em São
            Paulo.</p>

        <p><strong>Uva:</strong> Introduzida pela colonização italiana, é cultivada no Rio Grande do Sul (região
            serrana) e também em São Paulo e Minas Gerais. O Vale do Rio São Francisco é notável pela produção irrigada.
        </p>

        <p><strong>Fumo:</strong> Produzido em Arapiraca (Sergipe) para charutos e em Santa Cruz do Sul (RS) e interior
            de Santa Catarina para cigarros.</p>

        <p><strong>Banana:</strong> Exportada principalmente do Vale do Ribeira, litoral paranaense e Bahia, com
            destaque também para os litorais fluminense e capixaba.</p>

        <p><strong>Feijão:</strong> Cultivado em estados como Paraná, Minas Gerais, São Paulo e Bahia, com destaque para
            o município de Irecê na Bahia.</p>

        <p><strong>Milho:</strong> Produzido em todo o Brasil, especialmente no Paraná, Rio Grande do Sul, Santa
            Catarina e Minas Gerais, utilizado para consumo humano e ração animal.</p>

        <p><strong>Mandioca:</strong> Nativa da Amazônia, é uma lavoura de subsistência com maiores produtores na Bahia,
            Maranhão, Minas Gerais e Rio Grande do Sul.</p>



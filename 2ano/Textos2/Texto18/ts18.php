        <h2>Pecuária brasileira</h2>

        <p>A pecuária e a avicultura são setores importantes nas exportações brasileiras, mas enfrentam desafios,
            principalmente o impacto ambiental do avanço dos pastos em áreas de florestas nativas.</p>

        <p><strong>Sistemas de Criação</strong></p>

        <p>Existem diferentes formas de criação de animais como atividade lucrativa:</p>

        <ul>
            <li><strong>Criação Intensiva:</strong> O gado é criado em confinamento ou em pequenas áreas de pastagem. Os
                animais são geralmente de raças selecionadas, resultando em alta produtividade de leite, carne e couro
                de alta qualidade.</li>
            <li><strong>Criação Extensiva:</strong> Os animais são criados soltos em grandes áreas de pastagem, com
                menores investimentos e rendimento.</li>
            <li><strong>Criação Semiextensiva:</strong> No Brasil, predomina a criação semiextensiva, onde os animais
                são criados em pastos cultivados, mas recebem vacinação e acompanhamento veterinário.</li>
        </ul>

        <p><strong>Tecnologia na Pecuária</strong></p>

        <p>Na pecuária, fatores naturais como pastagens e clima adequado são essenciais, mas a tecnologia desempenha um
            papel crescente na melhoria da produtividade e qualidade da produção animal.</p>

        <p><strong>Avanços Tecnológicos</strong></p>

        <ul>
            <li><strong>Seleção Genética:</strong> Utilização de técnicas de biotecnologia para selecionar e reproduzir
                animais de corte ou leiteiros com maior produtividade, resultando em melhorias qualitativas ao longo das
                gerações. Exames genéticos também são empregados para analisar características hereditárias.</li>
            <li><strong>Inseminação Artificial:</strong> Método que utiliza sêmen de animais selecionados para
                fertilizar a fêmea, aumentando a qualidade genética da cria.</li>
            <li><strong>Fecundação In Vitro:</strong> Processo de fertilização em laboratório, utilizando ovos
                recolhidos de fêmeas e espermatozoides de machos selecionados.</li>
            <li><strong>Clonagem:</strong> Produção em laboratório de indivíduos geneticamente idênticos.</li>
        </ul>

        <p><strong>Adaptação ao Mercado Internacional</strong></p>

        <p>Com a expansão do mercado de carne brasileira no exterior, frigoríficos e proprietários rurais precisam
            ajustar suas práticas aos padrões internacionais.</p>

        <ul>
            <li><strong>Criação Intensiva:</strong> Crescente utilização no setor de gado leiteiro, visando aumentar a
                eficiência produtiva.</li>
        </ul>

        <p><strong><span class="termo" data-palavra="zootecnia" data-definicao="Área dedicada ao estudo da reprodução, genética e nutrição de animais, com foco na produção comercial — diferente da veterinária, voltada à saúde animal.">Zootecnia</span></strong></p>

        <p>Zootecnia é uma área dedicada ao estudo da reprodução, genética e nutrição de animais, com foco na criação
            comercial. Apesar de frequentemente associada à veterinária, sua ênfase está na produção animal para fins
            comerciais.</p>



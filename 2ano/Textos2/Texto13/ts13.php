<h2>Gás Natural </h2>
<p>Também temos o gás natural, que é uma fonte de energia fóssil formada a partir da decomposição de matéria
            orgânica acumulada no subsolo há milhões de anos. Esse processo de decomposição, com o auxílio de altas
            pressões e temperaturas, transformou a matéria orgânica em hidrocarbonetos gasosos, como metano. O gás
            natural é extraído de reservatórios subterrâneos e é utilizado como combustível para gerar energia elétrica
            e calor, além de ser um importante insumo em diversas indústrias. </p>
<div class="w3-panel w3-leftbar w3-pale-yellow w3-margin w3-padding">
<h3><strong>Se Você não sabia, agora já sabe!</strong></h3>
<p>O gasoduto Bolívia-Brasil é uma das maiores infraestruturas de transporte de gás natural da América do
                Sul, conectando a Bolívia, país produtor de gás, ao Brasil, um dos maiores consumidores da commodity na
                região. Foi inaugurado em 1999 e desde então tem sido uma fonte importante de gás para o Brasil.</p>
<div class="w3-margin"><img alt="ts13f07" class="w3-mobile" id="imagem7" src="ts13f07.png"/>
<span class="w3-small w3-margin-left" id="citacao7"> </span>
</div>
<p>No entanto, o gasoduto também tem sido fonte de conflitos políticos e econômicos entre os dois países. Em 1º
                de maio de 2006, o então presidente boliviano Evo Morales decretou a nacionalização da indústria de
                hidrocarbonetos do país, ocupando com tropas as refinarias que a Petrobras operava em território
                boliviano. No ano seguinte, a Petrobras vendeu essas refinarias ao governo boliviano, em um episódio
                que gerou fortes tensões diplomáticas e discussões sobre o preço do gás exportado ao Brasil.</p>
<p>Além disso, há também questões ambientais envolvidas no gasoduto: em seu trecho inicial, no Mato Grosso do
                Sul, ele atravessa áreas do Pantanal, um dos biomas mais sensíveis do país, além de terras cultivadas,
                serras e reservas ecológicas ao longo dos cinco estados por onde passa até chegar ao Rio Grande do Sul.
                Por isso, sua construção exigiu estudos de impacto ambiental e o remanejamento de trechos originais
                para preservar sítios arqueológicos e áreas de comunidades tradicionais.</p>
<p>Em resumo, o gasoduto Bolívia-Brasil é uma infraestrutura importante para o abastecimento de gás no
                Brasil, mas também é uma fonte de conflitos políticos, econômicos e ambientais entre os dois países.</p>
</div>
<p>Petróleo, carvão mineral e gás natural têm algo em comum além de serem combustíveis fósseis: ao serem queimados, todos liberam CO2 e outros gases que se acumulam na atmosfera e intensificam o efeito estufa. Essa é uma das pontes entre a matriz energética que estudamos hoje e o próximo assunto do curso, os climas do Brasil, já que entender de onde vem a energia que movimenta o país também ajuda a entender por que o clima do planeta está mudando.</p>

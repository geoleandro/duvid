<h2 id="centralizado"> Não existe pergunta boba! A Ciência é feita de perguntas!</h2>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

            Por que se fala que a industrialização do Brasil foi dependente?
            </strong> </p>
<p><span class="primeiraLetra">R:</span>

            A <span class="termo" data-palavra="teoria da dependência" data-definicao="Teoria segundo a qual o subdesenvolvimento de países como o Brasil resulta de uma relação de dependência econômica em relação aos países centrais do capitalismo, que compram matérias-primas e vendem produtos industrializados.">teoria da dependência</span> surgiu após o esgotamento da teoria da substituição das importações na era JK, com a entrada de indústrias automotivas internacionais, dentre outras. Essa teoria diz que o subdesenvolvimento dos países como o Brasil, México, África do Sul etc. além do processo de colonização era também resultado do interesse do centro do capitalismo e das elites do próprio país em manter esses países produzindo bens primários.<br/>A ideia é a de que os países subdesenvolvidos, porém industrializados como o Brasil, não estão no mesmo patamar de igualdade com os países desenvolvidos, onde fornecem matérias-primas e recebem produtos industrializados, criando uma relação de dependência.

        </p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

            Quais são as fórmulas econômicas mais utilizadas para industrializar um país?


            </strong></p>
<p><span class="primeiraLetra">R:</span>

            Existem diversas formas de teorizar e aplicar uma fórmula econômica, a depender das regras do sistema proposto. No sistema capitalista, as variáveis giram, grosso modo, em torno do lucro e do trabalho assalariado e pela lei de oferta e procura. Dentro desse sistema, temos, de modo geral, grandes formas e suas variações que englobam várias visões de mundo sobre o que seria um bom caminho para a economia e, consequentemente, para a industrialização. Temos a forma da economia neoliberal e a economia desenvolvimentista.<br/>

            A forma neoliberal baseia-se na suposição de que o mecanismo de preços deveria ser respeitado como o fator determinante da economia. Isso significa que o Estado controlaria o mínimo possível as medidas fiscais e monetárias, por exemplo.<br/>
            
            Por outro lado, temos a visão desenvolvimentista nacionalista, como a de Vargas, O Estado interviria mais diretamente por meio de empresas estatais e das empresas de economia mista, como o Banco do Brasil, no sentido de assegurar as áreas que deveriam receber investimentos.
            

        </p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

            Qual a posição do Brasil perante os outros países do Mundo?

            </strong></p>
<p><span class="primeiraLetra">R:</span>

            Essa questão remete à <span class="termo" data-palavra="Divisão Internacional do Trabalho (DIT)" data-definicao="Forma como os países se especializam e se relacionam na economia mundial, historicamente dividindo-se entre exportadores de produtos industrializados e exportadores de produtos primários.">Divisão Internacional do Trabalho (DIT)</span>, que busca entender como são caracterizados o conjunto de países de acordo com a produção industrial, dentre outras coisas.<br/>

            Até a década de 1960, a velha DIT se referia aos países do Norte como os responsáveis pelo fornecimento de produtos industrializados e os do Sul, pelos produtos primários, como minérios e produtos agrícolas. Com o passar do tempo, surgiram países, como o Brasil, México e Coréia do Sul, Hong Kong, Taiwan, Singapura, Índia, etc. que reorganizaram seu espaço produtivo e foram caracterizados de Países recentemente industrializados.<br/>
            
            Alguns desses países favorecem a entrada de multinacionais em seu território e melhoraram suas exportações. Outros investiram em bens de capital como o Brasil e em infraestrutura. O importante é lembrar que a análise sobre um país está intimamente ligada aos interesses do capitalismo mundial, dos governos locais, dos fatores naturais e das características próprias de cada povo com seu território, não se trata de simples comparação entre um país e outro, pois há história e geografias diferentes entre cada país no mundo.

        </p>
<p>Vale notar que, mesmo depois de décadas de industrialização, o Brasil continua sendo, na balança comercial,
            um grande exportador de commodities: lembre-se da aula sobre recursos minerais, em que vimos que minério de
            ferro, soja e petróleo seguem entre os principais produtos exportados pelo país. Isso mostra que a
            industrialização não elimina de uma vez por todas o papel de fornecedor de matérias-primas que um país
            ocupa na Divisão Internacional do Trabalho, ela apenas se soma a esse papel. O Brasil de hoje exporta ao
            mesmo tempo minério de ferro bruto e aviões fabricados pela Embraer, o que o coloca numa posição híbrida e
            complexa dentro da economia mundial: nem totalmente periférico, nem plenamente central.</p>

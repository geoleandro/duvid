<h2> O relevo brasileiro</h2>
<p>O Brasil é um país de altitude média relativamente baixa, contando com cerca de 40% de todo o território
            nacional abaixo dos 200 m de altitude. Os pontos mais elevados do relevo brasileiro são o Pico da Neblina,
            com 2.995 metros de altitude, e o Pico 31 de Março, com 2.974 metros de altitude, ambos na mesma serra, no Amazonas. </p>
<p> A altitude média do território brasileiro se deve ao país estar localizado sobre uma grande placa tectônica
            livre da possibilidade de se chocar com outras placas, o que torna o Brasil um país imune a sofrer
            terremotos.</p>
<p>Aliás, a medição exata dos pontos mais altos do relevo brasileiro mudou nos últimos anos: por muito tempo o
            Pico da Bandeira, no Espírito Santo, e depois o Pico da Neblina, no Amazonas, disputaram o título de "teto
            do Brasil" com base em medições feitas ainda no século passado. Em 2016, o IBGE recalculou a altitude dos sete picos mais altos do país usando um novo modelo geoidal, mais
            preciso, e o Pico da Neblina "cresceu" 1,52 metro na medição oficial, confirmando de vez seu título de
            ponto mais elevado do Brasil, com os atuais 2.995 metros: um bom lembrete de que até um dado
            aparentemente definitivo, como "o ponto mais alto do Brasil", depende da tecnologia de medição disponível
            em cada época.</p>
<p>Essa combinação entre altitude modesta e relevo antigo e desgastado também explica um traço importante da
            matriz energética brasileira. Onde um planalto termina de forma abrupta e cede lugar a uma planície,
            formam-se quedas d'água e desníveis expressivos no curso dos rios, exatamente o tipo de energia potencial
            que uma usina hidrelétrica precisa para funcionar. Não é coincidência que boa parte das grandes usinas do
            país, de Itaipu a Belo Monte, esteja construída sobre esses degraus do relevo, nas bordas de planaltos ou
            nos trechos encachoeirados dos grandes rios. O relevo brasileiro, ao mesmo tempo antigo e desgastado, é
            um dos motivos pelos quais o Brasil conseguiu construir uma matriz elétrica majoritariamente renovável,
            apoiada em hidrelétricas, algo raro entre as grandes economias do mundo.</p>
<p>Podemos dizer em resumo do relevo brasileiro, que ele se dá em: </p>
<div class="w3-panel w3-leftbar w3-sand w3-margin w3-padding">
<p>• Planaltos: Áreas com elevação e aplanadas, caracterizadas por declives onde o processo de desgaste
                erodido é maior do que o acúmulo sedimentar. </p>
<p>
                • Planícies: áreas moderadamente planas, nas quais o processo de depósito de sedimentos é maior que o de
                desgaste.
            </p>
<p>
                • Depressão Relativa: áreas situadas acima do nível do mar, mas abaixo de regiões que lhe são próximas.
            </p>
</div>

<h2 id="centralizado"> Não existe pergunta boba! A Ciência é feita de perguntas!</h2>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

                Quais as características da estrutura geológica do Brasil?
            </strong> </p>
<p><span class="primeiraLetra">R:</span> O território brasileiro é formado por estruturas geológicas antigas.
            Trata-se de um conjunto de rochas que servem de alicerce para o território. Suas idades geológicas vão desde
            Paleozoico ao Mesozoico em relação as bacias sedimentares e do Pré-Cambriano (Arqueozoico-Proterozóico) para
            os terrenos cristalinos.</p>
<p>Já o relevo brasileiro é um pouco mais recente (isso considerando milhões de anos). Isso quer dizer que o
            relevo continua sendo desgastado pelos agentes de erosão e ele tem relação com as rochas antigas e com as
            transformações que ocorram a partir do Mesozoico, como a criação das cordilheiras andinas e da própria
            abertura do continente Atlântico na época da separação da Pangeia.</p>
<p>Portanto, a estrutura geológica do Brasil é marcada pelos crátons, pelos dobramentos antigos e pelas grandes
            bacias sedimentares.</p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>Qual a diferença entre Crátons e Escudos
                cristalinos? </strong></p>
<p><span class="primeiraLetra">R:</span> A diferença é que os Escudos cristalinos estão expostos a processos
            erosivos. Já as áreas cratônicas estão subjacente (por baixo) de bacias sedimentares, por exemplo. Vamos
            fazer uma analogia com uma cama. O colchão são as rochas magmática ou metamórficas (Crátons). O forro de
            cama, aquele com elástico seria a bacia sedimentar. As vezes o colchão fica exposto e pode sofrer ação do
            tempo, este seria o escudo cristalino. Veja na imagem abaixo um exemplo na bacia do Amazonas:

        </p>
<div class="w3-margin"><img alt="ts05f013" class="w3-mobile" id="imagem13" src="ts05f013.png"/>
<span class="w3-small w3-margin-left" id="citacao13"> </span>
</div>
<p>Os crátons e as plataformas (crátons recobertos por bacias sedimentares) formam a base sobre a qual se
            assenta o território brasileiro.</p>
<p>Há três importantes formações de crátons na porção continental do Brasil:</p>
<div class="w3-panel w3-sand w3-leftbar w3-margin w3-padding">
<p>- província da <strong>Guiana Meridional</strong>, situada no extremo norte, abrangendo os Estados do
                Amazonas, Roraima e Amapá, possui altitudes elevadas;</p>
<p>- <strong>Xingu</strong>, localizada na porção sul das terras amazônicas, nos Estados de Rondônia, Mato
                Grosso, Pará e sul do Amazonas, apresentam altitudes medianas;</p>
<p>- crátons de<strong> São Francisco</strong> Minas Gerais e Bahia.</p>
</div>
<p>Os escudos cristalinos foram formados há mais de 2 bilhões de anos no Pré-Cambriano, estiveram sujeitos a
            dobramentos, são eles: os cinturões do Atlântico que se estendem desde a parte leste do Nordeste até o
            sudeste do Rio Grande do Sul; a porção de Brasília, com áreas ao sul de Tocantins até o sudeste de Minas
            Gerais e o cinturão orogênico do Paraguai-Araguaia, que ocupa terras de Goiás, Tocantins e Mato Grosso, este
            o mais erodido. </p>
<p>Os escudos cristalinos são áreas de exploração de minérios e corresponde a 36% do território nacional.</p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

                Qual a importância das bacias sedimentares?

            </strong></p>
<p><span class="primeiraLetra">R:</span>

            As bacias sedimentares corresponde a 64% do território brasileiro e são basicamente três: a bacia Amazônica,
            com petróleo e gás natural de difícil acesso devido a longa compactação de suas camadas; a bacia do
            Parnaíba, com importantes reservas de água subterrânea e carvão mineral; e a bacia do Paraná com exposição
            de enormes derrames de lava vulcânica que deram origem a solos extremamente férteis chamados de terra roxa.
        </p>
<p>As bacias sedimentares foram formadas há mais de 500 milhões de anos a partir de sedimentos e fósseis. Muitos
            fósseis são de peixes e conchas marinhos, pois durante a era Paleozoica, extensas áreas do território da
            América do Sul estavam submersas por águas, fenômeno conhecido como “mar Devoniano”.</p>
<p>Nas áreas de bacias sedimentares devido a decomposição incompleta de seres vivos, animais e vegetais, e após
            milhões de anos recobertos por sedimentos, há grande possibilidade de se encontrar petróleo, gás natural ou
            carvão mineral, uma das razões para o seu estudo.</p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

                O que é o pré-sal e por que ele é tão importante para o Brasil?

            </strong></p>
<p><span class="primeiraLetra">R:</span>

            O
            <span class="termo" data-palavra="Pré-sal" data-definicao="Camada de rochas sedimentares localizada a grandes profundidades no fundo do oceano, abaixo de uma espessa camada de sal, onde ficaram aprisionadas enormes reservas de petróleo e gás natural de excelente qualidade. No Brasil, concentra-se principalmente nas bacias de Santos e Campos.">pré-sal</span>
            é uma camada de rochas sedimentares que se formou há mais de 100 milhões de anos, quando a
            América do Sul e a África ainda estavam se separando. Enormes quantidades de matéria orgânica ficaram
            represadas em lagos que, com o avanço do mar, foram recobertos por uma grossa camada de sal, formando uma
            espécie de tampa natural que preservou o petróleo por dezenas de milhões de anos, a mais de 5 ou 7 mil
            metros de profundidade, entre a camada de sal e o leito rochoso do oceano.
        </p>
<p>A descoberta comercial do pré-sal ocorreu em 2006, na Bacia de Santos, e a primeira produção começou em 2009,
            no campo de Tupi. Hoje ele já responde por cerca de 80% de toda a produção de petróleo e gás da Petrobras,
            com destaque para os campos gigantes de Tupi, Búzios e Mero. O petróleo do pré-sal é tão relevante que,
            puxado por ele, o petróleo se tornou o principal produto da pauta de exportações brasileira nos últimos
            anos, superando até mesmo a soja em determinados períodos.</p>
<p>Extrair petróleo a essa profundidade, atravessando quilômetros de água do mar, depois a camada de sal e só
            então alcançando o reservatório, é um dos maiores desafios de engenharia offshore do mundo. O Brasil
            desenvolveu tecnologia própria para isso, e a exploração do pré-sal é hoje motivo de orgulho técnico, mas
            também de debate: o país precisa decidir como usar essa riqueza mineral não renovável, seja investindo os
            royalties em educação e saúde, seja equilibrando sua matriz energética diante da urgência climática
            discutida nas aulas sobre mudanças climáticas.</p>
<p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>

                Existe uma reserva de água escondida sob as bacias sedimentares do Brasil?

            </strong></p>
<p><span class="primeiraLetra">R:</span>

            Sim, e ela é gigantesca. O
            <span class="termo" data-palavra="Aquífero Guarani" data-definicao="Um dos maiores reservatórios de água doce subterrânea do mundo, formado por rochas sedimentares porosas que armazenam água entre as camadas de arenito. Estende-se por Brasil, Argentina, Paraguai e Uruguai, principalmente sob a Bacia do Paraná.">Aquífero
                Guarani</span> é um dos maiores reservatórios subterrâneos de água doce do planeta, formado
            justamente nas rochas porosas da Bacia do Paraná, protegido por baixo dos derrames basálticos que também
            deram origem à terra roxa. Ele se estende por cerca de 1,2 milhão de km² sob o território de quatro
            países (Brasil, Argentina, Paraguai e Uruguai), sendo que cerca de dois terços de sua área ficam em solo
            brasileiro. Suas reservas de água somam algo em torno de 30 mil km³, o suficiente para abastecer a
            população da região por séculos, se explorado de forma sustentável.</p>
<p>O Aquífero Guarani é usado hoje sobretudo para abastecimento urbano em cidades do interior de São Paulo,
            Paraná e Rio Grande do Sul, além de estâncias hidrotermais como Águas de São Pedro e Termas de Rio
            Quente, onde a água emerge naturalmente aquecida pelo calor da própria Terra. Justamente por ser um
            recurso hídrico transfronteiriço, sua gestão exige cooperação internacional entre os quatro países que o
            compartilham, o que o transforma também num caso interessante de geopolítica da água.</p>

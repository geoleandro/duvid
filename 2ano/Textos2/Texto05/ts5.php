<p>Todas essas formas de relevo não são apenas curiosidade geológica: elas moldam diretamente onde e como a
            população brasileira ocupou o território. Os planaltos, por exemplo, concentram a maioria das grandes
            metrópoles do Centro-Sul (São Paulo, Belo Horizonte, Curitiba), porque oferecem clima mais ameno e solos
            estáveis para construção. As planícies costeiras, por sua vez, atraíram desde cedo os portos e as
            primeiras cidades coloniais, exatamente como vimos na aula sobre a formação do território brasileiro, já
            que oferecem acesso direto ao mar. Já as depressões, embora menos vistosas, favoreceram historicamente a
            agropecuária extensiva, sobretudo a pecuária, por reunirem grandes extensões de terrenos rebaixados e
            relativamente planos. Entender o relevo, portanto, é entender também por que o mapa de cidades, estradas
            e atividades econômicas do Brasil tem a cara que tem.</p>

<h2> O espaço geográfico: entre análise e síntese</h2>
<p>Desde a formação do Brasil e a consolidação do seu território, seu povoamento e a repartição de suas terras,
            estamos vendo alguns aspectos da realidade. Porém, todos esses acontecimentos, esses eventos ocorrem de
            forma simultânea, uns mais rápidos, outros mais lentos. </p>
<p> Na Ciência, temos que fazer uma divisão (análise) dos temas para depois realizar uma junção de tudo
            (síntese).</p>
<p>O espaço geográfico é um só, ele é composto por objetos naturais e sociais, mas é, grosso modo, formado por
            várias camadas. A estrutura geológica e as formas de relevo constituem mais uma dessas camadas. Elas
            pertencem a geografia física, assim como o clima, a vegetação, a hidrografia, dentre outras. </p>
<p> Esses elementos combinam-se e, devido a extensão do território brasileiro, acabam por constituir diferentes
            paisagens naturais. </p>
<p>Nessas paisagens o clima e o solo influenciam a vegetação, que por sua vez é influenciado pelo relevo e o
            solo depende da estrutura geológica que serve de base para o nosso espaço habitado. </p>

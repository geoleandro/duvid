<h2> ...mais sobre a estrutura geológica do Brasil</h2>
<p> Desde a separação dos continentes da Pangeia há mais de 65 milhões de anos, o Brasil sofreu impacto dessa
            separação entre África e América, formação das cordilheiras e do atual contorno do continente americano.</p>
<p> Um deles diz respeito ao vulcanismo. Os grandes derrames de lava em Poços de Caldas e Araxá (MG), São
            Sebastião (SP), Itatiaia e Cabo Frio (RJ) e Lajes (SC). No Sul (SP até RG) grande derrame basáltico na bacia
            do Paraná (origem dos solos Terra-Roxa), Bacia Amazônica e Parnaíba).</p>
<p>Vale reforçar essa ligação entre a lava basáltica antiga e a economia atual, porque ela é um ótimo exemplo de
            como a estrutura geológica influencia diretamente a vida das pessoas séculos depois. Aqueles imensos
            derrames de lava que cobriram boa parte do interior paulista, do norte do Paraná e do oeste de Minas
            Gerais, há mais de 130 milhões de anos, se decompuseram ao longo do tempo geológico e deram origem à
            chamada terra roxa: um solo escuro, avermelhado, rico em ferro e magnésio e muito fértil. Foi justamente
            sobre essa terra roxa, e não por acaso, que se desenvolveu boa parte da cafeicultura paulista do século
            XIX, que vimos na aula sobre a formação do território brasileiro. A geologia de 130 milhões de anos atrás
            ajudou a decidir, portanto, onde ficariam as fazendas de café que sustentaram a economia brasileira num
            período inteiro da nossa história.</p>
<p> O que acontece se sobrepormos a estrutura geológica com seus escudos cristalinos e bacias sedimentares com
            as variações de altitude do relevo?</p>

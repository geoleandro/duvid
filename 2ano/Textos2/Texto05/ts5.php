<p>Chapadas, planalto com altitude com mais de 500 metros. Famosos: Chapada Diamantina (sul da Bahia) Chapada
            dos Guimarães (MT) e Veadeiros (GO). </p>
<p>A Chapada Diamantina é um bom exemplo de como esse tipo de relevo também carrega história econômica. As
            rochas sedimentares antigas da região concentram diamantes que passaram a ser explorados de forma
            intensa a partir da década de 1840, atraindo garimpeiros para cidades como Lençóis, Mucugê e Andaraí.
            Entre 1845 e 1871, Lençóis chegou a ser a maior produtora de diamantes do mundo, riqueza que atraiu
            comerciantes europeus e rendeu à cidade até um vice-consulado francês. O ciclo entrou em declínio no
            fim do século XIX, quando jazidas maiores foram descobertas na África do Sul, mas o legado urbano e
            arquitetônico do garimpo permanece nos casarios históricos da região, hoje parte do Parque Nacional da
            Chapada Diamantina.</p>
<p> Pediplano: é o processo que leva, em regiões de clima árido a semiárido, ao desenvolvimento de áreas

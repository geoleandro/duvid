<h2> Eventos geológicos no Brasil</h2>
<p> Vale lembrar os acontecimentos geológicos que ocorreram no Brasil.</p>
<p>Na era Pré-Cambriana e Arqueozoica e Proterozoica ocorreram a formação dos escudos cristalinos, junto com o
            acúmulo de jazidas minerais metálicas. Foi nesse período que se formou a Serra do Mar e da Mantiqueira. </p>
<p>Na era Paleozoica formaram-se as bacias sedimentares antigas e as bacias carboníferas do sul do país. </p>
<p>Na era Mesozoica ocorreram os derrames de rochas basálticas na Região Sul, a formação do petróleo e das
            bacias sedimentares mais atuais. </p>
<p> E na última era, a Cenozoica, as bacias sedimentares do Pantanal, da Amazônia e planícies costeiras. Além
            das ilhas vulcânicas como do Arquipélago de Fernando de Noronha, Ilha Trindade, dentre outras.</p>
<p>Essas ilhas vulcânicas merecem uma explicação à parte, porque não se formaram do mesmo jeito que os
            derrames de lava do continente. Fernando de Noronha e a Ilha da Trindade nasceram sobre o que os geólogos
            chamam de ponto quente: uma região do manto terrestre onde o calor interno é anomalamente concentrado e
            perfura a crosta oceânica de baixo para cima, formando vulcões isolados no meio do oceano, sem relação
            direta com os limites das placas tectônicas. Como a Placa Sul-Americana se desloca lentamente sobre esse
            ponto quente ao longo de milhões de anos, formou-se uma cadeia de montanhas submarinas, com as ilhas mais
            antigas mais distantes da posição atual do ponto quente e as mais jovens mais próximas dele. Fernando de
            Noronha, hoje Patrimônio Natural da Humanidade pela Unesco, tem rochas vulcânicas formadas em dois
            grandes episódios eruptivos, um entre 8 e 12 milhões de anos atrás e outro bem mais recente, há cerca de
            1,7 milhão de anos, enquanto a Ilha da Trindade, no Espírito Santo, é ainda mais jovem. Ambas concentram
            ecossistemas únicos, com aves marinhas, tartarugas e recifes que não existem no litoral continental, e
            por isso são hoje áreas de proteção ambiental rigorosamente controladas.</p>

        <h2 id="centralizado"> Não existe pergunta boba! A Ciência é feita de perguntas!</h2>

        <p><strong>Um mosaico de vegetações:</strong> Se olharmos para os cinco domínios que estudamos nesta aula,
            fica claro que a vegetação brasileira não é uma coisa só: a Mata dos Cocais é uma zona de transição
            dominada por palmeiras; o Pantanal é uma planície moldada pelo ritmo das águas; o Cerrado é uma savana
            que também funciona como reservatório hídrico do país; a Caatinga é um bioma exclusivamente brasileiro,
            adaptado à seca extrema; e os Pampas são campos temperados que ultrapassam nossas fronteiras. Apesar
            dessas diferenças enormes, todos os cinco compartilham um mesmo destino: estão sob forte pressão do
            avanço agropecuário, e nenhum deles recebe, proporcionalmente, o mesmo nível de proteção legal e de
            atenção pública que a Amazônia costuma receber — o que ajuda a explicar por que tanto o Cerrado quanto
            os Pampas figuram, hoje, entre os biomas mais desmatados do Brasil.</p>

        <p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>
                Qual é a situação atual do Cerrado em relação à sua cobertura original e qual é o impacto do
                agronegócio nessa região?
            </strong> </p>
        <p><span class="primeiraLetra">R:</span>
            Segundo dados do IBGE e do MapBiomas, o Cerrado já perdeu cerca de metade de sua cobertura vegetal
            nativa. O agronegócio, especialmente o plantio da soja, tem desempenhado um papel significativo na
            transformação dessa região. A expansão das fronteiras agrícolas tem levado à conversão de matas nativas
            em grandes áreas de monocultura, conhecidas como <span class="termo" data-palavra="desertos verdes" data-definicao="Expressão usada para grandes áreas de monocultura (como soja ou eucalipto) que, apesar de verdes, sustentam pouquíssima biodiversidade em comparação com a vegetação nativa que substituíram.">"desertos verdes"</span>, o que resulta na perda de
            biodiversidade e na degradação dos ecossistemas naturais do Cerrado.
        </p>

        <p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span> <strong>
                Como o clima e a pluviosidade do Pantanal influenciam as inundações periódicas, e quais são as
                causas dessas inundações?
            </strong></p>
        <p><span class="primeiraLetra">R:</span>
            No Pantanal, os índices de pluviosidade são, na verdade, inferiores aos verificados na maior parte da
            região Centro-Oeste — é o segundo bioma brasileiro mais seco, atrás apenas da Caatinga. As inundações
            periódicas nessa região são explicadas muito mais pela topografia plana da Bacia do rio Paraguai do que
            pelo volume das chuvas. As chuvas, concentradas entre novembro e março (cerca de 70% do total anual),
            somadas a essa topografia praticamente plana, fazem a água se espalhar lentamente pela planície ao invés
            de escoar, formando as extensas áreas alagadas características do Pantanal.
        </p>

        <p class="w3-border w3-round-large w3-padding"> <span class="primeiraLetra">P:</span><strong>
                Quais são os principais conflitos que surgem no Cerrado e nos Pampas devido às práticas agrícolas e ao
                uso da terra?
            </strong>
        </p>
        <p><span class="primeiraLetra">R:</span>
            No Cerrado, os principais conflitos envolvem camponeses e pequenos agricultores que enfrentam a expansão
            do agronegócio, que muitas vezes leva à desapropriação de terras e à degradação ambiental. Nos Pampas, a
            vegetação é composta por gramíneas em uma área de clima subtropical, e a eliminação da cobertura vegetal
            para a prática agrícola pode levar a processos de arenização, que é a transformação do solo em areia.
            Essa degradação do solo pode reduzir a produtividade agrícola e causar conflitos entre agricultores e
            defensores da conservação ambiental.
        </p>


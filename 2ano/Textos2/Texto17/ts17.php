        <h2>Pantanal</h2>

        <div class="w3-margin"><img id="imagem3" src="ts17f03.png" alt="ts17f03" class="w3-mobile" >
		   
            <span class="w3-small w3-margin-left" id="citacao3" > Fonte: Wikipedia. </span>
            
            </div>

        <p><strong>Localização e Características Gerais:</strong></p>
        <p>O Pantanal é a maior planície alagada do mundo, situado principalmente nos estados do Mato Grosso e Mato
            Grosso do Sul, além de partes menores na Bolívia e Paraguai. Este bioma é caracterizado por sua vasta rede
            de rios, lagoas e áreas alagadiças. Seu funcionamento ecológico é regido pelo chamado pulso de
            inundação: durante o verão, o excesso de água dos rios que descem do planalto se espalha lentamente pela
            planície, alagando-a por meses; no inverno seco, as águas recuam e deixam para trás lagoas temporárias
            (as baías) e pastagens naturais extremamente férteis. É justamente essa alternância entre cheia e seca
            que sustenta a riqueza de vida do Pantanal e explica por que, apesar de estar cercado por Cerrado ao
            norte e leste, ele mantém uma dinâmica hídrica própria e completamente diferente.</p>

        <p><strong>Vegetação Predominante:</strong></p>
        <p>A vegetação do Pantanal é uma combinação de espécies de cerrado, floresta amazônica e <span class="termo" data-palavra="Chaco boliviano" data-definicao="Região de vegetação seca e arbustiva que se estende pela Bolívia, Paraguai e Argentina, contribuindo com espécies vegetais adaptadas à seca para a flora do Pantanal.">chaco boliviano</span>,
            incluindo gramíneas, arbustos e árvores esparsas.</p>

        <p><strong>Interferência Humana e Impactos:</strong></p>
        <p><strong>Pecuária Extensiva:</strong> A criação de gado é a principal atividade econômica, causando alterações
            no solo e na vegetação. Ao contrário do que ocorre em outros biomas, a pecuária pantaneira tradicional é
            considerada relativamente compatível com a conservação: o gado se alimenta das pastagens naturais que
            surgem durante a vazante, sem a necessidade de desmatamento extensivo, o que fez do Pantanal um dos
            biomas brasileiros historicamente menos desmatados. Esse equilíbrio, no entanto, vem sendo pressionado
            pela conversão de áreas naturais em pastagens plantadas e pelo avanço da soja no entorno da planície.</p>

            <div class="w3-margin"><img id="imagem4" src="ts17f04.png" alt="ts17f04" class="w3-mobile" >
		   
                <span class="w3-small w3-margin-left" id="citacao4" > Fonte: www.brasil.com </span>
                
                </div>
            




        <p><strong>Queimadas e Desmatamento:</strong> Práticas de manejo inadequado e queimadas sazonais contribuem para
            a degradação do ecossistema. Em 2020, o Pantanal viveu o pior ano de incêndios de sua história recente:
            os focos de fogo consumiram cerca de 45 mil km², ou pouco mais de 30% da porção brasileira do bioma —
            140% a mais do que em 2019 — resultado de uma seca severa (chuvas até 50% abaixo da média entre janeiro e
            maio) somada a queimadas de origem humana que fugiram de controle. Estima-se que quase 17 milhões de
            animais vertebrados tenham morrido nesses incêndios, entre eles antas, onças-pintadas e araras-azuis.</p>
        <p><strong>Biodiversidade:</strong> Apesar da pressão ambiental, o Pantanal continua sendo um dos ambientes
            com maior concentração de vida selvagem visível da América do Sul, abrigando a maior população de
            onças-pintadas do continente, além de capivaras, jacarés-do-pantanal, araras-azuis e centenas de espécies
            de aves aquáticas — o que faz da região um destino de referência mundial para o ecoturismo de observação
            de fauna.</p>
        <p><strong>Turismo Sustentável:</strong> A promoção de turismo ecológico tem surgido como uma alternativa
            econômica e ambientalmente sustentável. Roteiros de observação de fauna, como os voltados para avistar
            onças-pintadas na região da Bacia do Rio Cuiabá, têm mostrado que um animal vivo, observado por turistas
            ano após ano, pode gerar mais renda ao longo do tempo do que a pecuária ou o desmatamento pontual — um
            argumento econômico que vem ganhando força entre pesquisadores e comunidades locais como estratégia de
            conservação de longo prazo.</p>


            <h2>O papel da imigração no Brasil </h2>

            <p>A matriz étnica branca no Brasil foi formada por diversos povos, mas sobretudo pela população europeia. </p>

            <p>No período colonial, além dos portugueses, entraram no Brasil espanhóis, holandeses, franceses, ingleses e
                italianos. </p>

            <p>Após a independência do Brasil houve uma nova entrada maciça de imigrantes, principalmente entre 1850 e
                1934, que se instalaram em diversas regiões do país. Os principais são: </p>

            <p><strong>Portugueses</strong>: desde a colonização, os portugueses, o grupo mais numeroso, contribuíram para
                a formação do povo brasileiro com a mistura com indígenas e negros. Nos grandes centros urbanos,
                principalmente Rio de Janeiro e São Paulo, a presença de portugueses é mais numerosa. </p>

            <p><strong>Italianos</strong>: depois dos portugueses, o outro grupo mais numeroso a imigrar para o Brasil.
                Grande parte veio para São Paulo, mas um número expressivo também para o Rio Grande do Sul (especialmente
                Bento Gonçalves, Garibaldi, Caxias do Sul), Santa Catarina (Nova Trento, Nova Veneza), o Paraná e o Rio de
                Janeiro. </p>

            <p><strong>Espanhóis</strong>: o terceiro grupo mais numeroso dentro do grupo branco no país. Distribuídos
                principalmente em São Paulo e, em menor proporção, no Rio de Janeiro, em Minas Gerais e no Rio Grande do
                Sul.</p>

            <p>Há outros grupos brancos de origem europeia que também se destacam na população brasileira. São eles:</p>

            <p><strong>Alemães</strong>: os imigrantes alemães foram alocados principalmente no Sul do Brasil, nos Estados
                de Santa Catarina (Blumenau, Joinville) e no Rio Grande do Sul (São Leopoldo, Novo Hamburgo). Há pequenos
                grupos em São Paulo, no Paraná e no Espírito Santo.</p>

            <p><strong>Eslavos</strong>: o povo eslavo é oriundo de países como Polônia, Rússia e Ucrânia, com
                predominância no Paraná, nas cidades de Curitiba e Ponta Grossa.</p>

            <p>Muitos imigrantes vieram da Ásia. Os principais são:</p>

            <p><strong>Sírio-libaneses</strong>: o Brasil possui milhões de descendentes de sírios e de libaneses. De
                língua árabe, a maioria cristã, mas há muitos muçulmanos também. Dedicam-se principalmente ao comércio, e
                há muitos políticos brasileiros com essa origem.</p>

            <p><strong>Japoneses</strong>: estima-se que quase 2 milhões de japoneses e descendentes vivam no Brasil, que
                abriga a maior comunidade japonesa fora do Japão. Estão radicados principalmente em São Paulo e no norte do
                Paraná (Londrina e Maringá), mas também no Mato Grosso, no Pará e no Amazonas. A maioria iniciou nas
                atividades agrícolas, ligadas ao plantio de hortaliças, além de arroz e algodão.</p>

            <p><strong>Chineses</strong>: calcula-se que a população total de chineses no Brasil seja de 250 a 300 mil
                habitantes. Desde a década de 1990 os números aumentaram bastante, principalmente nos grandes centros como
                Rio de Janeiro e São Paulo, nas atividades de comércio e alimentação.</p>

            <p><strong>Coreanos</strong>: mais recente e em menor número (50 mil), a comunidade coreana está concentrada
                na capital paulista, São Paulo.</p>


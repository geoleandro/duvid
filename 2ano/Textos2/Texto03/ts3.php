            <h2>A importância do Censo Demográfico </h2>

            <p>O instrumento utilizado para levantar os dados sobre a população brasileira e a realidade do território é o
                <span class="termo" data-palavra="Censo Demográfico" data-definicao="Levantamento periódico, realizado pelo IBGE, que conta a população de um país e coleta informações sobre suas características (idade, cor, escolaridade, renda, moradia etc.). No Brasil, é feito a cada dez anos e envolve milhares de recenseadores.">Censo
                    Demográfico</span>.</p>

            <p>O IBGE é o órgão responsável pelo Censo. É um processo longo e envolve milhares de pessoas, dentre elas os
                recenseadores. O Censo é o processo de contar e obter informações sobre as características dos habitantes de
                um país. </p>

            <p>O recenseador visita a casa de todos os brasileiros, vestido com um jaleco azul e com a identificação do IBGE,
                e anota em seu aparelho eletrônico algumas questões. Há uma pesquisa simples e outra, por amostragem, mais
                aprofundada. Na primeira, é perguntada a idade, a cor da pele (com opções entre branco, pardo, preto, amarelo
                ou indígena), o grau de escolaridade, além de questões sobre saneamento básico, número de banheiros, renda,
                dentre outras. No questionário completo, as questões possuem mais opções, como tipo e características do
                domicílio, religião, pessoas com deficiência residentes, trabalho e rendimento etc. </p>

            <p>Há outros questionários importantes, como os sobre características do entorno: pavimentação das ruas,
                circulação, existência de calçadas e arborização. Também existe um questionário específico para a população
                indígena, sobre características e infraestrutura das aldeias e escolaridade. </p>

            <p>Quase todos os países fazem, com regularidade, seus censos demográficos a cada década: contam seus
                habitantes e obtêm informações que permitem identificar suas características (sexo, idade, cor, religião,
                migração, educação, trabalho, entre outras), conhecer em detalhes as condições em que vive a população e os
                seus níveis de desenvolvimento socioeconômico, assim como traçar um retrato abrangente e fiel da realidade
                nacional. </p>


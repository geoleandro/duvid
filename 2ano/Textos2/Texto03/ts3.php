            <h2> A população negra no Brasil</h2>

            <p>Estima-se que 4,8 milhões de africanos foram transportados para o Brasil e vendidos como escravos, ao longo
                de mais de três séculos. Outros 670 mil morreram no caminho, entre as mais de 9 mil viagens de navios entre
                o Brasil e o continente africano, nas mais desumanas condições. </p>

            <p>Todo o processo de escravização dos africanos pelos colonizadores e seu uso como mão de obra foi marcado
                pela desumanidade. </p>

            <p>As línguas e a cultura africanas foram quase totalmente extirpadas de cada grupo que chegava ao Brasil.
                Bantos, fulas ou kanembus eram proibidos, inclusive, de conviver na mesma vila. </p>

            <p>Aliás, o próprio desenvolvimento do capitalismo, a escravidão e o nascimento de um novo tipo de economia
                internacional devem ser analisados em conjunto. </p>

            <p>Por que escravizar outros seres humanos, em vez de contratar trabalhadores livres assalariados? </p>

            <p>Porque o Brasil estava inserido na política mercantilista da época, ou seja, enriquecer a metrópole através
                da produção de gêneros tropicais e da extração de metais preciosos com baixo custo. </p>

            <p>Dado o tamanho do território brasileiro, com milhões de hectares de terras disponíveis, os europeus não
                precisariam trabalhar para ninguém, bastando cultivar a própria terra, se essa fosse a única questão em
                jogo. </p>

            <p>O objetivo principal era o lucro que o tráfico de escravos proporcionava com o transporte de seres humanos
                da África para a América. Havia distinções entre a escravidão indígena e a africana: características de
                cada etnia, além da preocupação política da Metrópole com a possibilidade de revoltas dos colonos no
                Brasil. </p>

            <p> Com a Revolução Industrial, iniciada no século XVIII e intensificada no século XIX, as máquinas aumentaram
                a produtividade capitalista a tal ponto que foi necessário ampliar o mercado consumidor. Por isso, segundo
                os historiadores, o Reino Unido decidiu pôr fim ao comércio de escravos em suas colônias a partir de 1807 e
                pressionou pelo fim do tráfico em todo o mundo. Portugal e Brasil foram os países que mais resistiram. No
                Brasil, o tráfico negreiro foi proibido em 1850 e a escravidão em 1888, o último país das Américas a tomar
                essa decisão.</p>


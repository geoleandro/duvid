                silvícolas e os campineiros, e com os negros africanos, uns e outros aliciados como escravos.</p>

            <p><strong>Duvid:</strong> E de tudo isso, podemos dizer que surgiu, deste lado do Atlântico, um povo distinto
                do europeu? Por quais razões?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Há dois processos nessa formação. O primeiro é o surgimento de um povo
                novo. Entretanto, há, em segundo lugar, a manutenção do velho. Vou tentar ser mais claro. O povo novo nasce
                dessas culturas e matrizes raciais tão distintas, uma etnia diferenciada, mestiça. Um tipo de gente nova,
                porque assim é vista por si mesma e pelos outros. Mas também é um povo velho, pois está ligado à exploração
                externa, dirigida pela expansão europeia para gerar lucros para a metrópole. O Brasil é, em resumo, um
                mutante: possui características próprias, mas está, desde sua gênese, ligado à matriz portuguesa.</p>

            <p><strong>Duvid:</strong> Professor, como ocorreu, na sua visão, esse choque entre diferentes mundos, o do
                europeu e o dos habitantes das Américas?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Imagine a chegada, além-mar, de um grupo pequeno mas superagressivo e
                capaz de destruir, sob diversas formas, principalmente por infecções, a população indígena existente. Os
                conflitos surgiram em diversos níveis. No plano biológico, com as bactérias trazidas pelos europeus e que
                eram mortais para a população indígena. No ecológico, pela disputa do território, suas matas e riquezas
                para outro uso. No econômico e social, pela escravização do índio, pela mercantilização das relações de
                produção que uniu esses dois mundos: o europeu, velho mundo, e o brasileiro, como provedor de gêneros
                exóticos, escravos, ouro etc.</p>

            <p><strong>Duvid:</strong> ... e os indígenas foram os primeiros a sentir na pele a grande mudança que estava
                prestes a acontecer?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Exatamente. Para os indígenas, com toda sua espiritualidade aflorada,
                a chegada dos europeus foi algo espantoso, uma verdadeira visão mítica do mundo. As tribos não possuíam essa
                característica de classe, tampouco uma visão da vida marcada por relações comerciais. Após alguns anos,
                viram-se inseridos na maior tragédia possível: destruição das bases de sua vida social, negação de seus
                valores, cativeiro, trabalho forçado etc. Grande parte morria de tristeza, certos de que não poderiam mais
                viver naquela situação.</p>

            <p><strong>Duvid:</strong> Professor, de acordo com suas pesquisas, o que estava por trás de toda essa violência
                que ocorreu com a invasão do Brasil?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Em um contexto mais amplo, os portugueses (e também os espanhóis)
                tinham acabado de se livrar da ocupação secular dos árabes e tinham expulsado os judeus de seus
                territórios. A expansão marítima, fruto da guerra por conquista, do saqueio e da evangelização sobre os
                povos da África, da Ásia e, principalmente, das Américas, consolidou o primeiro sistema econômico mundial,
                que unificaria Portugal e Espanha e, ao mesmo tempo, interrompia o desenvolvimento autônomo, a alegria e as
                culturas originais dos povos que aqui viviam.</p>

            <p><strong>Duvid:</strong> E esse sistema foi forjado a partir do escravagismo?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong> ... e por meio da miscigenação. A escravidão indígena predominou ao
                longo de todo o primeiro século. Somente no século XVII a escravidão negra viria a ultrapassá-la. Os
                indígenas eram utilizados principalmente para produção de subsistência, como preparo de alimentos, caça e
                pesca. A escravatura negra era preferível para a produção mercantil de exportação. Dessa mistura de brancos
                e índios surgem os mamelucos, que foram fundamentais para o domínio português terra adentro.</p>

            <p><strong>Duvid:</strong> E a maioria dos negros foi trazida de quais países?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>De modo geral, os negros do Brasil foram trazidos principalmente da
                costa ocidental africana. Podemos dividi-los em três grandes grupos com culturas diversas: 1) os de cultura
                sudanesa, provenientes da Gâmbia, Serra Leoa e Costa do Marfim; 2) o grupo de cultura islamizada do norte da
                Nigéria, que se instalou na Bahia e no Rio de Janeiro, por exemplo; 3) as tribos bantos, do grupo
                congo-angolês, de Angola e Moçambique. </p>

            <p><strong>Duvid:</strong> Como se deu essa adaptação dos africanos nessa sociedade emergente do Brasil?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Os negros foram forçados a se incorporar passivamente ao universo
                cultural dessa nova sociedade. Eles foram a mão de obra que produziu tudo o que aqui se fez. Mas havia uma
                política de não permitir a concentração de escravos de uma mesma etnia nas fazendas e até nos navios. Além
                de distintas línguas e culturas, isso dificultou a construção de um patrimônio cultural africano unificado.
                Mas toda essa herança africana, o meio cultural e racial, associada às crenças indígenas, criaria uma
                fisionomia singular para a cultura brasileira.</p>

            <p><strong>Duvid:</strong> O período escravocrata no Brasil moldou nossa cultura com repercussões até hoje?</p>

            <p><strong>Prof. Darcy Ribeiro: </strong>Sim, de fato. O Brasil que se construía, sua base ecológica, o projeto
                colonial, a monocultura e o escravismo resultaram em uma sociedade totalmente nova. A empresa escravista foi
                fundada na violência mais cruel de apropriação de seres humanos e de coerção permanente, exercida através
                dos castigos mais atrozes; tudo isso atuou como mola desumanizadora e deculturadora de eficácia
                incomparável. Nenhum povo que passasse por isso como sua rotina de vida, através de séculos, sairia dela sem
                ficar marcado indelevelmente. Todos nós, brasileiros, somos carne da carne daqueles pretos e índios

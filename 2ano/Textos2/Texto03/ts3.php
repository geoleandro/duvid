            <h2> A formação histórica e os grupos étnicos no Brasil</h2>

            <p>Em 1500 havia, por volta, 5 milhões de índios no Brasil. Depois entraram cerca de 6 milhões de negros e,
                aproximadamente, 4 milhões de brancos. O Nordeste foi a primeira região a ser colonizada, com mão de obra
                escrava para a cultura da cana-de-açúcar. No Norte ocorreu ocupação tardia, com influência indígena, em
                caboclos (brancos e índios) e cafuzos (negros e índios). No Sudeste, predomínio de brancos imigrantes que
                vieram trabalhar na cultura do café, após o término da escravidão. No Sul, maioria branca, de imigrantes que
                receberam propriedades para ocupar essa parcela do território. </p>

            <p>A grande marca da população brasileira está baseada na miscigenação, ou no cruzamento entre grupos étnicos.
                Diferentemente de outros países, a cor da pele tem um peso grande no Brasil, daí a denominação de mulato
                (branco e negro). Esse critério não leva em conta a herança genética da pessoa. Há países que classificam
                sua população pelas origens e pela identificação cultural de cada um. Mesmo com pele branca e cabelos
                lisos, há aqueles que preferem se declarar afrodescendentes ou indígenas, pois possuem ancestrais desses
                grupos étnicos. Esse tema, porém, vem mudando ao longo das décadas. </p>

            <div class="w3-margin"><img id="imagem4" src="ts03f04.png" alt="ts03f04" class="w3-mobile">
                <span class="w3-small w3-margin-left" id="citacao4"> Fonte: IBGE. Recenseamentos gerais de 1950, 1980, 2000
                    e 2010. </span>

            </div>

            <p> As informações sobre etnias nem sempre fizeram parte das pesquisas no Brasil. Os Censos de 1960 e 1970, por
                exemplo, não registraram esses dados. Na tabela acima é possível observar um ajuste sobre o pertencimento
                dos grupos étnicos. Sabemos hoje que o Brasil é constituído por maioria parda e negra, o que tem ligação
                direta com o passado de formação da população.</p>

            <p>Houve melhorias com o passar das décadas, como incluir os indígenas em grupos separados dos orientais.
                Entretanto, a noção de pardo ainda pode confundir, pois incluiria tanto descendentes de africanos quanto de
                indígenas. </p>

            <p>Quais os motivos dessa mudança de percepção ou de atitude dos brasileiros em sua declaração sobre a qual
                grupo étnico pertencem? </p>

            <p>Há diversos motivos, mas o fato de que nas décadas passadas a maioria da população se declarava de cor
                branca, com mais de 60% na década de 1950, mesmo tendo descendentes negros ou indígenas, tem a ver com o
                preconceito existente na sociedade brasileira. Porém, com as conquistas e o avanço da legislação em favor
                dos direitos dos indígenas, como a demarcação de suas terras, além das políticas de cotas nas
                universidades para negros, tudo isso contribuiu para uma mudança de percepção e culminou em um maior
                ajustamento entre a declaração da população e seus grupos étnicos. </p>

            <p> O Censo de 2010 revelou, da mesma forma, a distribuição e as diferenças regionais em relação às etnias. A
                região Sul concentrava 78% da proporção de brancos, seguida pela região Sudeste, com 56%. Nas regiões Norte
                e Nordeste esses dados são reduzidos, com 23% e 29% respectivamente do total.</p>

            <p>Na região Norte concentram-se quase 40% dos indígenas do Brasil, e quase 70% da população se declara parda.
                Na região Nordeste está o maior percentual de negros (8%) e a segunda maior proporção de pardos (62%). </p>

            <p>Em pesquisas envolvendo amostras de DNA em grupos considerados brancos, constatou-se uma média de 33% de
                linhagens provenientes de indígenas e 28% de africanas. A miscigenação no Brasil ocorreu, em boa parte,
                com heranças genéticas transmitidas por via feminina, ou seja, essa mistura resultou sobretudo da relação
                entre o homem branco europeu e mulheres indígenas ou africanas. </p>

            <p>Isso porque, na época da colonização, havia poucas mulheres europeias: os colonizadores raramente traziam
                consigo suas mulheres e filhas. </p>


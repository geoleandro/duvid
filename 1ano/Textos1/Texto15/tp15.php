            <h2>Energia: o que é?</h2>

            <div class="area">
                <img alt="Representações do átomo, unidade fundamental de energia e matéria" class="w3-mobile" id="imagem1" src="tp15f01.png" style="display:block" />
            </div>
            <p class="citacao" style="display:block"> Fonte: pexels.com. </p>

            <p>A <span class="termo" data-palavra="Energia"
                    data-definicao="Grandeza física fundamental presente em todos os processos naturais e tecnológicos. De acordo com a Lei da Conservação da Energia, ela nunca é criada nem destruída, apenas convertida entre diferentes formas."><strong>energia</strong></span> é
                um conceito fundamental para entender o funcionamento do universo, pois está presente em todos os processos naturais e tecnológicos. Ela é uma grandeza física que pode ser transformada de uma forma para outra, mas, de acordo com a Lei da Conservação da Energia, ela nunca é criada nem destruída, apenas convertida entre diferentes formas.</p>

            <p>Em sua essência, a energia está por trás de todos os processos que acontecem no mundo, seja no nível mais microscópico, como a movimentação das partículas atômicas, ou no nível mais macroscópico, como a movimentação de veículos e a produção de eletricidade.</p>

            <p>Existem diversas formas de energia, que podem ser classificadas de acordo com a maneira como se manifestam no nosso cotidiano e na natureza. A seguir, apresento algumas das principais formas de energia:</p>

            <p><b><span class="termo" data-palavra="Energia Química"
                        data-definicao="Energia armazenada nas ligações químicas das substâncias, presente em alimentos, combustíveis, baterias e tecidos vivos. É liberada ou absorvida quando essas ligações se quebram ou se formam.">Energia
                        Química</span></b></p>
            <p>A energia química é a energia armazenada nas ligações químicas das substâncias. Essa forma de energia está presente em alimentos, combustíveis, baterias e até nos tecidos vivos. Quando essas substâncias reagem, as ligações químicas se quebram ou se formam, liberando ou absorvendo energia. Exemplos de energia química incluem:</p>
            <ul>
                <li><b>Alimentos:</b> quando consumimos alimentos, nosso corpo converte a energia química armazenada nesses alimentos em energia que nos permite realizar atividades físicas.</li>
                <li><b>Combustíveis:</b> o petróleo, o gás natural e o carvão são fontes de energia química. Quando queimados, liberam energia que é convertida em calor ou em movimento (como nos motores dos veículos).</li>
            </ul>

            <p><b><span class="termo" data-palavra="Energia Mecânica"
                        data-definicao="Energia associada ao movimento ou à posição dos corpos, soma da energia cinética (movimento) e da energia potencial (posição em relação a outras forças, como a gravidade).">Energia
                        Mecânica</span></b></p>
            <p>A energia mecânica está associada ao movimento ou à posição dos corpos. Ela é a soma da energia cinética (relacionada ao movimento) e da energia potencial (relacionada à posição dos corpos em relação a outras forças, como a gravidade). Exemplos de energia mecânica incluem:</p>
            <ul>
                <li><b>Movimento de veículos:</b> a energia mecânica está presente no movimento de carros, bicicletas, aviões etc.</li>
                <li><b>Energia de um pêndulo:</b> quando um pêndulo se move, ele alterna entre energia potencial (quando está mais alto) e energia cinética (quando está se movendo).</li>
            </ul>

            <p><b>Energia Térmica</b></p>
            <p>A energia térmica está relacionada ao calor. É a forma de energia que está associada ao movimento das partículas de uma substância. Exemplos de energia térmica incluem:</p>
            <ul>
                <li><b>Aquecimento de água:</b> quando aquecemos água em uma panela, a energia térmica proveniente do fogo faz com que as moléculas de água se movam mais rapidamente.</li>
                <li><b>Calor no forno:</b> a energia térmica gerada por um forno é usada para aquecer alimentos.</li>
            </ul>

            <p><b>Energia Elétrica</b></p>
            <p>A energia elétrica é a energia dos elétrons em movimento. É amplamente utilizada para alimentar aparelhos eletrônicos, iluminar ambientes e movimentar máquinas. Exemplos de energia elétrica incluem:</p>
            <ul>
                <li><b>Lâmpadas:</b> a energia elétrica é convertida em luz, iluminando os ambientes.</li>
                <li><b>Aparelhos eletrônicos:</b> computadores, televisores e celulares dependem de energia elétrica para funcionar.</li>
            </ul>

            <p><b>Energia Hidráulica</b></p>
            <p>A energia hidráulica é gerada pelo movimento da água, sendo aproveitada principalmente em usinas hidrelétricas. Exemplos incluem:</p>
            <ul>
                <li><b>Hidrelétricas:</b> a água em movimento gera eletricidade ao passar por turbinas.</li>
                <li><b>Moinhos de água:</b> utilizados no passado para moer grãos.</li>
            </ul>

            <p><b>Energia de Radiação</b></p>
            <p>A energia de radiação refere-se à energia transportada por ondas eletromagnéticas, como a luz solar, que é fundamental para a vida na Terra. Exemplos incluem:</p>
            <ul>
                <li><b>Luz solar:</b> pode ser convertida em energia elétrica através de painéis solares.</li>
                <li><b>Radiação térmica:</b> todos os corpos emitem radiação infravermelha devido à sua temperatura.</li>
            </ul>


            <h2>Energias Renováveis e Não Renováveis</h2>

            <p>A energia é essencial para o funcionamento da sociedade moderna, e sua origem pode ser dividida em duas grandes categorias: energias renováveis e energias não renováveis. Cada uma delas possui características distintas em relação à sua disponibilidade, impacto ambiental e formas de utilização.</p>

            <p><strong><span class="termo" data-palavra="Energias Renováveis"
                        data-definicao="Fontes de energia que fazem parte de um ciclo natural, constantemente reabastecidas pela natureza, com limite de utilização muito alto ou praticamente infinito (água, vento, biomassa, sol).">Energias
                        Renováveis</span></strong></p>

            <div class="area">
                <img alt="Painéis solares e turbina eólica em campo nevado" class="w3-mobile" id="imagem2" src="tp15f02.png" style="display:block" />
            </div>
            <p class="citacao" style="display:block"> Fonte: pexels.com. </p>

            <p>As energias renováveis são aquelas que fazem parte de um ciclo natural, ou seja, estão constantemente sendo reabastecidas pela natureza. Esse tipo de energia possui um limite de utilização muito alto ou praticamente infinito, pois os recursos que a geram são continuamente renovados. Isso as torna uma opção mais sustentável, pois não se esgotam com o uso contínuo. As principais fontes de energias renováveis incluem:</p>

            <p><strong>Água</strong><br>
                A energia hídrica é gerada pelo movimento da água, mais comumente aproveitada em hidrelétricas. A água represada em barragens é liberada, e seu movimento é utilizado para acionar turbinas que geram eletricidade. A energia da água é considerada renovável, pois a água está em constante ciclo natural de evaporação e precipitação. A grande vantagem dessa energia é a sua alta capacidade de geração de eletricidade, sendo uma das fontes mais utilizadas em muitos países.<br>
                <em>Exemplo:</em> usinas hidrelétricas, como a de Itaipu, no Brasil, que produzem grande parte da energia elétrica do país.</p>

            <p><strong>Ventos</strong><br>
                A energia eólica é gerada a partir da força dos ventos. Turbinas eólicas capturam a energia do vento e a convertem em eletricidade. O vento é um recurso abundante e constante, principalmente em regiões litorâneas e áreas abertas. A energia eólica é considerada uma das fontes mais limpas e sustentáveis, pois não gera poluição nem resíduos.<br>
                <em>Exemplo:</em> parques eólicos no nordeste do Brasil, como o Complexo Eólico Lagoa do Barro, no Piauí, que já soma 277,8 MW de capacidade instalada, e o vizinho Complexo Eólico Lagoa dos Ventos, com 716 MW, o maior parque eólico em operação na América do Sul.</p>

            <p><strong>Biomassa</strong><br>
                A biomassa refere-se à energia derivada de material orgânico, como madeira, resíduos agrícolas, lixo orgânico e até algas. Esse material pode ser queimado para gerar calor ou transformado em biocombustíveis, como o etanol e o biodiesel. A principal vantagem da biomassa é que ela pode ser gerada a partir de resíduos, ajudando a reduzir o desperdício e a poluição.<br>
                <em>Exemplo:</em> o uso de resíduos de madeira para gerar energia em usinas termoelétricas ou a produção de etanol a partir da cana-de-açúcar no Brasil.</p>

            <p><strong>Energia Solar</strong><br>
                A energia solar é gerada a partir da radiação solar. Ela pode ser captada por painéis fotovoltaicos, que convertem a luz solar diretamente em eletricidade, ou por coletor solar, que converte o calor solar em energia térmica. A energia solar é uma das fontes mais promissoras de energia renovável, pois o sol é uma fonte praticamente ilimitada e disponível em grande parte do planeta.<br>
                <em>Exemplo:</em> painéis solares instalados em residências ou grandes usinas solares, como o Complexo Solar Janaúba, no norte de Minas Gerais, o maior parque fotovoltaico do Brasil, com capacidade de 1,2 GWp distribuída em 20 parques solares e capacidade para abastecer mais de 1,5 milhão de residências.</p>

            <p><strong><span class="termo" data-palavra="Energias Não Renováveis"
                        data-definicao="Fontes de energia com disponibilidade limitada, que não se renovam a uma taxa suficiente para acompanhar o ritmo de consumo. Geralmente associadas à queima de combustíveis fósseis.">Energias
                        Não Renováveis</span></strong></p>

            <div class="area">
                <img alt="Bomba de extração de petróleo (cavalo mecânico)" class="w3-mobile" id="imagem3" src="tp15f03.png" style="display:block" />
            </div>
            <p class="citacao" style="display:block"> Fonte: pexels.com. </p>

            <p>As energias não renováveis, por outro lado, são recursos finitos, ou seja, sua disponibilidade é limitada. Esses recursos não se renovam ou se reabastecem a uma taxa suficientemente rápida para acompanhar seu ritmo de consumo. As energias não renováveis são geralmente associadas à queima de combustíveis fósseis, que liberam gases poluentes e contribuem para o aquecimento global. As principais fontes de energia não renovável incluem:</p>

            <p><strong>Carvão</strong><br>
                O carvão mineral é um combustível fóssil formado a partir da decomposição de matéria orgânica, como plantas, ao longo de milhões de anos. Ele tem sido uma das principais fontes de energia desde a Revolução Industrial e é amplamente utilizado para gerar eletricidade em termelétricas e como combustível para indústrias. Apesar de ser uma fonte abundante em algumas regiões do mundo, o carvão é altamente poluente, liberando dióxido de carbono (CO2), óxidos de enxofre e outros poluentes no ar.<br>
                <em>Exemplo:</em> usinas termoelétricas que utilizam carvão como principal fonte de energia, como as que operam na China e na Índia.</p>

            <p><strong>Petróleo</strong><br>
                O petróleo é uma mistura complexa de hidrocarbonetos que pode ser refinada para produzir uma variedade de produtos, como gasolina, diesel, querosene, lubrificantes e asfalto. O petróleo é a principal fonte de energia para transporte, aquecimento e produção de eletricidade. Embora seja uma fonte de energia muito eficiente, sua extração é difícil e poluente, e é um recurso finito, ou seja, não estará disponível para sempre.<br>
                <em>Exemplo:</em> refinarias de petróleo que produzem gasolina e diesel, como as operadas pela Petrobras no Brasil.</p>

            <p><strong>Gás Natural</strong><br>
                O gás natural é uma fonte de energia composta principalmente por metano, sendo formado da mesma maneira que o petróleo, através da decomposição de matéria orgânica. Ele é considerado menos poluente do que o carvão e o petróleo, mas, ainda assim, a sua queima libera CO2. O gás natural é utilizado principalmente para gerar eletricidade, aquecer ambientes e como combustível para veículos. No entanto, a falta de infraestrutura necessária, como gasodutos, limita sua distribuição.<br>
                <em>Exemplo:</em> usinas termelétricas que utilizam gás natural, como as localizadas no estado do Rio de Janeiro, ou sua utilização como combustível em carros e ônibus.</p>

            <p><strong>E o Brasil, nessa conta?</strong> O país é uma exceção interessante no cenário mundial. Segundo o Balanço Energético Nacional de 2025, divulgado pela Empresa de Pesquisa Energética (EPE), 88,2% de toda a eletricidade gerada no Brasil em 2024 veio de fontes renováveis, com a energia hidráulica sozinha respondendo por 56,1% do total, e eólica e solar somadas já alcançando 23,7%. Quando se olha para a matriz energética completa, incluindo não só eletricidade mas também combustíveis usados em transporte e indústria, essa participação renovável cai para cerca de 50%, ainda assim, bem acima da média mundial, que gira em torno de 13% a 15%. Essa diferença explica por que o Brasil discute a transição energética a partir de um ponto de partida bem mais favorável do que a maioria dos países.</p>


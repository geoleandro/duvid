            <p><span class="termo" data-palavra="Combustível"
                    data-definicao="Substância que pode ser queimada para a produção de energia, liberando calor que pode ser convertido em movimento, eletricidade ou usado para aquecer ambientes."><strong>Combustíveis</strong></span> são
                substâncias que podem ser queimadas para a produção de energia. Eles são essenciais para o funcionamento de muitos processos industriais, no setor de transportes e para o fornecimento de energia elétrica em diversas partes do mundo. Quando um combustível é queimado, ele libera energia na forma de calor, que pode ser utilizada de várias maneiras, como para movimentar máquinas, gerar eletricidade ou aquecer ambientes.</p>

            <p>A queima de combustíveis resulta em reação química que libera energia térmica e pode ser usada para transformar essa energia em outros tipos, como energia mecânica ou elétrica. Dependendo do tipo de combustível, essa reação pode ser mais ou menos eficiente, além de gerar diferentes impactos ambientais.</p>

            <p><strong>Tipos de Combustíveis</strong><br>
                Os combustíveis podem ser classificados em várias categorias, mas as mais comuns são:</p>

            <p><strong>Lenha</strong><br>
                A lenha é um combustível natural que vem das árvores e é utilizado principalmente para aquecimento e cozimento. Ela é um dos combustíveis mais antigos e ainda é bastante usada em várias partes do mundo, especialmente em áreas rurais. Quando queimada, a lenha libera calor, mas também emite dióxido de carbono (CO2) e outras substâncias que podem contribuir para a poluição do ar e o efeito estufa.<br>
                <em>Exemplo:</em> lenha queimada em fogões a lenha ou lareiras para aquecer a casa.</p>

            <p><strong>Carvão</strong><br>
                O carvão é um combustível fóssil que resulta da decomposição de matéria orgânica, como plantas, ao longo de milhões de anos. Ele possui um alto poder calorífico e é amplamente utilizado em termelétricas, indústrias e, no passado, foi a principal fonte de energia durante a Revolução Industrial. O carvão, no entanto, é um dos combustíveis mais poluentes, pois sua queima emite grandes quantidades de dióxido de carbono (CO2), óxidos de enxofre e outros poluentes atmosféricos.<br>
                <em>Exemplo:</em> usinas termoelétricas que queimam carvão para gerar eletricidade.</p>

            <p><strong>Petróleo</strong><br>
                O petróleo é um líquido viscoso e complexo composto por hidrocarbonetos, encontrado no subsolo em grandes reservatórios. Ele é a principal fonte de combustível para transportes, principalmente em forma de gasolina, diesel e querosene. Além disso, o petróleo também é refinado para produzir uma série de outros produtos, como plásticos, óleos lubrificantes e asfalto. Embora o petróleo seja eficiente, sua extração e queima resultam em poluição do ar e contribuem para o aquecimento global.<br>
                <em>Exemplo:</em> gasolina utilizada em automóveis ou diesel em caminhões.</p>

            <p><strong>Gás Natural</strong><br>
                O gás natural é uma fonte de energia fóssil formada pela decomposição da matéria orgânica no subsolo, de forma semelhante ao petróleo. Ele é principalmente composto por metano (CH4) e, quando comparado ao carvão e ao petróleo, é uma fonte de energia mais limpa, pois emite menos poluentes. O gás natural é utilizado para gerar eletricidade, aquecer residências e como combustível para veículos. Porém, sua distribuição é limitada pela infraestrutura necessária, como gasodutos.<br>
                <em>Exemplo:</em> uso do gás natural em termelétricas ou em carros movidos a gás.</p>

            <p><strong><span class="termo" data-palavra="Biocombustível"
                        data-definicao="Fonte de energia renovável derivada de matéria orgânica, como vegetais e resíduos orgânicos. O etanol e o biodiesel são os exemplos mais comuns.">Biocombustíveis</span></strong><br>
                Os biocombustíveis são fontes de energia renováveis derivadas de matéria orgânica, como vegetais e resíduos orgânicos. O etanol (produzido a partir da cana-de-açúcar) e o biodiesel (feito a partir de óleos vegetais ou gordura animal) são os exemplos mais comuns. Os biocombustíveis têm a vantagem de serem mais sustentáveis em comparação com os combustíveis fósseis, pois podem ser produzidos de forma renovável. Contudo, sua produção também pode ter impactos ambientais, como desmatamento e uso excessivo de recursos naturais.<br>
                <em>Exemplo:</em> etanol utilizado como combustível em veículos no Brasil.</p>

            <p>O Brasil é pioneiro nesse tipo de combustível: em 1975, o governo lançou o Proálcool, programa criado em resposta às crises internacionais do petróleo da década de 1970, para estimular a produção de etanol a partir da cana-de-açúcar e reduzir a dependência do petróleo importado. O programa deu origem à frota de carros a álcool e, mais tarde, aos motores flex, capazes de rodar com qualquer proporção de gasolina e etanol. Hoje, toda a gasolina vendida no país é obrigatoriamente misturada com etanol anidro, mistura que o Conselho Nacional de Política Energética elevou para 32% em 2026, e o diesel comercializado leva uma mistura obrigatória de 15% de biodiesel (o chamado B15), com testes em andamento para elevar esse percentual ainda mais nos próximos anos.</p>

            <p><strong>Impactos Ambientais dos Combustíveis Fósseis</strong><br>
                Embora os combustíveis fósseis, como o carvão, o petróleo e o gás natural, desempenhem um papel vital na geração de energia e no desenvolvimento industrial, sua queima libera grandes quantidades de dióxido de carbono (CO2), um dos principais gases do efeito estufa. Isso contribui para o aquecimento global, a mudança climática e outros problemas ambientais, como a poluição do ar e chuvas ácidas. Além disso, a extração desses combustíveis pode causar danos aos ecossistemas, como o desmatamento e a contaminação dos corpos d'água.<br>
                Por esse motivo, muitos países estão tentando reduzir a dependência de combustíveis fósseis e adotar fontes de energia mais limpas e sustentáveis, como as energias renováveis. O objetivo é diminuir o impacto ambiental e garantir uma oferta de energia mais segura e sustentável para as gerações futuras.</p>


            <h2>De Estocolmo ao Rio: como o mundo chegou à Eco-92</h2>

            <p>A história das conferências ambientais globais começa em 1972, em Estocolmo, na Suécia. A Conferência da ONU sobre Meio Ambiente Humano foi a primeira vez que a comunidade internacional se reuniu especificamente para discutir problemas ambientais. O documento final, a Declaração de Estocolmo, reconhecia que o ser humano tem o direito a um ambiente de qualidade que permita uma vida digna, e que tem ao mesmo tempo a responsabilidade de proteger o meio ambiente para as gerações futuras. Era uma linguagem nova para a diplomacia: o planeta como objeto de responsabilidade coletiva.</p>

            <p>Vinte anos depois, a Eco-92 deu um salto qualitativo. O evento produziu quatro documentos centrais que ainda hoje estruturam o debate ambiental internacional. A <span class="termo" data-palavra="Agenda 21" data-definicao="Plano de ação aprovado na Eco-92 que estabelece 2.500 recomendações sobre desenvolvimento sustentável para o século XXI. Abrange temas que vão de desmatamento a pobreza, de participação feminina a controle do lixo. É um documento não vinculante: os países não são obrigados a cumpri-lo.">Agenda 21</span> era um plano de ação com mais de 2.500 recomendações para o século XXI, cobrindo temas que iam de florestas e oceanos a pobreza e educação. A Declaração do Rio enunciou 27 princípios sobre a relação entre meio ambiente e desenvolvimento. A Convenção-Quadro sobre Mudança do Clima estabeleceu o primeiro compromisso internacional para estabilizar emissões de gases de efeito estufa. E a Convenção sobre Diversidade Biológica criou um marco legal para proteger espécies e ecossistemas.</p>

            <h3>O conceito de desenvolvimento sustentável</h3>

            <p>O conceito que passou a dominar o debate a partir da Eco-92 foi o de <span class="termo" data-palavra="Desenvolvimento Sustentável" data-definicao="Conceito popularizado pelo Relatório Brundtland (1987) como 'desenvolvimento que satisfaz as necessidades do presente sem comprometer a capacidade das gerações futuras de satisfazer suas próprias necessidades'. É alvo de críticas tanto da direita (restringe o crescimento) quanto da esquerda (não questiona o modelo econômico, apenas o regula).">desenvolvimento sustentável</span>, definido pelo Relatório Brundtland de 1987 como o desenvolvimento que atende às necessidades do presente sem comprometer a capacidade das gerações futuras de atender às suas próprias necessidades. A fórmula tinha a vantagem de ser aceita por governos muito diferentes: ela não exige abandonar o crescimento econômico, apenas torná-lo mais eficiente e de longo prazo. Mas também é alvo de críticas: para os ecossocialistas, é uma tentativa de conciliar o inconciliável, o capitalismo com limites ecológicos que ele, por definição, não aceita.</p>

            <p>A Eco-92 também consagrou o <span class="termo" data-palavra="Princípio da Responsabilidade Comum Mas Diferenciada" data-definicao="Princípio do direito ambiental internacional que reconhece que todos os países têm responsabilidade sobre os problemas ambientais globais, mas que essa responsabilidade deve ser proporcional à contribuição histórica de cada um para o problema e à sua capacidade econômica de agir. É a base da argumentação dos países em desenvolvimento para exigir mais compromissos dos países ricos.">Princípio da Responsabilidade Comum mas Diferenciada</span>: todos os países têm responsabilidade sobre os problemas ambientais globais, mas essa responsabilidade deve ser proporcional à contribuição histórica de cada um. Países que poluíram mais por mais tempo devem fazer mais. Esse princípio ainda hoje é o coração das disputas nas negociações climáticas.</p>

            <h3>Rio+20: vinte anos depois, no mesmo lugar</h3>

            <p>Em 2012, exatamente vinte anos após a Eco-92, o Rio de Janeiro voltou a sediar uma grande conferência ambiental da ONU, batizada informalmente de Rio+20. Representantes de 193 países se reuniram para avaliar o que havia sido cumprido das promessas de 1992 e definir os próximos passos. O documento final, "O Futuro que Queremos", tratou principalmente do conceito de economia verde: a ideia de reorientar investimentos públicos e privados para setores que reduzem a pressão sobre os recursos naturais, gerando emprego e renda sem repetir o modelo de crescimento baseado em combustíveis fósseis e desmatamento.</p>

            <p>A Rio+20 é lembrada, na maior parte das avaliações posteriores, como um evento de expectativas moderadas e resultados ainda mais modestos. Diferente da Eco-92, que produziu convenções com força legal, a Rio+20 resultou principalmente em compromissos voluntários e recomendações. Seu legado mais concreto foi lançar as bases para o processo que, três anos depois, resultaria nos Objetivos de Desenvolvimento Sustentável, aprovados junto com o Acordo de Paris em 2015.</p>


            <h2>Quando o mundo tentou sentar junto</h2>

            <p><span class="primeiraLetra">E</span>m 1992, o Rio de Janeiro recebeu a maior conferência ambiental da história até aquele momento. Cento e setenta e oito países enviaram representantes. Doze mil delegados. Mais de cem chefes de Estado. O nome oficial era Conferência das Nações Unidas sobre Meio Ambiente e Desenvolvimento, mas ficou conhecida como Eco-92 ou Rio-92. O objetivo era simples de enunciar e quase impossível de executar: fazer o mundo inteiro concordar sobre como lidar com a degradação ambiental sem parar o desenvolvimento econômico.</p>


            <h2>Sustentabilidade: o que é, o que não é e o que está em disputa</h2>

            <p>Poucas palavras foram tão usadas e tão esvaziadas quanto "sustentabilidade". Empresas que despejam resíduos em rios dizem que são "comprometidas com o desenvolvimento sustentável". Governos que aprovam desmatamento dizem que é "uso sustentável dos recursos". Para além do greenwashing, a ideia de sustentabilidade tem um conteúdo sério que vale entender com precisão.</p>

            <p>A <span class="termo" data-palavra="Sustentabilidade" data-definicao="Capacidade de um sistema de manter suas funções ao longo do tempo. Na dimensão ambiental, significa usar recursos naturais numa taxa menor ou igual à sua taxa de regeneração. Tem três dimensões frequentemente citadas: ambiental (equilíbrio ecológico), social (equidade e bem-estar) e econômica (viabilidade a longo prazo). A tensão entre essas três dimensões é o coração do debate sobre desenvolvimento sustentável.">sustentabilidade</span> tem três dimensões que precisam funcionar juntas: a ambiental (os recursos naturais não podem ser consumidos mais rápido do que se regeneram), a social (os benefícios e os custos do desenvolvimento devem ser distribuídos de forma justa entre as gerações atuais e futuras) e a econômica (o sistema precisa ser viável sem depender de subsídios ou da destruição de capital natural). O problema é que, na prática, essas três dimensões entram em conflito com muita frequência. Uma mineradora pode ser economicamente sustentável por décadas enquanto destrói ecossistemas inteiros e expulsa comunidades.</p>

            <h3>Os Objetivos de Desenvolvimento Sustentável</h3>

            <p>Em 2015, junto com o Acordo de Paris, a ONU aprovou os <span class="termo" data-palavra="ODS (Objetivos de Desenvolvimento Sustentável)" data-definicao="Conjunto de 17 objetivos e 169 metas aprovados pela ONU em 2015 como parte da Agenda 2030. Substituíram os Objetivos de Desenvolvimento do Milênio (ODM, 2000-2015) e cobrem temas como erradicação da pobreza, segurança alimentar, saúde, educação, energia limpa, cidades sustentáveis, ação climática e biodiversidade. São um guia de planejamento, não um tratado vinculante.">ODS (Objetivos de Desenvolvimento Sustentável)</span>, um conjunto de 17 objetivos e 169 metas que os países se comprometem a atingir até 2030. Os ODS cobrem desde a erradicação da pobreza (ODS 1) e a fome zero (ODS 2) até a ação climática (ODS 13), a vida na água (ODS 14) e a vida terrestre (ODS 15). São um guia de planejamento para governos, empresas e sociedade civil, mas não são tratados vinculantes: nenhum país é punido por não atingir suas metas.</p>

            <p>Em 2023, a ONU divulgou um relatório de avaliação dos ODS com um dado alarmante: o mundo estava, na média, cumprindo menos de 15% das metas previstas para 2030. Os objetivos ligados a clima, biodiversidade e oceanos eram os que apresentavam os piores resultados. A combinação de pandemia de Covid-19, guerra na Ucrânia e inflação global havia revertido décadas de progresso em segurança alimentar e pobreza em muitos países.</p>

            <h3>O Brasil cria seu próprio mercado regulado de carbono</h3>

            <p>Em dezembro de 2024, o Brasil deu um passo importante na regulamentação de créditos de carbono ao sancionar a lei que cria o Sistema Brasileiro de Comércio de Emissões de Gases de Efeito Estufa, conhecido pela sigla SBCE. Diferente do mercado voluntário, em que empresas compram créditos por iniciativa própria para melhorar sua imagem, o SBCE cria um mercado regulado pelo governo: empresas que emitem mais de 10 mil toneladas de CO2 equivalente por ano passam a ter um teto de emissões definido oficialmente, e podem comprar ou vender permissões de emissão entre si, no modelo internacionalmente conhecido como cap-and-trade (limitar e negociar). Quem emite menos do que seu teto pode vender o excedente; quem emite mais precisa comprar permissões extras ou pagar multas.</p>

            <p>A implementação do SBCE está prevista para acontecer em fases ao longo de seis anos, começando pelos setores industriais que mais emitem gases de efeito estufa. Para um país com a maior floresta tropical do planeta e um agronegócio de escala continental, ter um mercado de carbono regulado e confiável é visto como uma peça central da estratégia brasileira para atrair investimento internacional em conservação florestal e energia limpa, ao mesmo tempo em que cria uma fonte de receita para quem preserva.</p>

            <h3>O Fundo de Perdas e Danos: quem paga pelo que já foi perdido</h3>

            <p>Financiamento climático não serve só para reduzir emissões futuras ou ajudar países a se adaptar. Existe também a pergunta sobre o que fazer com os danos que já aconteceram e que não têm mais volta: uma ilha do Pacífico que perdeu parte do seu território para o mar, uma safra inteira destruída por uma seca sem precedentes, uma cidade costeira que precisou ser realocada. Para esse tipo de dano, irreversível e já ocorrido, foi criado em 2022, na COP27 do Egito, o <span class="termo" data-palavra="Fundo de Perdas e Danos" data-definicao="Mecanismo financeiro internacional criado na COP27 (2022) para compensar países vulneráveis por danos climáticos já ocorridos e irreversíveis, como perda de território para o mar ou destruição de safras por eventos extremos. Diferente do financiamento para mitigação e adaptação, que olha para o futuro, o Fundo de Perdas e Danos lida com prejuízos que já aconteceram e não têm mais solução técnica, apenas compensação financeira.">Fundo de Perdas e Danos</span> (Loss and Damage Fund), depois de mais de três décadas de pressão de países pobres e nações insulares.</p>

            <p>O fundo é considerado um marco histórico porque, pela primeira vez, os países ricos aceitaram formalmente a ideia de que devem parte da conta pelos danos climáticos que já aconteceram, não apenas pelos que ainda vão acontecer. Na prática, a operacionalização do fundo tem sido lenta e os valores efetivamente depositados continuam muito abaixo das necessidades estimadas, que passam de centenas de bilhões de dólares por ano segundo organizações que representam pequenas ilhas e países menos desenvolvidos. Ainda assim, o fundo simboliza uma mudança de linguagem importante na diplomacia climática: da prevenção para a reparação.</p>

            <h3>Limites planetários</h3>

            <p>O conceito mais recente e possivelmente mais importante para entender os limites da sustentabilidade é o dos <span class="termo" data-palavra="Limites Planetários" data-definicao="Conceito científico desenvolvido pelo pesquisador Johan Rockström e equipe (2009) que identifica nove processos do sistema terrestre (clima, biodiversidade, ciclos do nitrogênio e fósforo, uso da água doce, acidificação dos oceanos, aerossóis, ozônio estratosférico, uso da terra, entidades novas) e define os limites dentro dos quais a humanidade pode operar com segurança. Em 2023, seis dos nove limites já haviam sido ultrapassados.">Limites Planetários</span>, desenvolvido em 2009 pelo cientista sueco Johan Rockström. A ideia é que o sistema terrestre tem nove processos fundamentais (o clima, a biodiversidade, os ciclos do nitrogênio e fósforo, o uso da água doce, a acidificação dos oceanos, entre outros) que mantêm o planeta no estado estável que permitiu o desenvolvimento humano nos últimos 10.000 anos. Cada processo tem um limite além do qual o sistema pode se tornar instável de forma irreversível. Em 2023, uma atualização do estudo mostrou que seis dos nove limites já foram ultrapassados, o que levou o grupo de pesquisa a dizer que o planeta havia saído do "espaço operacional seguro" para a humanidade.</p>


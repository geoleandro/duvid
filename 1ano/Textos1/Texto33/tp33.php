            <h2>De Kyoto a Paris: dois modelos para salvar o clima</h2>

            <p>Em 1997, cinco anos depois da Eco-92, as nações voltaram a se reunir no Japão e assinaram o <span class="termo" data-palavra="Protocolo de Kyoto" data-definicao="Acordo internacional assinado em 1997, em vigor desde 2005, que estabeleceu metas vinculantes de redução de emissões de gases de efeito estufa apenas para os países industrializados (Anexo I). Os EUA assinaram mas não ratificaram. O Canadá saiu em 2012. Expirou em 2020, substituído pelo Acordo de Paris.">Protocolo de Kyoto</span>. Era o primeiro tratado com metas vinculantes de redução de emissões. Mas tinha uma característica importante: as metas obrigatórias valiam apenas para os países industrializados listados no chamado Anexo I, como EUA, União Europeia, Japão, Canadá e Austrália. Países em desenvolvimento, incluindo China, Índia e Brasil, não tinham metas de corte obrigatórias.</p>

            <p>A lógica era coerente com o Princípio da Responsabilidade Diferenciada: os ricos poluíram mais, devem cortar mais. Mas criou um problema político grave. Os Estados Unidos, responsáveis por mais de 20% das emissões globais na época, se recusaram a ratificar o protocolo. O Senado americano votou 95 a 0 contra a ratificação, argumentando que excluir China e Índia das metas era uma vantagem competitiva injusta. O Canadá entrou em vigor com o tratado mas se retirou em 2012, quando ficou claro que não cumpriria as metas. O Protocolo de Kyoto sobreviveu até 2020, mas sem os dois maiores emissores históricos do mundo em suas metas vinculantes.</p>

            <h3>O modelo Paris: todos participam, mas ninguém é obrigado</h3>

            <p>O <span class="termo" data-palavra="Acordo de Paris" data-definicao="Tratado climático global assinado em 2015 por 196 países, em vigor desde 2016. Estabelece o objetivo de limitar o aquecimento global a 1,5°C acima dos níveis pré-industriais. Cada país define suas próprias metas (NDCs) sem imposição externa. Não tem mecanismo de sanção para descumprimento, mas prevê transparência e revisão periódica das metas.">Acordo de Paris</span>, assinado em 2015, tentou resolver o problema do Kyoto com uma solução diferente. Em vez de metas impostas de cima para baixo, cada país define suas próprias contribuições voluntárias, chamadas de NDCs (Nationally Determined Contributions, ou Contribuições Nacionalmente Determinadas). O objetivo comum é limitar o aquecimento global a 1,5°C acima dos níveis pré-industriais, mas não há sanção prevista para quem não cumprir. Cento e noventa e seis países assinaram, incluindo os EUA, China e Índia.</p>

            <p>A vantagem do modelo Paris é a participação universal: nenhum grande emissor ficou de fora. A desvantagem é que as NDCs iniciais, somadas, não eram suficientes para atingir a meta de 1,5°C. O próprio <span class="termo" data-palavra="IPCC" data-definicao="Painel Intergovernamental sobre Mudanças Climáticas, criado pela ONU em 1988, reúne milhares de cientistas de todo o mundo para revisar e sintetizar as pesquisas mais atuais sobre o clima. Não realiza pesquisa própria: compila e avalia estudos já publicados para produzir relatórios de consenso científico que servem de base técnica para as negociações climáticas nas COPs.">IPCC</span> (Painel Intergovernamental sobre Mudanças Climáticas), órgão científico da ONU criado em 1988 que reúne milhares de pesquisadores para sintetizar o conhecimento científico sobre o clima, calculou no relatório de 2021 que as metas apresentadas pelos países colocariam o mundo numa trajetória de aquecimento de 2,4°C a 2,7°C até 2100, com impactos muito mais severos do que os calculados para 1,5°C. Donald Trump retirou os Estados Unidos do acordo em 2017. Joe Biden os recolocou em 2021. As NDCs precisam ser revisadas e elevadas periodicamente, e o mecanismo de pressão é a transparência e o monitoramento público, não a punição.</p>

            <p>O Brasil entregou sua NDC mais recente durante a COP29, em novembro de 2024, com uma meta em formato de banda: reduzir as emissões líquidas de gases de efeito estufa entre 59% e 67% até 2035, em comparação aos níveis de 2005. Em números absolutos, isso significa sair de cerca de 2 bilhões de toneladas de CO2 equivalente emitidas por ano para uma faixa entre 850 milhões e 1,05 bilhão de toneladas. O formato de banda, em vez de um número fixo único, é uma forma de a meta acomodar incertezas tecnológicas e econômicas dos próximos anos sem abandonar o compromisso de redução.</p>

            <h3>O papel das COPs</h3>

            <p>Desde a Eco-92, as nações se reúnem anualmente nas chamadas <span class="termo" data-palavra="COP (Conferência das Partes)" data-definicao="Sigla de Conference of the Parties: reunião anual dos países signatários da Convenção-Quadro da ONU sobre Mudança do Clima. Acompanha a implementação dos acordos e negocia novos compromissos. A COP21 (Paris, 2015) produziu o Acordo de Paris. A COP28 (Dubai, 2023) foi a primeira a mencionar explicitamente a eliminação gradual dos combustíveis fósseis.">COPs</span> (Conferências das Partes). A COP3 (Kyoto, 1997) produziu o Protocolo de Kyoto. A COP21 (Paris, 2015) produziu o Acordo de Paris. A COP26 (Glasgow, 2021) pressionou os países a ampliar suas NDCs. A COP28 (Dubai, 2023) foi historicamente a primeira a mencionar explicitamente, num documento final, a eliminação gradual dos combustíveis fósseis, com fortes pressões dos países produtores de petróleo para suavizar a linguagem. Cada COP é um retrato da correlação de forças política e econômica global em torno do clima.</p>

            <h3>COP29 e COP30: o dinheiro entra de vez na mesa de negociação</h3>

            <p>Em novembro de 2024, a COP29 aconteceu em Baku, no Azerbaijão, e teve como tema central o <span class="termo" data-palavra="Financiamento Climático" data-definicao="Recursos financeiros destinados a ajudar países a reduzir emissões (mitigação) e a se adaptar aos impactos das mudanças climáticas (adaptação). É um dos pontos mais disputados nas negociações climáticas internacionais, porque envolve a pergunta concreta de quem paga a conta da transição energética e da adaptação dos países mais pobres.">financiamento climático</span>: quem paga a conta da transição energética e da adaptação nos países mais pobres. Depois de negociações tensas que se estenderam madrugada adentro, os países desenvolvidos se comprometeram a mobilizar pelo menos 300 bilhões de dólares por ano até 2035 para apoiar países em desenvolvimento. O valor foi amplamente criticado por representantes de nações pobres e ilhas do Pacífico, que pediam algo próximo de 1,3 trilhão de dólares anuais e chamaram o resultado final de insuficiente diante da escala do problema.</p>

            <p>Um ano depois, em novembro de 2025, foi a vez do Brasil sediar a COP30, em Belém, no coração da Amazônia, a primeira COP realizada dentro de uma floresta tropical. Depois de duas semanas de negociação marcadas por tensões geopolíticas globais, 195 países aprovaram por consenso o chamado Pacote de Belém: um conjunto de decisões que incluiu o compromisso de triplicar o financiamento internacional para adaptação climática até 2035, a criação de um conjunto de indicadores para monitorar o progresso da adaptação em áreas como água, alimentação e saúde, e um mecanismo de "transição justa" para apoiar trabalhadores e comunidades afetados pela mudança da matriz energética. A escolha de Belém como sede não foi apenas simbólica: colocou a Amazônia, e o Brasil, no centro físico e político da diplomacia climática global daquele ano.</p>


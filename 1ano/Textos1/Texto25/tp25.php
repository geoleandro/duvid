            <h2>O que está em jogo no fundo do mar</h2>

            <h3>O Direito do Mar e a divisão do oceano</h3>

            <p>O oceano não pertence a ninguém, e pertence a todos ao mesmo tempo. Essa tensão é regulada pela <span class="termo" data-palavra="UNCLOS" data-definicao="Convenção das Nações Unidas sobre o Direito do Mar, assinada em 1982, que divide os espaços marítimos em zonas com diferentes graus de soberania e criou a Autoridade Internacional dos Fundos Marinhos.">Convenção das Nações Unidas sobre o Direito do Mar (UNCLOS)</span>, assinada em 1982 e ratificada por quase 170 países até hoje. Ela divide os espaços marítimos em zonas com diferentes graus de soberania.</p>

            <p>O <strong>mar territorial</strong> vai até 12 milhas náuticas da costa: o país tem soberania plena, como se fosse terra firme. A <strong>Zona Contígua</strong> vai de 12 a 24 milhas: o país pode fiscalizar e aplicar leis aduaneiras e sanitárias. A <span class="termo" data-palavra="Zona Econômica Exclusiva" data-definicao="Faixa de mar que se estende até 200 milhas náuticas da costa, onde o país costeiro tem direitos exclusivos sobre os recursos naturais do mar, do fundo e do subsolo, mas não soberania plena sobre a navegação.">Zona Econômica Exclusiva (ZEE)</span> vai até 200 milhas: o país não governa o mar, mas tem direito exclusivo sobre todos os recursos naturais da coluna d'água, do fundo e do subsolo. Além das 200 milhas, começa o alto mar, patrimônio comum da humanidade.</p>

            <p>Há ainda um mecanismo adicional: países podem solicitar à Comissão de Limites da Plataforma Continental (CLPC) da ONU o reconhecimento de uma plataforma continental estendida além das 200 milhas, desde que provem que o leito marinho é continuação geológica do seu território. Vários países fizeram isso, entre eles o Brasil, a Rússia, o Canadá e a Austrália.</p>

            <p>Além das 200 milhas, no chamado alto mar, existe uma área ainda mais distante: o fundo oceânico que fica fora de qualquer plataforma continental estendida, chamado apenas de "a Área". A UNCLOS declarou essa região patrimônio comum da humanidade e criou a Autoridade Internacional dos Fundos Marinhos (ISA), sediada na Jamaica, para regular a exploração mineral ali, incluindo os nódulos polimetálicos que você conheceu no bloco anterior. Até hoje, a ISA já concedeu dezenas de licenças de exploração (não de extração comercial em larga escala) para países e empresas, num equilíbrio ainda instável entre abrir a corrida pelos minerais do fundo do mar e proteger ecossistemas que a ciência mal começou a entender.</p>


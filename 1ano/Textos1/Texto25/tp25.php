            <h3>As cadeias oceânicas</h3>

            <p>No meio dos oceanos, extensas cadeias de montanhas submarinas marcam os pontos onde duas placas tectônicas se afastam. Magma sobe pelo vão aberto, solidifica e forma nova crosta oceânica continuamente. São as <span class="termo" data-palavra="Cadeias Oceânicas" data-definicao="Longas cadeias de montanhas submarinas formadas nos limites divergentes entre placas. A Cadeia Mesoatlântica separa as placas americana e euro-africana e é a maior estrutura geológica contínua do planeta.">cadeias oceânicas</span>. A Cadeia Mesoatlântica percorre o Atlântico de norte a sul por 16.000 km, separando as placas americana e euro-africana. Ela se expande cerca de 2,5 cm por ano, ou seja, a América do Sul e a África se distanciam nesse ritmo.</p>

            <p>Onde a cadeia emerge acima do nível do mar, forma ilhas vulcânicas: Açores, Islândia, Tristão da Cunha e Santa Helena são picos da Cadeia Mesoatlântica. A Islândia cresce visivelmente: vulcões entram em erupção com regularidade, e o país inteiro está sendo construído pela divergência das placas em tempo real. Em outros pontos, surgem os <span class="termo" data-palavra="Montes Submarinos" data-definicao="Vulcões extintos ou inativos que cresceram no fundo do oceano sem chegar à superfície. Funcionam como oásis de biodiversidade, atraindo cardumes e sendo alvo de pesca predatória.">montes submarinos</span> (seamounts): vulcões extintos que nunca chegaram à superfície, mas que funcionam como oásis de biodiversidade no meio do oceano profundo.</p>

            <p>Cientistas estimam que existam mais de 100 mil montes submarinos com mais de 1.000 metros de altura espalhados pelos oceanos, e a maioria nunca foi visitada por nenhum equipamento científico. Correntes marinhas que sobem pelas encostas desses vulcões extintos trazem nutrientes das profundezas para camadas mais rasas, criando pontos de altíssima concentração de vida num oceano aberto que, fora dali, é quase um deserto biológico. Esses mesmos cardumes concentrados atraem frotas de pesca industrial, que arrastam redes pesadas pelo fundo desses montes, destruindo corais de água fria e esponjas que levaram séculos para crescer numa única passagem. Como a maior parte dos montes submarinos fica em alto-mar, fora da jurisdição de qualquer país, regular essa pesca depende de acordos internacionais que, na prática, poucos países fiscalizam com rigor.</p>


            <h2>O fundo profundo: planícies, fossas e montanhas</h2>

            <h3>A planície abissal</h3>

            <p>Depois do talude, o fundo se nivela numa extensão plana e vastíssima: a <span class="termo" data-palavra="Planície Abissal" data-definicao="Extensão plana do fundo oceânico entre 3.000 e 6.000 metros de profundidade. Cobre cerca de 40% da superfície do planeta e abriga fontes hidrotermais e nódulos de manganês com alto valor econômico.">planície abissal</span>. Com profundidade entre 3.000 e 6.000 metros, ela cobre cerca de 40% da superfície total da Terra. É a maior feição geológica do planeta e também a menos conhecida. A pressão ali chega a 600 vezes a pressão atmosférica da superfície, temperatura flutua em torno de 2°C e não há luz solar.</p>

            <p>Boa parte do que sabemos sobre esse fundo vem de uma expedição pioneira: entre 1872 e 1876, o navio britânico HMS Challenger percorreu todos os oceanos, jogando cordas com peso para medir profundidade metro por metro, coletando amostras de água, sedimento e organismos. Foi a expedição que provou, pela primeira vez, que existe vida em todas as profundidades oceânicas. Hoje, esse trabalho manual e lentíssimo foi substituído por sonares multifeixe instalados em navios e satélites, que enviam ondas sonoras até o fundo e calculam a profundidade pelo tempo de retorno do eco, a mesma lógica do sensoriamento remoto que você estudou em outra aula, só que usando som em vez de luz, já que ondas eletromagnéticas não atravessam a água do mar.</p>

            <p>Mesmo assim, há vida. Na segunda metade do século XX, a descoberta das <span class="termo" data-palavra="Fontes Hidrotermais" data-definicao="Rachaduras no fundo oceânico por onde água superaquecida a mais de 300°C jorra, rica em minerais. Sustentam ecossistemas inteiros sem luz solar, através da quimiossíntese bacteriana.">fontes hidrotermais</span> (ou fumadores negros) revolucionou a biologia: são rachaduras no fundo oceânico por onde água superaquecida a mais de 300°C jorra, rica em minerais. Em torno dessas fontes, ecossistemas inteiros prosperam sem nenhuma luz solar, sustentados pela quimiossíntese bacteriana. Vermes tubulares de 2 metros, caranguejos albinos e peixes sem olhos vivem num ambiente que antes parecia impossível para a vida. A descoberta foi tão radical que mudou até a busca por vida fora da Terra: hoje, agências espaciais estudam luas geladas como Europa (de Júpiter) e Encélado (de Saturno), que escondem oceanos de água líquida sob crostas de gelo, justamente porque fontes hidrotermais parecidas com as terrestres poderiam sustentar vida ali também, sem depender do Sol.</p>

            <p>A planície abissal também é coberta por <span class="termo" data-palavra="Nódulos Polimetálicos" data-definicao="Concreções ricas em manganês, níquel, cobre e cobalto que se formam no fundo oceânico ao longo de milhões de anos. Alvo de disputa entre mineradoras e ambientalistas por seu valor para baterias e tecnologia.">nódulos polimetálicos</span>: concreções ricas em manganês, níquel, cobre e cobalto que crescem milímetros por milhão de anos. Estima-se que haja trilhões de toneladas desses nódulos apenas no Oceano Pacífico, numa região chamada Zona Clarion-Clipperton, entre o Havaí e o México. Esses metais são essenciais para baterias de carros elétricos e celulares, o que tornou a corrida por eles ainda mais urgente. Em 2021, a pequena ilha-nação de Nauru, no Pacífico, acionou uma regra da ISA que obriga o órgão a aprovar um código de mineração em até dois anos, pressionando para que a exploração comercial comece logo. Cientistas marinhos e várias organizações ambientais pediram uma moratória, argumentando que ainda sabemos pouco demais sobre esses ecossistemas para arriscar destruí-los antes mesmo de catalogá-los.</p>

            <h3>As fossas oceânicas</h3>

            <p>Em alguns pontos da planície, o fundo mergulha ainda mais fundo nas <span class="termo" data-palavra="Fossas Oceânicas" data-definicao="Depressões longas e estreitas no fundo oceânico, formadas pela subducção de uma placa tectônica sob outra. Concentradas no cinturão de fogo do Pacífico, são responsáveis pelos maiores terremotos e tsunamis do planeta.">fossas oceânicas</span>. Elas se formam onde uma placa oceânica mergulha sob outra numa zona de subducção. A Fossa das Marianas, no Pacífico, tem 11.034 metros de profundidade: caberia o Monte Everest inteiro com mais de 2 km sobrando.</p>

            <p>O ponto mais profundo da fossa, chamado Challenger Deep, foi visitado por seres humanos apenas três vezes na história. A primeira, em 1960, quando o oceanógrafo suíço Jacques Piccard e o tenente da Marinha americana Don Walsh desceram 10.912 metros no batiscafo Trieste, uma viagem de quase 5 horas só para descer, e passaram apenas 20 minutos no fundo antes de subir. A segunda só aconteceu 52 anos depois, em 2012, quando o cineasta James Cameron, sozinho num submersível que ele mesmo ajudou a projetar, repetiu o feito e trouxe de volta imagens e amostras que a tecnologia de 1960 não permitia coletar. A terceira foi a de Victor Vescovo, em 2019, mencionada mais à frente nesta aula. Passaram-se mais anos entre essas três descidas do que entre o primeiro voo dos irmãos Wright e a chegada do homem à Lua, um lembrete de como o fundo do mar continua sendo, em muitos sentidos, mais inacessível do que o espaço.</p>

            <p>As fossas não são apenas recordes geográficos. Elas são zonas sísmicas intensas: o atrito entre as placas gera terremotos de grande magnitude, e o deslocamento abrupto do fundo oceânico provoca tsunamis devastadores. O terremoto e tsunami de 2011 no Japão, que destruiu a usina de Fukushima, ocorreu exatamente numa zona de subducção no Pacífico. O <strong>Anel de Fogo do Pacífico</strong>, que concentra 90% dos terremotos mundiais, acompanha o traçado das fossas oceânicas ao redor do oceano.</p>

            <p>O maior terremoto já registrado por instrumentos modernos aconteceu justamente numa dessas zonas: o terremoto do Chile de 1960, de magnitude 9,5, na fronteira entre a placa de Nazca e a placa Sul-Americana, perto da Fossa Peru-Chile. O tremor gerou um tsunami que atravessou todo o Oceano Pacífico e ainda causou mortes no Havaí e no Japão, a mais de 17.000 km de distância do epicentro. É a prova de que o relevo escondido no fundo do mar, quando se move, tem força suficiente para atingir o lado oposto do planeta.</p>


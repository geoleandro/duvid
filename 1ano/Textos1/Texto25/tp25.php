            <h2>Do litoral ao abismo: as zonas do fundo oceânico</h2>

            <h3>A plataforma continental</h3>

            <p>Quando você entra no mar, o fundo vai descendo devagar por um bom trecho antes de cair de vez. Essa faixa rasa, extensão submersa do continente, chama-se <span class="termo" data-palavra="Plataforma Continental" data-definicao="Extensão submersa e suave do continente sob o oceano, com profundidade geralmente menor que 200 metros. Concentra a maior biodiversidade marinha, os principais pesqueiros e os grandes campos de petróleo.">plataforma continental</span>. Ela tem profundidade média inferior a 200 metros e pode se estender por dezenas a centenas de quilômetros mar adentro, dependendo da geologia de cada costa.</p>

            <p>A plataforma abriga a maior concentração de vida marinha do planeta. A luz do sol penetra até o fundo, permitindo a fotossíntese do fitoplâncton, base de toda a cadeia alimentar oceânica. É nessa faixa que vivem corais, manguezais submersos, peixes, crustáceos, moluscos. Não por acaso, é também onde se concentra a pesca mundial: mais de 90% do pescado consumido no planeta vem da plataforma continental.</p>

            <p>Essa fartura de luz explica uma divisão que os oceanógrafos usam para classificar o oceano em camadas verticais. A <strong>zona nerítica</strong> é a coluna de água sobre a plataforma continental, iluminada e rica em nutrientes trazidos pelos rios, onde se concentra a maior parte da pesca. Além da plataforma, a coluna de água em alto-mar se divide em <strong>zona epipelágica</strong> (até 200 metros, com luz suficiente para fotossíntese), <strong>zona mesopelágica</strong> (200 a 1.000 metros, penumbra, sem fotossíntese) e <strong>zona batipelágica</strong> e <strong>abissopelágica</strong>, mais fundo ainda, em escuridão total. Repare que essa classificação descreve a água, não o relevo do fundo, que você já conheceu como plataforma, talude e planície abissal: uma bacia oceânica profunda pode ter, empilhadas acima dela, todas essas camadas de água ao mesmo tempo.</p>

            <p>Para o Brasil, a plataforma tem importância econômica ainda maior. As bacias sedimentares de Campos e Santos, localizadas sobre a plataforma e o talude ao largo do Rio de Janeiro e São Paulo, contêm o <span class="termo" data-palavra="Pré-sal" data-definicao="Petróleo acumulado abaixo de uma espessa camada de sal, no fundo do oceano, a profundidades que podem passar de 7.000 metros contando a lâmina d'água. Descoberto em 2006, tornou o Brasil um dos maiores produtores mundiais de petróleo.">pré-sal</span>: petróleo acumulado abaixo de uma camada de sal que pode chegar a 2.000 metros de espessura. Para chegar até o petróleo, é preciso perfurar primeiro entre 1.500 e 3.000 metros de água do mar e só depois a camada de sal e a rocha, o que soma mais de 7.000 metros de profundidade total em alguns poços, um desafio de engenharia que não existia em nenhuma outra parte do mundo em escala comercial até o Brasil desenvolvê-lo. A descoberta, em 2006, transformou o Brasil em um dos maiores produtores de petróleo do mundo e gerou uma disputa política intensa sobre como distribuir os royalties entre estados e municípios.</p>

            <p>A plataforma continental também é o lar dos recifes de coral, alguns dos ecossistemas mais ricos e mais ameaçados do planeta. No Brasil, o maior complexo recifal do Atlântico Sul fica no Banco de Abrolhos, na Bahia, formado por estruturas únicas em forma de cogumelo chamadas chapeirões. O aquecimento dos oceanos, tema que você já estudou nas aulas sobre mudanças climáticas, provoca o branqueamento dos corais: o aumento da temperatura da água expulsa as algas que vivem dentro do tecido coral e dão a ele cor e boa parte do alimento, deixando o esqueleto de carbonato de cálcio exposto e, se o estresse térmico continuar, levando o recife à morte.</p>


            <h3>A Amazônia Azul</h3>

            <p>O Brasil tem a maior ZEE do Atlântico Sul: mais de 3,5 milhões de km². Com a extensão da plataforma continental aprovada pela ONU, essa área sobe para mais de 4,5 milhões de km², área quase igual à da Amazônia Verde. Por isso o projeto recebeu o nome de <strong>Amazônia Azul</strong>. Nessa região estão o pré-sal, campos de gás natural, jazidas de manganês, cobalto, níquel e terras raras no fundo abissal, além dos principais pesqueiros do Atlântico Sul, uma concentração de riqueza que explica por que o Brasil trata essa faixa de oceano quase como se fosse uma extensão do próprio território nacional, e não apenas um recurso qualquer a ser explorado.</p>

            <p>Essa conquista não aconteceu de uma vez. O Brasil começou a submeter pedidos de extensão da plataforma continental à CLPC em 2004, dividindo o pleito em partes: a região Sul foi aprovada em 2019, e a chamada Margem Equatorial, ao largo do Amapá e do Pará, foi reconhecida pela ONU só em 2025, mais de duas décadas depois do primeiro pedido. Ainda falta a análise de mais um trecho, a Margem Oriental-Meridional. Levar décadas para reconhecer alguns milhões de quilômetros quadrados de oceano mostra como a diplomacia marítima é lenta e como cada centímetro de plataforma reivindicada exige anos de levantamento geológico detalhado para provar, com dados, que aquele pedaço de fundo do mar é mesmo continuação natural do território brasileiro.</p>

            <p>A gestão desse território marítimo é feita pela Marinha do Brasil e envolve desafios enormes: monitorar mais de 4 milhões de km² de oceano com recursos limitados. A pesca ilegal estrangeira é uma preocupação real em todo o Atlântico Sul: em 2018, o pesqueiro chinês Chang Rong 4 colidiu com o atuneiro brasileiro Oceano Pesca I durante uma disputa por um cardume, a mais de 600 km do Rio Grande do Norte, já em águas internacionais. O problema de fundo é que, fora da ZEE, o alto mar não pertence a ninguém: frotas estrangeiras podem pescar livremente bem na borda das 200 milhas, sem cometer nenhum crime, e a fiscalização brasileira só pode agir se elas de fato cruzarem a linha. Um relatório da ONG Oceana, de 2021, mapeou mais de 400 embarcações chinesas atuando de forma parecida na fronteira da ZEE argentina, um retrato do mesmo tipo de pressão pesqueira que o Brasil enfrenta em sua própria costa.</p>

            <h3>As disputas no Mar do Sul da China</h3>

            <p>O caso brasileiro não é único. No Mar do Sul da China, seis países reivindicam soberania sobre as mesmas ilhas, recifes e plataformas: China, Vietnã, Filipinas, Malásia, Brunei e Taiwan. A China construiu ilhas artificiais sobre recifes para ampliar sua presença e reivindicar ZEEs maiores, em clara violação do UNCLOS. Em 2016, um tribunal de arbitragem internacional em Haia decidiu a favor das Filipinas e considerou ilegais as reivindicações históricas chinesas sobre a maior parte da região, mas a China simplesmente ignorou a decisão e manteve suas bases nas ilhas artificiais, mostrando os limites reais do UNCLOS quando a potência que descumpre a lei também é uma das que ajudam a fazer cumpri-la. O conflito combina soberania, recursos de petróleo estimados em 125 bilhões de barris, rotas comerciais estratégicas e projeção militar. É um dos pontos mais tensos da geopolítica atual e vai se intensificar com o aumento da demanda por recursos do fundo oceânico.</p>

            <h3>A corrida pelo Polo Norte</h3>

            <p>No extremo oposto do planeta, o degelo do Ártico provocado pelo aquecimento global, tema que você já estudou em outra aula deste módulo, está abrindo uma disputa parecida. Em 2007, um submersível russo desceu cerca de 4.200 metros até o fundo do Oceano Ártico e fincou uma bandeira de titânio exatamente sob o Polo Norte, um gesto simbólico para reforçar a reivindicação da Rússia sobre a Cordilheira de Lomonosov, uma cadeia montanhosa submarina que o país argumenta ser extensão geológica de seu próprio território, seguindo a mesma lógica de plataforma continental estendida que o Brasil usa na Amazônia Azul. Canadá e Dinamarca (por causa da Groenlândia) reivindicam a mesma cordilheira, e a região é vista como rica em petróleo, gás e novas rotas de navegação, que só existem porque o gelo que antes cobria o Ártico o ano inteiro está derretendo mais cedo e mais rápido a cada década.</p>


            <h3>A poluição agrícola</h3>

            <p>No Brasil rural, os principais vilões são os agrotóxicos e o excesso de fertilizantes. O país é o maior consumidor de agrotóxicos do mundo: mais de 600 mil toneladas por ano. Parte dessas substâncias escoa com as chuvas até os rios e aquíferos, contaminando a água usada para beber e irrigar. Pesquisa da Fiocruz identificou agrotóxicos na urina de 100% das crianças avaliadas em municípios do Mato Grosso onde o cultivo de soja é intensivo, um resultado que mostra como a contaminação não fica restrita ao campo: ela viaja pela água, pelo ar e pela cadeia alimentar até alcançar quem nunca pisou numa lavoura.</p>

            <p>Outro problema grave é a <strong>eutrofização</strong>: o excesso de nitrogênio e fósforo dos fertilizantes que chega aos rios e lagos estimula o crescimento excessivo de algas. Quando as algas morrem e se decompõem, consomem todo o oxigênio dissolvido na água, matando peixes e outros organismos aquáticos. Lagos e represas ao redor de áreas agrícolas intensivas no Brasil apresentam episódios recorrentes de eutrofização, prejudicando o abastecimento e a pesca. Em casos extremos, a explosão de cianobactérias (algas azuis) libera toxinas que tornam a água imprópria até para o contato humano, obrigando estações de tratamento a fechar temporariamente a captação em represas que abastecem cidades inteiras.</p>

            <h3>Poluição por rejeitos de mineração</h3>

            <p>A mineração produz rejeitos que precisam ser armazenados em barragens. Quando essas estruturas falham, o impacto é catastrófico e irreversível na escala humana. Os rejeitos de Mariana cobriram com lama tóxica mais de 660 km do Rio Doce. Em novembro de 2025, dez anos depois do rompimento, Governo Federal, Minas Gerais, Espírito Santo e as empresas responsáveis assinaram o Novo Acordo do Rio Doce, no valor de R$ 170 bilhões, prevendo a restauração florestal de 40 mil hectares de mata ciliar ao longo da bacia. Mesmo assim, o ecossistema aquático segue longe da recuperação plena, e famílias atingidas continuam esperando por reparação integral uma década depois da tragédia.</p>

            <h3>Garimpo ilegal e mercúrio</h3>

            <p>Outra fonte de contaminação, distinta das barragens de rejeito, é o garimpo ilegal de ouro em rios da Amazônia. Para separar o ouro do sedimento, garimpeiros usam mercúrio, que se transforma em metilmercúrio ao entrar na água e sofre <span class="termo" data-palavra="Bioacumulação" data-definicao="Processo pelo qual substâncias tóxicas, como metais pesados, se acumulam progressivamente nos tecidos dos seres vivos ao longo da cadeia alimentar, atingindo as maiores concentrações nos predadores no topo, incluindo o ser humano.">bioacumulação</span> ao longo da cadeia alimentar: peixes pequenos absorvem pouco, peixes grandes que os comem acumulam mais, e quem come esses peixes grandes recebe a dose mais concentrada de todas. Estudos da Fiocruz encontraram metilmercúrio em praticamente toda a população Yanomami testada em Roraima, associado a danos neurológicos, sobretudo em crianças. Entre 2024 e o início de 2026, uma intensa operação de fiscalização reduziu a área de garimpo ativo em terra Yanomami em mais de 98%, mas o mercúrio já lançado nos rios continua circulando no ambiente e nos peixes por muitos anos, mesmo depois que o garimpo para.</p>


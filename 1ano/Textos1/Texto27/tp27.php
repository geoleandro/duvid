            <h3>Água como arma: o Tratado das Águas do Indo</h3>

            <p>Quando dois países dividem a mesma bacia, a água pode virar instrumento de pressão política, não só recurso econômico. Em 1960, Índia e Paquistão assinaram o Tratado das Águas do Indo, mediado pelo Banco Mundial, dividindo os seis rios do sistema Indo entre os dois países. Apesar de décadas de tensão e até guerras entre os dois vizinhos, o tratado resistiu intacto por 65 anos, sendo citado como um raro exemplo de cooperação hídrica bem-sucedida entre rivais históricos.</p>

            <p>Isso mudou em abril de 2025. Depois de um atentado terrorista na Caxemira que matou 26 turistas, a Índia suspendeu unilateralmente o tratado, alegando que dois dos atacantes tinham ligação com o Paquistão. O ministro indiano da água declarou publicamente que "nenhuma gota da água do rio Indo" deveria mais chegar ao território paquistanês. Na prática, a Índia não tem estrutura para interromper o fluxo de imediato, mas o gesto político foi claro: um país que destina mais de 90% da água do Indo à irrigação, sustentando cerca de 16 milhões de hectares agrícolas, viu a água que sustenta sua agricultura ser usada como ameaça. O episódio mostra que mesmo tratados considerados modelos de sucesso, como o do Indo, continuam reféns da política a qualquer momento.</p>

            <h3>A privatização da água</h3>

            <p>Um debate crescente no mundo envolve a privatização dos serviços de água e saneamento. Defensores argumentam que empresas privadas são mais eficientes e investem mais em infraestrutura. Críticos apontam que a lógica do lucro é incompatível com um serviço essencial: empresas privadas tendem a priorizar áreas rentáveis (bairros ricos) e negligenciar periferias e zonas rurais. Na Bolívia, em 2000, a privatização do sistema de água de Cochabamba gerou tarifas tão altas que a população se revoltou em protestos que ficaram conhecidos como a "Guerra da Água". O governo reverteu a privatização após dias de confronto. No Brasil, o Marco Legal do Saneamento (2020) abriu o setor para concessões privadas, exigindo que 99% da população urbana tenha água tratada e 90% tenha coleta de esgoto até 2033. Leilões de concessão em estados como Rio de Janeiro, Alagoas e Ceará atraíram bilhões em investimento privado nos anos seguintes, mas municípios pequenos e regiões de baixa renda seguem menos atrativos para as empresas, repetindo em menor escala o padrão observado em Cochabamba.</p>

            <h3>O Objetivo 6 da Agenda 2030</h3>

            <p>Em 2015, a ONU estabeleceu 17 Objetivos de Desenvolvimento Sustentável (ODS) a serem alcançados até 2030. O <strong>ODS 6</strong> trata especificamente de "água potável e saneamento", com metas como garantir acesso universal e equitativo à água potável, alcançar saneamento adequado para todos, melhorar a qualidade da água reduzindo a poluição e proteger e restaurar ecossistemas relacionados à água, como as matas ciliares e os aquíferos que você estudou nesta aula. O Brasil está atrasado em relação à maioria dessas metas, e organizações internacionais avaliam que, no ritmo atual de investimento, o país não vai cumprir o ODS 6 dentro do prazo estabelecido, deixando a promessa de "água para todos até 2030" como uma meta cada vez mais distante da realidade de milhões de brasileiros.</p>


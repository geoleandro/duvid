            <h2>Como os rios são contaminados</h2>

            <h3>As fontes de poluição</h3>

            <p>A poluição hídrica tem origens diversas e pode ser classificada em dois grandes grupos. As <strong>fontes pontuais</strong> são as que lançam poluentes num ponto identificável: canos de esgoto, saídas de indústrias, tubulações de frigoríficos. As <strong>fontes difusas</strong> são mais difíceis de controlar: agrotóxicos e fertilizantes que escorrem das lavouras com a chuva, sedimentos de áreas desmatadas, dejetos de criações de animais espalhados pela bacia.</p>

            <p>No Brasil urbano, o principal poluente dos rios é o esgoto doméstico sem tratamento. Fezes humanas carregam bactérias, vírus e parasitas que causam doenças como cólera, febre tifoide, hepatite A e leptospirose. O Brasil coleta apenas 58% do esgoto gerado e trata pouco mais da metade do que coleta, deixando a maior parte da população sem tratamento completo do que produz todos os dias. O resultado: rios como o Tietê (SP), o Guandu (RJ) e inúmeros outros urbanos são essencialmente esgotos a céu aberto em boa parte de seus cursos.</p>

            <p>O custo dessa falta de saneamento aparece nas estatísticas de saúde pública. Em 2024, o Brasil registrou mais de 344 mil internações hospitalares por doenças relacionadas a saneamento inadequado, quase metade delas causadas por doenças de transmissão feco-oral como diarreia, hepatite A e febre tifoide, num gasto de R$ 174 milhões para o SUS. Um quinto dessas internações foi de crianças entre 0 e 4 anos, a faixa etária mais vulnerável a esse tipo de doença. Estudos do setor estimam que universalizar o saneamento básico reduziria essas internações em cerca de 70% em poucos anos, gerando economia de dezenas de milhões de reais por ano em atendimentos que hoje são inteiramente evitáveis.</p>

            <p>Para medir esse tipo de poluição, cientistas e órgãos ambientais usam indicadores técnicos. A <span class="termo" data-palavra="Demanda Bioquímica de Oxigênio (DBO)" data-definicao="Indicador que mede a quantidade de oxigênio que as bactérias consomem para decompor a matéria orgânica presente na água. Quanto mais esgoto ou matéria orgânica um rio recebe, maior a DBO e menor o oxigênio disponível para peixes e outros seres vivos.">Demanda Bioquímica de Oxigênio (DBO)</span> mede quanto oxigênio as bactérias consomem para decompor a matéria orgânica despejada num rio: quanto mais esgoto, maior a DBO e menor o oxigênio que sobra para a vida aquática. Esse e outros parâmetros (oxigênio dissolvido, presença de coliformes fecais, turbidez, pH) são combinados no <span class="termo" data-palavra="Índice de Qualidade da Água (IQA)" data-definicao="Indicador criado pela Agência Nacional de Águas que combina nove parâmetros (como oxigênio dissolvido, DBO e coliformes fecais) numa nota de 0 a 100 para classificar a qualidade de um rio, de péssima a ótima.">Índice de Qualidade da Água (IQA)</span>, usado pela Agência Nacional de Águas para classificar rios brasileiros numa escala de 0 a 100, de péssima a ótima qualidade. Trechos urbanos do Tietê e do Guandu costumam registrar os piores índices do país havia décadas.</p>


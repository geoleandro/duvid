            <h2>Quem usa, quem polui e quem paga o preço</h2>

            <h3>Os principais usos da água no Brasil</h3>

            <p>No Brasil, a agricultura irrigada consome cerca de 67% de toda a água retirada dos rios e aquíferos. As indústrias consomem aproximadamente 9% e o abastecimento urbano, 23%. Esses números revelam uma assimetria importante: o setor que mais consome é também o que mais polui com fertilizantes e agrotóxicos, enquanto o setor que menos consome (urbano) é o que mais concentra pessoas e pressão política por saneamento.</p>

            <p>Dentro da irrigação, o perfil é ainda mais concentrado. Grandes propriedades rurais voltadas para exportação (soja, cana-de-açúcar, arroz) respondem pela maior parte do consumo. Pequenos agricultores e comunidades tradicionais, que dependem dos mesmos rios, competem em condições desiguais por um recurso que frequentemente está diminuindo ou degradado pela montante.</p>

            <h3>Pegada hídrica: a água escondida em cada produto</h3>

            <p>Quando você come um hambúrguer ou compra uma calça jeans, também está consumindo água, só que de forma invisível. A <span class="termo" data-palavra="Pegada Hídrica" data-definicao="Volume total de água doce usado, direta ou indiretamente, para produzir um bem ou serviço, contabilizando toda a cadeia produtiva, da lavoura de ração animal até o produto final na prateleira.">pegada hídrica</span> mede o volume total de água usado, direta ou indiretamente, para produzir um bem, considerando toda a cadeia: a água que a planta bebeu, a que lavou o equipamento, a que os animais consumiram. Produzir 1 quilo de carne bovina consome, em média, cerca de 15 mil litros de água; 1 quilo de arroz, cerca de 2,5 mil litros; uma calça jeans de algodão, mais de 7 mil litros, considerando o cultivo da fibra. Esse conceito é chamado de <strong>água virtual</strong>: quando o Brasil exporta soja ou carne, está exportando, embutida no produto, uma quantidade enorme de água que não vai voltar para a bacia de origem.</p>

            <h3>Estresse hídrico: quando falta água para todos</h3>

            <p>Alguns lugares do planeta sofrem de <span class="termo" data-palavra="Estresse Hídrico" data-definicao="Situação em que a demanda por água de uma população ou região se aproxima ou ultrapassa a disponibilidade de água doce renovável. Pode ser físico, quando a água simplesmente não existe em quantidade suficiente, ou econômico, quando existe água mas falta infraestrutura para captá-la e distribuí-la.">estresse hídrico</span>: quando a demanda por água se aproxima ou ultrapassa a disponibilidade renovável de uma região. Os hidrólogos costumam separar dois tipos. O estresse físico ocorre onde a água simplesmente não existe em quantidade suficiente, como no Oriente Médio ou no norte da África. O estresse econômico ocorre onde a água até existe, mas falta dinheiro e infraestrutura para captá-la, tratá-la e levá-la até quem precisa, situação comum em partes da África Subsaariana e também em periferias urbanas brasileiras que têm rios próximos, mas não têm rede de distribuição. Uma região pode ter chuva abundante e ainda assim sofrer estresse hídrico, se a gestão for ruim o suficiente.</p>

            <h3>O caso do Mar de Aral</h3>

            <p>O exemplo mais dramático de colapso hídrico por uso agrícola excessivo é o <strong>Mar de Aral</strong>, na Ásia Central. Nos anos 1960, a União Soviética desviou os dois rios que abasteciam o mar para irrigar algodão no deserto. Em cinco décadas, o que era o quarto maior lago do mundo perdeu mais de 90% de seu volume. Cidades que eram portos ficaram a centenas de quilômetros da água. Pescadores perderam seus meios de vida. O sal e os pesticidas do fundo exposto são carregados pelo vento e causam doenças respiratórias e câncer nas populações locais. O clima da região também mudou: sem a massa de água para regular a temperatura, os verões ficaram mais quentes e os invernos mais frios. O Mar de Aral é hoje símbolo global do que acontece quando o interesse econômico de curto prazo prevalece sobre a gestão sustentável da água.</p>


            <h3>O Código Florestal e suas brechas</h3>

            <p>O Código Florestal Brasileiro (Lei 12.651/2012) define faixas mínimas de mata ciliar obrigatória ao longo de rios de diferentes tamanhos: 30 metros para rios com até 10 metros de largura, chegando a 500 metros para grandes rios. O problema é que o mesmo Código criou a figura das "Áreas de Uso Restrito" e anistiou produtores que desmataram antes de 2008 do dever de recuperação integral.</p>

            <p>O resultado prático: o Brasil perdeu mais de 40% de suas matas ciliares originais, segundo o MapBiomas. As regiões com maior déficit são exatamente as mais intensamente agrícolas: Cerrado, Mata Atlântica e sul da Amazônia. Recuperar essas áreas custa bilhões e leva décadas. Não recuperar custa ainda mais, distribuindo o custo sobre as populações que dependem dos rios, geralmente as mesmas que menos se beneficiaram economicamente do desmatamento que causou o problema em primeiro lugar.</p>

            <h3>Contaminação do solo e dos aquíferos</h3>

            <p>A <span class="termo" data-palavra="Lixiviação" data-definicao="Processo pelo qual a água da chuva carrega substâncias dissolvidas do solo para camadas mais profundas, podendo contaminar os lençóis freáticos e aquíferos com agrotóxicos, metais pesados e fertilizantes.">lixiviação</span> é o processo pelo qual substâncias do solo são arrastadas pela chuva para as camadas mais profundas, contaminando os aquíferos. Uma vez que agrotóxicos ou metais pesados entram no lençol freático, são quase impossíveis de remover. Comunidades que dependem de poços artesianos em regiões de agricultura intensiva vivem com o risco constante de consumir água contaminada sem saber, pois os efeitos de muitos agrotóxicos são crônicos e só aparecem anos depois.</p>

            <h3>Uma saída parcial: a água de reuso</h3>

            <p>Diante da escassez e da poluição, cidades e indústrias têm investido na <span class="termo" data-palavra="Água de Reuso" data-definicao="Água residual (esgoto ou efluente industrial) tratada para ser reaproveitada em usos que não exigem qualidade potável, como irrigação, lavagem de ruas ou processos industriais, reduzindo a retirada de água nova dos rios.">água de reuso</span>: o aproveitamento de água já usada, tratada em graus variados, para fins que não exigem qualidade potável, como irrigação de jardins públicos, lavagem de ruas, resfriamento industrial ou descarga de vasos sanitários em prédios comerciais. Israel é o caso mundial mais avançado, reaproveitando mais de 85% do seu esgoto tratado, a maior parte para irrigação agrícola. No Brasil, o reuso ainda é pouco praticado fora de grandes indústrias, mas cresce como resposta às crises de abastecimento das grandes cidades. Não resolve a poluição na origem, mas reduz a pressão sobre os mananciais que ainda estão preservados.</p>

